# -*- coding: utf-8 -*-
"""
Б1. Эталон исходника.
Вход:  путь к PDF (DOCX — отдельная ветка)
Выход: 00_слой.jsonl, 00_текст.txt, 00_мета.json

Один индекс документа: страница = markdown-разбор pymupdf4llm без разметки.
Таблицы приходят разобранными в том же потоке, отдельной веткой не идут.
Страница без слоя — OCR только её, если движок есть.
00_текст.txt — склейка слоя, символ в символ. Колонтитулы снимаются,
юникод NFC; строки абзаца не склеиваются. Суждений нет.
"""
import sys, os, re, json, unicodedata, importlib.util
from collections import Counter

_сп = importlib.util.spec_from_file_location(
    "общее", os.path.join(os.path.dirname(os.path.abspath(__file__)), "общее.py"))
_общее = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(_общее)

ПОРОГ_OCR = 0.80
ПОРОГ_КОЛОНТИТУЛА = 0.30
ПУСТАЯ = 100


# Разметка, которую ставит pymupdf4llm: `**жирный**`, `_курсив_`, html-теги,
# заголовки, рамка таблицы. В эталоне ей не место: Б4 сверяет цитату знак в
# знак, а модель цитирует текст, а не вёрстку — `SRMR<sup>between</sup>` от
# неё не дождаться. На 133 забракованных цитатах прогона чистка сняла 9
# поломок из 16 и добавила 6 находок.
ПЕРЕНОС = re.compile(r"<br\s*/?>", re.I)      # разрыв строки внутри ячейки таблицы
РАЗМЕТКА = re.compile(
    r"</?(?:sup|sub|u|b|i|em|strong|mark)\s*/?>|\*\*|~~"
    r"|(?<![0-9A-Za-zА-Яа-я])_|_(?![0-9A-Za-zА-Яа-я])"
    r"|^#{1,6} +|^ *\|[-: |]+\|$|^-{3,}$", re.M)

# Курсив у pymupdf4llm бывает обложен пробелами: `(n = 73)` приходит как
# `( _n_ = 73)`. Снять один маркер мало — без этого пробел остаётся в эталоне,
# а модель цитирует `(n = 73)`, как в PDF, и Б4 бракует дословную цитату.
ПРОБЕЛ_ПОСЛЕ_СКОБКИ = re.compile(r"(?<=[(\[])[ \t]+")
ПРОБЕЛ_ПЕРЕД_СКОБКОЙ = re.compile(r"[ \t]+(?=[)\]])")

# Строка-разделитель шапки: ровно одна на таблицу, считать дешевле find_tables.
РАЗДЕЛИТЕЛЬ_ТАБЛИЦЫ = re.compile(r"^\|-+", re.M)


def снять_разметку(md):
    """Текст markdown-разбора без самой разметки: содержимое таблиц остаётся,
    рамка — нет."""
    т = РАЗМЕТКА.sub("", ПЕРЕНОС.sub("\n", md)).replace("|", " ")
    return ПРОБЕЛ_ПЕРЕД_СКОБКОЙ.sub("", ПРОБЕЛ_ПОСЛЕ_СКОБКИ.sub("", т))


def страницы_markdown(doc):
    """[(текст без разметки, сколько таблиц)] по странице документа."""
    pymupdf4llm = _общее.библиотека("pymupdf4llm", "b1")
    чанки = pymupdf4llm.to_markdown(doc, page_chunks=True, show_progress=False)
    return [(снять_разметку(ч["text"]),
             len(РАЗДЕЛИТЕЛЬ_ТАБЛИЦЫ.findall(ч["text"]))) for ч in чанки]


def ocr_страницы(page):
    """Текстовый слой пуст — пробуем OCR страницы. Нет tesseract — пусто."""
    try:
        tp = page.get_textpage_ocr(language="eng+rus", dpi=140)
        return (page.get_text("text", textpage=tp) or "").strip()
    except Exception:
        return ""


# Числовая ссылка на литературу посреди фразы: `analyses [35] and`,
# `practice [31,34]`, `[3–5]`. Модель её в цитату не переносит, и Б4 бракует
# дословную в остальном цитату. Интервал `[-.95; -.15]` сюда не попадает.
ССЫЛКА_НА_ЛИТЕРАТУРУ = re.compile(r"[ \t]*\[\d{1,3}(?:[ \t]*[,–-][ \t]*\d{1,3})*\]")


def эталон(текст):
    """NFC и невидимые знаки. Строки не склеивать: это уже не тот эталон."""
    текст = unicodedata.normalize("NFC", текст or "")
    текст = (текст.replace("\u00ad", "").replace("\ufeff", "")
                  .replace("\xa0", " ").replace("\u2011", "-"))
    текст = ССЫЛКА_НА_ЛИТЕРАТУРУ.sub("", текст)
    текст = re.sub(r"[ \t]+", " ", текст)
    текст = re.sub(r"\n{3,}", "\n\n", текст)
    return текст.strip()


def читать_pdf(путь):
    """Страницы для И1: разбор как есть, без OCR и без нормализации."""
    pymupdf = _общее.библиотека("pymupdf", "b1")
    doc = pymupdf.open(путь)
    страницы = [т for т, _ in страницы_markdown(doc)]
    мета = dict(doc.metadata or {})
    doc.close()
    return страницы, мета


def слой_pdf(путь):
    pymupdf = _общее.библиотека("pymupdf", "b1")
    doc = pymupdf.open(путь)
    слой, мета = [], dict(doc.metadata or {})
    for i, (сырой, таблиц) in enumerate(страницы_markdown(doc)):
        текст, ocr = эталон(сырой), False
        if len(текст) < ПУСТАЯ and not таблиц:
            добыча = эталон(ocr_страницы(doc[i]))
            if добыча:
                текст, ocr = добыча, True
        слой.append({"страница": i + 1, "текст": текст, "таблиц": таблиц, "ocr": ocr})
    doc.close()
    return слой, мета


def читать_docx(путь):
    """Страницы для И1: линейный текст документа."""
    Document = _общее.библиотека("docx", "b1").Document
    d = Document(путь)
    текст = "\n".join(p.text for p in d.paragraphs)
    return [текст], {}


def слой_docx(путь):
    страницы, мета = читать_docx(путь)
    return [{"страница": 1, "текст": эталон(страницы[0]), "таблиц": 0, "ocr": False}], мета


ЧИТАТЕЛИ = {".pdf": читать_pdf, ".docx": читать_docx}


def плотность(страницы):
    если_есть = sum(1 for s in страницы if len((s or "").strip()) > ПУСТАЯ)
    return если_есть / max(1, len(страницы))


def снять_колонтитулы(страницы):
    кандидаты = Counter()
    for s in страницы:
        строки = [l.strip() for l in s.split("\n") if l.strip()]
        for l in строки[:2] + строки[-2:]:
            без_цифр = re.sub(r"\d+", "#", l)
            if len(без_цифр) < 120:
                кандидаты[без_цифр] += 1
    порог = max(3, int(len(страницы) * ПОРОГ_КОЛОНТИТУЛА))
    мусор = {k for k, v in кандидаты.items() if v >= порог}
    чистые = []
    for s in страницы:
        строки = [l for l in s.split("\n")
                  if re.sub(r"\d+", "#", l.strip()) not in мусор]
        чистые.append("\n".join(строки).strip())
    return чистые, sorted(мусор)


def склеить_слой(записи):
    """Линейный текст и смещения: срез [начало:начало+знаков] == текст страницы."""
    части = [з["текст"] for з in записи]
    текст = "\n\n".join(части)
    курсор = 0
    for i, з in enumerate(записи):
        if i:
            курсор += 2
        з["начало"] = курсор
        з["знаков"] = len(з["текст"])
        курсор += з["знаков"]
    return текст, записи


def main(путь_исходника, папка_выхода):
    путь_исходника = _общее.путь_исходника(путь_исходника, "b1")
    расш = os.path.splitext(путь_исходника)[1].lower()
    if расш not in (".pdf", ".docx"):
        raise SystemExit(f"нет читателя для {расш}")

    if расш == ".pdf":
        записи, мета_файла = слой_pdf(путь_исходника)
    else:
        записи, мета_файла = слой_docx(путь_исходника)

    сырые = [з["текст"] for з in записи]
    пл = плотность(сырые)
    чистые, колонтитулы = снять_колонтитулы(сырые)
    for з, t in zip(записи, чистые):
        з["текст"] = t
    текст, записи = склеить_слой(записи)

    позиции = [{"страница": з["страница"], "начало": з["начало"], "знаков": з["знаков"]}
               for з in записи]
    мета = {
        "исходник": os.path.basename(путь_исходника),
        "путь_в_корпусе": _общее.в_корпусе(путь_исходника),
        "канал": _общее.канал(путь_исходника),
        "формат": расш.lstrip("."),
        "страниц": len(записи),
        "знаков": len(текст),
        "слов": len(текст.split()),
        "плотность_текста": round(пл, 3),
        "нужен_ocr": пл < ПОРОГ_OCR,
        "страниц_ocr": sum(1 for з in записи if з.get("ocr")),
        "таблиц": sum(з.get("таблиц") or 0 for з in записи),
        "снятые_колонтитулы": колонтитулы,
        "страницы": позиции,
        "из_файла": {k: v for k, v in мета_файла.items() if v},
    }

    os.makedirs(папка_выхода, exist_ok=True)
    with open(os.path.join(папка_выхода, "00_слой.jsonl"), "w", encoding="utf-8") as f:
        for з in записи:
            f.write(json.dumps(з, ensure_ascii=False) + "\n")
    open(os.path.join(папка_выхода, "00_текст.txt"), "w", encoding="utf-8").write(текст)
    json.dump(мета, open(os.path.join(папка_выхода, "00_мета.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    print(json.dumps({k: v for k, v in мета.items() if k != "страницы"},
                     ensure_ascii=False, indent=2))
    for з in записи:
        if текст[з["начало"]:з["начало"] + з["знаков"]] != з["текст"]:
            print("слой расходится с 00_текст — файл записан, координаты страниц неверны")
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1], sys.argv[2]))
