# -*- coding: utf-8 -*-
"""
Б2. Дерево структуры.
Вход:  <папка>/00_текст.txt, <папка>/00_мета.json
Выход: <папка>/01_структура.json — плоский список разделов с позициями в тексте.

Три источника заголовков, по убыванию надёжности:
  1) закладки/оглавление PDF (если были) — сюда не доходят, берём из мета;
  2) строки, похожие на заголовок (короткие, без точки в конце, часто нумерованные);
  3) fallback — деление на равные части по абзацам.
Скрипт НЕ решает, о чём раздел. Только границы.
"""
import sys, os, re, json, importlib.util


def _общее():
    сп = importlib.util.spec_from_file_location(
        "общее", os.path.join(os.path.dirname(os.path.abspath(__file__)), "общее.py"))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м

# Служебное опознаётся приметами, а не заголовком, и ошибка приметы молча уносит
# содержание. Два случая, в которых стоит посмотреть глазами.
ПОРОГ_ТРЕВОГИ_СЛУЖЕБНОГО = 0.20   # доля текста, помеченная служебной
ХВОСТ = 0.7                       # служебное обычно лежит после этой отметки

МИН_РАЗДЕЛ = 1200      # знаков; короче — приклеиваем к предыдущему
МАКС_РАЗДЕЛ = 40000    # знаков; длиннее — режем принудительно
ЦЕЛЬ_FALLBACK = 12000  # размер части, когда заголовков нет

СЛОВАРНЫЙ_ЗАГОЛОВОК = re.compile(
    r"^(Глава|ГЛАВА|Часть|ЧАСТЬ|Раздел|Приложение|Введение|Заключение"
    r"|Литература|Список литературы|Библиография|Примечания|Указатель|Содержание"
    r"|Chapter|Part|Section|Introduction|Conclusion"
    r"|References|Bibliography|Appendix|Notes|Index|Contents)\b.{0,90}$")

НУМЕРОВАННЫЙ_ЗАГОЛОВОК = re.compile(r"^(\d{1,2})(?:\.\d{1,2})?[\.\)]?\s+\S.{0,80}$")


def похоже_на_заголовок(строка):
    """3 — словарный заголовок, 4 — нумерованный (проверяется отдельно, см.
    найти_заголовки), 2 — версальная строка, 0 — не заголовок."""
    s = строка.strip()
    if not (3 <= len(s) <= 100):
        return 0
    if s.endswith((".", ",", ";", ":")) and not re.match(r"^\d", s):
        return 0
    if СЛОВАРНЫЙ_ЗАГОЛОВОК.match(s):
        return 3
    if НУМЕРОВАННЫЙ_ЗАГОЛОВОК.match(s):
        return 4
    # ВЕРСАЛЬНАЯ СТРОКА
    буквы = [c for c in s if c.isalpha()]
    if len(буквы) >= 6 and all(c.isupper() for c in буквы):
        return 2
    return 0


МИН_ОХВАТ = 0.5   # доля документа между первым и последним заголовком ряда


def восходящий_ряд(кандидаты, длина_текста):
    """Нумерация раздела идёт по документу вверх, начинается с единицы и
    покрывает документ. Пункты списка, ячейки таблицы и подписи к рисункам тоже
    нумерованы: их нумерация либо сбрасывается, либо укладывается в один
    небольшой кусок текста. Поэтому берётся самый длинный строго возрастающий
    ряд от единицы, и он принимается только если растянут по документу.

    Одного возрастания мало: перечень «12 признаков старения» — идеальный ряд
    1..12, но весь он лежит в 8–16% документа, и приняв его за структуру,
    скрипт теряет настоящие главы."""
    лучший = []
    for старт in range(len(кандидаты)):
        if кандидаты[старт]["номер"] != 1:
            continue
        ряд, последний = [кандидаты[старт]], 1
        for к in кандидаты[старт + 1:]:
            if к["номер"] == последний + 1:
                ряд.append(к); последний = к["номер"]
        if len(ряд) > len(лучший):
            лучший = ряд
    if not лучший:
        return []
    охват = (лучший[-1]["начало"] - лучший[0]["начало"]) / max(1, длина_текста)
    return лучший if охват >= МИН_ОХВАТ else []


МИН_ЯВНЫХ = 5   # столько явных заголовков — и слабый сигнал (ВЕРСАЛЬ) не нужен


def найти_заголовки(текст):
    """Три класса доказательств: словарные заголовки (Глава/Часть/References) —
    вес 3, нумерованные — вес 4, но только те, чья нумерация складывается в
    восходящий ряд; версальные строки — вес 2. Если явных (3 и 4) достаточно,
    слабый класс отбрасывается целиком: иначе подписи к рисункам и навигация
    лезут в оглавление."""
    найдено = []
    курсор = 0
    for строка in текст.split("\n"):
        вес = похоже_на_заголовок(строка)
        if вес:
            з = {"заголовок": строка.strip(), "начало": курсор, "вес": вес}
            if вес == 4:
                з["номер"] = int(НУМЕРОВАННЫЙ_ЗАГОЛОВОК.match(з["заголовок"]).group(1))
            найдено.append(з)
        курсор += len(строка) + 1

    нумерованные = восходящий_ряд([з for з in найдено if з["вес"] == 4], len(текст))
    if len(нумерованные) < МИН_ЯВНЫХ:
        нумерованные = []
    for з in нумерованные:
        з["вес"] = 3
    отброшены = {id(з) for з in найдено if з["вес"] == 4}
    найдено = [з for з in найдено if id(з) not in отброшены]

    явных = [з for з in найдено if з["вес"] == 3]
    return явных if len(явных) >= МИН_ЯВНЫХ else найдено


def уровень(заголовок):
    if re.match(r"^(Часть|ЧАСТЬ|Part)\b", заголовок):
        return 1
    if re.match(r"^\d{1,2}\.\d{1,2}", заголовок):
        return 3
    return 2


def собрать_разделы(текст, заголовки):
    if not заголовки:
        return нарезать_равномерно(текст)
    разделы = []
    for i, з in enumerate(заголовки):
        конец = заголовки[i + 1]["начало"] if i + 1 < len(заголовки) else len(текст)
        разделы.append({
            "заголовок": з["заголовок"],
            "уровень": уровень(з["заголовок"]),
            "начало": з["начало"],
            "конец": конец,
        })
    # хвост до первого заголовка
    if заголовки[0]["начало"] > МИН_РАЗДЕЛ:
        разделы.insert(0, {"заголовок": "[начало документа]", "уровень": 2,
                           "начало": 0, "конец": заголовки[0]["начало"]})
    return разделы


def нарезать_равномерно(текст, цель=ЦЕЛЬ_FALLBACK):
    """Fallback: заголовков нет. Режем по абзацам, набирая куски ~цель знаков."""
    абзацы = [m for m in re.finditer(r"[^\n]+(?:\n(?!\n)[^\n]+)*", текст)]
    разделы, начало, набрано, n = [], 0, 0, 1
    for a in абзацы:
        набрано = a.end() - начало
        if набрано >= цель:
            разделы.append({"заголовок": f"[часть {n}]", "уровень": 2,
                            "начало": начало, "конец": a.end()})
            начало, n = a.end(), n + 1
    if начало < len(текст):
        разделы.append({"заголовок": f"[часть {n}]", "уровень": 2,
                        "начало": начало, "конец": len(текст)})
    return разделы


def склеить_мелкие(разделы, текст):
    """Мелкие разделы накапливаются в группу, пока группа не дорастёт до МИН_РАЗДЕЛ,
    и только потом закрывается. Без этого документ с частыми короткими заголовками
    (гайд, слайды, справочник) склеивается в один раздел на весь текст: первая
    группа набирает размер и продолжает поглощать всё подряд."""
    итог = []
    for р in разделы:
        длина = р["конец"] - р["начало"]
        предыдущий_мал = итог and (итог[-1]["конец"] - итог[-1]["начало"]) < МИН_РАЗДЕЛ
        if итог and длина < МИН_РАЗДЕЛ and предыдущий_мал:
            итог[-1]["конец"] = р["конец"]
            итог[-1].setdefault("вошли", [итог[-1]["заголовок"]]).append(р["заголовок"])
        elif итог and длина < МИН_РАЗДЕЛ and not предыдущий_мал:
            итог.append(dict(р))          # начинаем новую группу с этого мелкого
        else:
            итог.append(dict(р))
    for р in итог:
        вошли = р.pop("вошли", None)
        if вошли:
            р["заголовок"] = f"{вошли[0]} … {вошли[-1]}"
            р["склеено_разделов"] = len(вошли)
    return итог


def разрезать_крупные(разделы, текст):
    итог = []
    for р in разделы:
        длина = р["конец"] - р["начало"]
        if длина <= МАКС_РАЗДЕЛ:
            итог.append(р); continue
        куски = нарезать_равномерно(текст[р["начало"]:р["конец"]], МАКС_РАЗДЕЛ // 2)
        for i, к in enumerate(куски, 1):
            итог.append({"заголовок": f'{р["заголовок"]} — фрагмент {i}',
                         "уровень": р["уровень"] + 1,
                         "начало": р["начало"] + к["начало"],
                         "конец": р["начало"] + к["конец"]})
    return итог


МАРКЕРЫ_СЛУЖЕБНОГО = [
    r"ПЕРЕЙТИ К ССЫЛКЕ", r"ПРОПУСТИТЬ ЗАМЕТКИ", r"\bibid\b", r"\bIbid\b",
    r"[Сс]м\. там же", r"\bpp?\.\s*\d+", r"\bс\.\s*\d+[,–—]",
]
ПОРОГ_СЛУЖЕБНОГО = 8   # маркеров на 10 000 знаков

# Вторая, независимая примета: строка, оканчивающаяся номером страницы или
# диапазоном страниц. Так устроены указатель, оглавление, библиография и список
# ресурсов на любом языке — маркеров вроде ibid в них может не быть ни одного.
СТРОКА_С_НОМЕРОМ = re.compile(r"[,–—-]\s*\d{1,4}(\s*[–—-]\s*\d{1,4})?\s*$")
ПОРОГ_НОМЕРОВ = 0.35   # доля строк раздела
МИН_СТРОК = 20         # на коротком фрагменте доля ничего не значит

# Третья примета: библиографическая строка — номер ссылки в начале, URL, doi,
# год с точкой, «In Proceedings», том и номер выпуска. Так устроен список
# литературы и в русском, и в английском тексте.
СТРОКА_БИБЛИОГРАФИИ = re.compile(
    r"^\[\d{1,3}\]|https?://|\b(19|20)\d{2}[a-z]?\.\s|\bdoi:|\bdoi\.org"
    r"|\bIn Proceedings|\barXiv|\bvol\.\s*\d|\bno\.\s*\d")
ПОРОГ_БИБЛИОГРАФИИ = 0.12   # доля строк раздела


def служебный(фрагмент):
    """Сноски, библиография, указатель — формально текст, но содержания не несут.
    Опознаются по трём независимым приметам, а не по заголовку: заголовок у них
    бывает любой или отсутствует. Срабатывает любая из трёх."""
    if not фрагмент:
        return False, 0.0
    попаданий = sum(len(re.findall(m, фрагмент)) for m in МАРКЕРЫ_СЛУЖЕБНОГО)
    плотн = round(попаданий / (len(фрагмент) / 10000), 1)
    if плотн >= ПОРОГ_СЛУЖЕБНОГО:
        return True, плотн
    строки = [л.strip() for л in фрагмент.split("\n") if л.strip()]
    if len(строки) >= МИН_СТРОК:
        с_номером = sum(1 for л in строки if СТРОКА_С_НОМЕРОМ.search(л)) / len(строки)
        if с_номером >= ПОРОГ_НОМЕРОВ:
            return True, плотн
        библио = sum(1 for л in строки if СТРОКА_БИБЛИОГРАФИИ.search(л)) / len(строки)
        if библио >= ПОРОГ_БИБЛИОГРАФИИ:
            return True, плотн
    return False, плотн


def main(папка):
    _общее().входы_шага(папка, "b2_структура.py")
    текст = open(os.path.join(папка, "00_текст.txt"), encoding="utf-8").read()
    заголовки = найти_заголовки(текст)
    разделы = собрать_разделы(текст, заголовки)
    разделы = склеить_мелкие(разделы, текст)
    разделы = разрезать_крупные(разделы, текст)

    for i, р in enumerate(разделы, 1):
        р["id"] = f"р{i:03d}"
        р["знаков"] = р["конец"] - р["начало"]
        р["доля_документа"] = round(р["знаков"] / max(1, len(текст)), 3)
        р["служебный"], р["плотность_сносок"] = служебный(текст[р["начало"]:р["конец"]])

    содержательных = [р for р in разделы if not р["служебный"]]

    знаков_содержательных = sum(р["знаков"] for р in содержательных)
    доля_служебного = 1 - знаков_содержательных / max(1, len(текст))
    тревоги = []
    if доля_служебного > ПОРОГ_ТРЕВОГИ_СЛУЖЕБНОГО:
        тревоги.append(f"служебным помечено {доля_служебного:.0%} текста — проверьте, "
                       f"не срезано ли содержание")
    ранние = [р["id"] for р in разделы
              if р["служебный"] and р["конец"] < ХВОСТ * len(текст)]
    if ранние:
        тревоги.append("служебный раздел стоит не в хвосте документа: "
                       + ", ".join(ранние))

    итог = {"источник_границ": "заголовки" if заголовки else "равномерно",
            "найдено_заголовков": len(заголовки),
            "разделов": len(разделы),
            "служебных": len(разделы) - len(содержательных),
            "знаков_содержательных": знаков_содержательных,
            "предупреждения": тревоги,
            "разделы": разделы}
    json.dump(итог, open(os.path.join(папка, "01_структура.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    print(f'{итог["источник_границ"]}: {len(разделы)} разделов')
    print(f'служебных (сноски/библиография): {итог["служебных"]}, '
          f'содержательных знаков: {итог["знаков_содержательных"]}')
    for т in тревоги:
        print("  ! " + т)
    for р in разделы:
        метка = "  [служебный]" if р["служебный"] else ""
        print(f'  {р["id"]}  {р["знаков"]:>6} зн.  {р["заголовок"][:60]}{метка}')


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
