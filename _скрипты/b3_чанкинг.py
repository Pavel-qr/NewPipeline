# -*- coding: utf-8 -*-
"""
Б3. Нарезка на чанки.
Вход:  00_текст.txt, 00_слой.jsonl, 01_структура.json
Выход: <папка>/02_чанки.jsonl — по строке на чанк.

Чанк — 2–3 соседние страницы эталона (B1), пока не упрёмся в потолок знаков.
Служебные куски (сноски, библиография) по границам Б2 в чанк не входят.

Перекрытия текста НЕТ. Вместо него у чанка есть поле "контекст_до" —
последний абзац предыдущего чанка. Модель его читает, чтобы понять ссылки
("этот подход", "она"), но тезисы из него не извлекает. Так связность
сохраняется, а дублей в выжимках не возникает.
"""
import sys, os, re, json, importlib.util


def _общее():
    сп = importlib.util.spec_from_file_location(
        "общее", os.path.join(os.path.dirname(os.path.abspath(__file__)), "общее.py"))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м

ЦЕЛЬ = 9000        # знаков в чанке (~3000–3500 токенов русского текста)
МАКС = 13000
МИН = 1500         # короче — приклеиваем к предыдущему чанку того же раздела
КОНТЕКСТ = 400     # знаков хвоста предыдущего чанка
ОТРЕЗОК = 1000     # знаков в адресном отрезке чанка (`отрезки`)
НАЧАЛО_ОТРЕЗКА = 60 # знаков начала отрезка в его адресе (`отрезки[].начинается_с`)


def абзацы(текст):
    """Границы абзацев [(начало, конец)] внутри текста — непустые куски между
    пустыми строками. Абзац — это срез текста, а не его копия: чанк дальше
    собирается тоже срезом, и его координаты верны по построению.

    До 17 сентября абзацы вырезались `re.split(r"\\n\\s*\\n")`, а чанк склеивался
    из них через `"\n\n"`. Разделитель `"\n\n\n\n"` или `"\n \n"` при этом терялся,
    склеенный кусок в тексте не находился, и координаты брались «от курсора»:
    15 чанков из 1190 в старом прогоне указывали не на свой текст."""
    границы, поз = [], 0
    for м in re.finditer(r"\n\s*\n", текст):
        if текст[поз:м.start()].strip():
            границы.append((поз, м.start()))
        поз = м.end()
    if текст[поз:].strip():
        границы.append((поз, len(текст)))
    return границы


def отрезки(текст):
    """Адреса внутри чанка: [(начало, конец)] кусков примерно по ОТРЕЗОК знаков.
    Единица объёма: П1 называет, какие отрезки занимает блок, и объём
    блока считается по ним, а не как «длина чанка ÷ число блоков». Единицу
    делает скрипт, по длине: абзацев в тексте из PDF почти нет (пустые строки
    там — границы страниц), а цитировать границы дословно — лишняя работа
    модели и лишний повод для кода 4. Через пустую строку отрезок не переходит;
    внутри абзаца граница сдвигается к ближайшему концу предложения."""
    адреса = []
    for н, к in абзацы(текст):
        поз = н
        while к - поз > ОТРЕЗОК * 1.5:
            цель = поз + ОТРЕЗОК
            # конец предложения в окне [цель − ОТРЕЗОК/2, цель + ОТРЕЗОК/2]
            лево = max(поз, цель - ОТРЕЗОК // 2)
            окно = текст[лево:min(к, цель + ОТРЕЗОК // 2)]
            # Конец предложения, а если его в окне нет (таблица, список без
            # точек) — ближайший пробел: граница никогда не режет слово.
            концы = ([m.end() for m in re.finditer(r"[.!?…]['»)\]]*\s", окно)]
                     or [m.end() for m in re.finditer(r"\s", окно)])
            if концы:
                граница = лево + min(концы, key=lambda e: abs(e - (цель - лево)))
            else:
                граница = цель
            адреса.append((поз, граница)); поз = граница
        адреса.append((поз, к))
    return адреса


def нарезать_раздел(текст):
    """[(начало, конец)] кусков раздела — сплошных срезов, набранных из целых
    абзацев до целевого размера. Абзац не режется; хвост короче МИН
    приклеивается к предыдущему куску."""
    куски, буфер = [], None
    for н, к in абзацы(текст):
        if буфер and к - буфер[0] > МАКС:
            куски.append(буфер); буфер = (н, к)
        elif буфер and буфер[1] - буфер[0] >= ЦЕЛЬ:
            куски.append(буфер); буфер = (н, к)
        else:
            буфер = (буфер[0], к) if буфер else (н, к)
    if буфер:
        if куски and буфер[1] - буфер[0] < МИН:
            куски[-1] = (куски[-1][0], буфер[1])
        else:
            куски.append(буфер)
    return куски


def содержательные_срезы(текст, структура, слой):
    """Куски эталона на содержательных страницах, без служебных разделов Б2."""
    живые = [(р["начало"], р["конец"]) for р in структура["разделы"] if not р["служебный"]]
    срезы = []
    for з in слой:
        з.get("страница"); з.get("начало"); з.get("знаков"); з.get("текст")
        н, к = з["начало"], з["начало"] + з["знаков"]
        if текст[н:к] != з["текст"]:
            raise SystemExit(
                f"b3: страница {з['страница']} не совпадает с 00_текст — повторите Б1")
        куски = []
        for а, б in живые:
            lo, hi = max(н, а), min(к, б)
            if hi > lo:
                куски.append((lo, hi))
        if not куски:
            continue
        полный = куски == [(н, к)]
        срезы.append({
            "страница": з["страница"],
            "начало": н if полный else куски[0][0],
            "конец": к if полный else куски[-1][1],
            "полный": полный,
        })
    return срезы


def группы_страниц(срезы):
    """Пачки по 2 страницы, третья — если ещё не набрали ЦЕЛЬ и не вылезли за МАКС."""
    группы, i = [], 0
    while i < len(срезы):
        пачка = [срезы[i]]
        i += 1
        while i < len(срезы) and len(пачка) < 3:
            if срезы[i]["страница"] != пачка[-1]["страница"] + 1:
                break
            щель = срезы[i]["начало"] - пачка[-1]["конец"]
            if щель < 0 or щель > 4:
                break
            знаков = sum(s["конец"] - s["начало"] for s in пачка) + (
                срезы[i]["конец"] - срезы[i]["начало"])
            if len(пачка) >= 2 and знаков > ЦЕЛЬ:
                break
            if знаков > МАКС:
                break
            пачка.append(срезы[i])
            i += 1
        группы.append(пачка)
    склеенные = []
    for г in группы:
        знаков = sum(s["конец"] - s["начало"] for s in г)
        if (склеенные and знаков < МИН
                and г[0]["страница"] == склеенные[-1][-1]["страница"] + 1):
            склеенные[-1].extend(г)
        else:
            склеенные.append(г)
    return склеенные


def main(папка):
    _общее().входы_шага(папка, "b3_чанкинг.py")
    текст = open(os.path.join(папка, "00_текст.txt"), encoding="utf-8").read()
    структура = json.load(open(os.path.join(папка, "01_структура.json"), encoding="utf-8"))
    слой = [json.loads(л) for л in open(os.path.join(папка, "00_слой.jsonl"), encoding="utf-8") if л.strip()]
    всего_знаков = len(текст)
    срезы = содержательные_срезы(текст, структура, слой)
    группы = группы_страниц(срезы)

    чанки = []
    предыдущий_хвост = ""
    for группа in группы:
        начало = группа[0]["начало"]
        конец = группа[-1]["конец"]
        кусок = текст[начало:конец]
        страницы = [s["страница"] for s in группа]
        адр = [{"n": i + 1,
                "начало": начало + а, "конец": начало + б,
                "начинается_с": " ".join(кусок[а:б].split())[:НАЧАЛО_ОТРЕЗКА]}
               for i, (а, б) in enumerate(отрезки(кусок))]
        чанки.append({
            "id": f"ч{len(чанки)+1:04d}",
            "раздел_id": f"с{страницы[0]:03d}" + ("" if len(страницы) == 1 else f'–с{страницы[-1]:03d}'),
            "раздел": f"стр. {страницы[0]}" + ("" if len(страницы) == 1 else f"–{страницы[-1]}"),
            "страницы": страницы,
            "начало": начало,
            "конец": конец,
            "знаков": len(кусок),
            "позиция_в_документе": round(начало / max(1, всего_знаков), 3),
            "контекст_до": предыдущий_хвост,
            "отрезки": адр,
            "текст": кусок,
        })
        предыдущий_хвост = кусок[-КОНТЕКСТ:]

    чужие = [ч["id"] for ч in чанки if текст[ч["начало"]:ч["конец"]] != ч["текст"]]
    if чужие:
        print(f"чанков с координатами не на свой текст: {len(чужие)} — {', '.join(чужие)}; "
              f"файл не записан")
        return 1
    if not чанки:
        print("содержательных страниц нет — ни одного чанка; файл не записан")
        return 1

    путь = os.path.join(папка, "02_чанки.jsonl")
    with open(путь, "w", encoding="utf-8") as f:
        for ч in чанки:
            f.write(json.dumps(ч, ensure_ascii=False) + "\n")

    размеры = [ч["знаков"] for ч in чанки]
    print(f"чанков: {len(чанки)}, знаков: {sum(размеры)}, "
          f"мин/сред/макс: {min(размеры)}/{sum(размеры)//len(размеры)}/{max(размеры)}")
    print("страницы: " + ", ".join(
        f"{ч['id']}={ч['страницы'][0]}" + ("" if len(ч['страницы']) == 1 else f"–{ч['страницы'][-1]}")
        for ч in чанки))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
