# -*- coding: utf-8 -*-
"""
Проверка выжимок Б4 (запускается сразу после модели).
Вход:  <папка>/00_текст.txt, <папка>/03_выжимки.jsonl
Выход: код возврата + отчёт в stdout; <папка>/03_проверка.json

Ловит единственную ошибку, которую модель делает на этом шаге и которая
отравляет саммари и расклад цифр: недословную цитату. Цитата проверяется
машиной, а не доверием: есть в эталоне `00_текст.txt` (слой B1). Сравнение по нормализованной
строке (пробелы, кавычки, тире), с учётом [...] и пробела переноса внутри
слова. Те же `норм`, `норм_с_картой` и `найдена` — одна нормализация на
все проверки цитат в пайплайне (Б4т, Б5, О4, У1).
"""
import sys, os, re, json, importlib.util


def _контракты():
    сп = importlib.util.spec_from_file_location(
        "контракты", os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                  "контракты.py"))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м

def норм(s):
    s = (s.replace("«", '"').replace("»", '"').replace("“", '"').replace("”", '"')
          .replace("‘", "'").replace("’", "'").replace("—", "-").replace("–", "-").replace("ё", "е")
          .replace("Ё", "Е"))
    return re.sub(r"\s+", " ", s).strip().lower()


ЗАМЕНЫ = {"«": '"', "»": '"', "“": '"', "”": '"', "‘": "'", "’": "'",
          "—": "-", "–": "-", "ё": "е", "Ё": "Е"}


def норм_с_картой(s):
    """То же, что `норм`, плюс карта: `карта[i]` — индекс этого знака в исходной
    строке.

    Зачем. Индексы разделов и чанков живут в сыром тексте, а цитаты ищутся в
    нормализованном. Раньше одно переводилось в другое глобальной пропорцией
    длин — `len(норм) / len(сырой)`. Но нормализация сжимает текст неравномерно:
    страница с таблицей, где половина знаков — пробелы, ужимается втрое, а
    сплошная проза почти не меняется. На 93 материалах пропорция ошибалась в
    худшей точке на 320 знаков (`02_техреспублика`), в среднем по материалу на
    14, и у 10% блоков это меняло `доля_документа` на 0,001.

    Карта не оценивает, а помнит: перевод становится точным по построению, и
    ошибке неоткуда взяться ни на какой вёрстке.

    Результат обязан совпадать с `норм` знак в знак — иначе карта описывает не
    тот текст, в котором ищут. Проверяется здесь же: две функции, считающие одно
    и то же по-разному, рано или поздно разойдутся, и молча."""
    буквы, карта, пробел = [], [], False
    for i, c in enumerate(s):
        c = ЗАМЕНЫ.get(c, c)
        if c.isspace():
            пробел = True
            continue
        if пробел and буквы:            # схлопнутый пробел показывает на свой знак
            буквы.append(" "); карта.append(i)
        пробел = False
        for x in c.lower():             # lower() у некоторых знаков даёт два
            буквы.append(x); карта.append(i)
    готово = "".join(буквы)
    if готово != норм(s):
        raise RuntimeError("норм_с_картой разошлась с норм — карта индексов "
                           "описывает не тот текст, дальше считать нельзя")
    return готово, карта


# Сокращение внутри цитаты: «[…]» или «[...]». Одно место на все сверки —
# b4, b4т и b5 режут цитату одинаково, иначе цитата, прошедшая дословность,
# не находится при поиске позиции.
СОКРАЩЕНИЕ = re.compile(r"\[\s*…\s*\]|\[\s*\.\.\.\s*\]")


def куски_цитаты(цитата):
    """Непустые куски нормализованной цитаты между сокращениями."""
    return [k.strip() for k in СОКРАЩЕНИЕ.split(норм(цитата)) if k.strip()]


def _с_переносом(фрагмент):
    """Цитата как в PDF после извлечения: внутри слова мог остаться пробел
    переноса (`col lected`, `autonomy- supportive`), либо модель склеила
    перенос, а в тексте пробел ещё есть. Между знаками — не больше одного
    пробела; другие буквы вставить нельзя. Хвост не захватывает продолжение
    слова (`the sat` ≠ `the satisfaction`)."""
    части = []
    for ch in фрагмент:
        if ch.isspace():
            части.append(r" ?")
            continue
        if части and not части[-1].endswith(r" ?"):
            части.append(r" ?")
        части.append(re.escape(ch))
    return "".join(части) + r"(?![a-zа-яё])"


def позиция(фрагмент, текст_норм, начало=0, конец=None):
    """Индекс фрагмента в норм-тексте: сначала дословно, иначе с переносом PDF."""
    if not фрагмент:
        return -1
    поле = текст_норм if конец is None else текст_норм[:конец]
    i = поле.find(фрагмент, начало)
    if i >= 0:
        return i
    m = re.search(_с_переносом(фрагмент), поле[начало:])
    return начало + m.start() if m else -1


def найдена(цитата, текст_норм):
    ц = норм(цитата)
    if not ц:
        return False
    куски = куски_цитаты(ц)
    поз = 0
    for k in куски:
        i = позиция(k, текст_норм, поз)
        if i < 0:
            return False
        поз = i + 1
    return True


def почему_не_найдена(цитата, текст_норм):
    """Чем именно плоха цитата: «недословна» или «куски переставлены».

    Куски, склеенные через `[…]`, ищутся подряд слева направо, и кусок, лежащий
    в тексте выше предыдущего, не находится. Снаружи это неотличимо от выдумки,
    хотя чинится иначе: там переписать цитату, здесь — переставить её части.
    Пока диагноз был один на оба случая, модель на правке возвращала ту же
    цитату, считая её дословной (и была права), — восемь перевызовов подряд."""
    куски = куски_цитаты(норм(цитата))
    if len(куски) > 1 and all(позиция(k, текст_норм) >= 0 for k in куски):
        return "куски цитаты переставлены — в тексте они идут в другом порядке"
    return "недословна"


