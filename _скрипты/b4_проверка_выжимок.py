def текст_исходника(папка):
    """Оригинал материала до нормализации B1: PDF, DOCX и любой читатель B1."""
    п = os.path.join(папка, "00_мета.json")
    if not os.path.exists(п):
        return None
    путь = (json.load(open(п, encoding="utf-8")) or {}).get("путь_в_корпусе")
    if not путь:
        return None
    исх = _общее().путь_исходника(путь, "b4")
    расш = os.path.splitext(исх)[1].lower()
    читатели = _b1().ЧИТАТЕЛИ
    if расш not in читатели:
        return None
    страницы, _ = читатели[расш](исх)
    return норм("\n".join(страницы))


def найдена_в_эталонах(цитата, *эталоны):
    return any(т and найдена(цитата, т) for т in эталоны)


def собрать_цитаты(в):
    """Все цитаты выжимки: кейсы, цифры, инструменты, опоры под практику,
    адресация, привязка к продукту."""
    for к in в.get("кейсы", []):
        yield "кейс", к.get("цитата")
    for ц in в.get("цифры", []):
        yield "цифра", ц.get("цитата")
    for и in в.get("инструменты", []):
        yield "инструмент", и.get("цитата")
    for о in в.get("опоры_под_практику", []):
        yield "опора под практику", о.get("цитата")
    yield "адресация", (в.get("адресация") or {}).get("цитата")
    yield "продукт", (в.get("привязка_к_продукту_автора") or {}).get("цитата")


def _общее():
    сп = importlib.util.spec_from_file_location(
        "общее", os.path.join(os.path.dirname(os.path.abspath(__file__)), "общее.py"))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


def main(папка):
    _общее().входы_шага(папка, "b4_проверка_выжимок.py")
    текст_норм = норм(open(os.path.join(папка, "00_текст.txt"), encoding="utf-8").read())
    выжимки = [json.loads(l) for l in open(os.path.join(папка, "03_выжимки.jsonl"), encoding="utf-8") if l.strip()]
    # Форма ответа проверяется до дословности: незачем сверять цитаты у цифры,
    # у которой источник стоит вне списка.
    if _контракты().стоп("П1", выжимки, os.path.basename(папка.rstrip("/")), папка):
        return 4

    всего = плохих = 0
    брак = []
    for в in выжимки:
        for где, ц in собрать_цитаты(в):
            if not ц:
                continue
            всего += 1
            if not найдена(ц, текст_норм):
                плохих += 1
                брак.append({"чанк": в.get("чанк_id"), "где": где,
                             "почему": почему_не_найдена(ц, текст_норм),
                             "цитата": ц[:160]})

    отчёт = {"цитат": всего, "недословных": плохих, "брак": брак}
    json.dump(отчёт, open(os.path.join(папка, "03_проверка.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    print(f"цитат: {всего}, недословных: {плохих}")
    for б in брак:
        print(f'  ✗ {б["чанк"]} [{б["где"]}] {б["почему"]}: {б["цитата"]}')
    if плохих:
        # Диагноз ставит шаг, а не оркестратор: `прогон.py` печатает то, что
        # сказал скрипт, и ничего не добавляет от себя (см. `общее.py`).
        print("  ! есть недословные цитаты — исправить выжимки и повторить Б4")
        return _общее().КОНТРАКТ
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
