# -*- coding: utf-8 -*-
"""
Проверка тематического разбора Б4т (запускается сразу после модели).
Вход:  <папка>/00_текст.txt, 02_чанки.jsonl, 03_темы.jsonl, канон тем
Выход: код возврата + отчёт в stdout; <папка>/03_проверка_тем.json

Ответ П1т — единственное место, где тема привязывается к тексту, и всё, что
скрипт может здесь проверить, он проверяет здесь, а не ниже по течению:

  · тема из канона (чужой id — ответ не по этому канону);
  · фрагмент — пара номеров отрезков `[от, до]` внутри своего чанка;
  · адрес блока — внутри одного из фрагментов его темы;
  · `полнота` — из закрытого списка;
  · цитата блока дословна и лежит внутри отрезков блока.

Любое нарушение — ответ не по требованию промта: код 4, исправить ответ и
повторить Б4т. Скрипты и промты при этом не трогать.
"""
import sys, os, json, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))


def _модуль(имя, файл):
    сп = importlib.util.spec_from_file_location(имя, os.path.join(ЗДЕСЬ, файл))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


_b4 = _модуль("b4", "b4_проверка_выжимок.py")
_общее = _модуль("общее", "общее.py")
_к = _модуль("контракты", "контракты.py")
_канон = _модуль("канон", "канон.py")

# Цитата может начинаться чуть раньше границы отрезка, если модель прихватила
# конец предыдущего предложения; на большее окно не рассчитываем.
ОКНО = 400


def пара(x, верх):
    """`[от, до]` — два целых, 1 ≤ от ≤ до ≤ верх; иначе None."""
    if (isinstance(x, list) and len(x) == 2
            and all(isinstance(v, int) and not isinstance(v, bool) for v in x)
            and 1 <= x[0] <= x[1] <= верх):
        return x[0], x[1]
    return None


def начало_цитаты(цитата, текст_норм, карта, чанк, из_сырого):
    """Сырой индекс начала цитаты: ищем в окне своего чанка, потом по всему тексту."""
    куски = _b4.куски_цитаты(цитата)
    if not куски:
        return None
    н = max(0, из_сырого(чанк["начало"]) - ОКНО)
    к = min(len(текст_норм), из_сырого(чанк["конец"]) + ОКНО)
    i = _b4.позиция(куски[0], текст_норм, н, к)
    if i < 0:
        i = _b4.позиция(куски[0], текст_норм)
    return карта[min(max(i, 0), len(карта) - 1)] if i >= 0 else None


def main(папка):
    _общее.входы_шага(папка, "b4т_проверка_тем.py")
    import bisect
    сырой = open(os.path.join(папка, "00_текст.txt"), encoding="utf-8").read()
    текст_норм, карта = _b4.норм_с_картой(сырой)
    из_сырого = lambda i: bisect.bisect_left(карта, i)
    чанки = {c["id"]: c for c in
             (json.loads(l) for l in open(os.path.join(папка, "02_чанки.jsonl"), encoding="utf-8") if l.strip())}
    темы_канона = {т["id"] for т in _канон.читать()}
    разборы = [json.loads(l) for l in open(os.path.join(папка, "03_темы.jsonl"), encoding="utf-8") if l.strip()]

    # Форма ответа — до содержания.
    if _к.стоп("П1т", разборы, os.path.basename(папка.rstrip("/"))):
        return 4

    брак = []          # (чанк, тема, что)
    цитат = недословных = 0
    for р in разборы:
        c = чанки.get(р["чанк_id"])
        if c is None:
            брак.append((р["чанк_id"], None, "чанка с таким id нет в 02_чанки.jsonl — ответ не от этого чанкинга"))
            continue
        if "отрезки" not in c:
            print(f"чанк {c['id']} без адресов отрезков — повторите Б3 (и Б4, Б4т за ним)")
            return 1
        верх = len(c["отрезки"])
        видели = set()
        for т in р["темы"]:
            ид = т["id"]
            if ид not in темы_канона:
                брак.append((c["id"], ид, "темы с таким id в каноне нет"))
                continue
            if ид in видели:
                брак.append((c["id"], ид, "тема названа в чанке дважды — одна тема, один объект"))
                continue
            видели.add(ид)
            фрагменты = []
            for ф in т["фрагменты"]:
                п = пара(ф, верх)
                if п is None:
                    брак.append((c["id"], ид, f"фрагмент {ф!r} — не пара номеров отрезков 1…{верх}"))
                    continue
                фрагменты.append(п)
            if not фрагменты and т["блоки"]:
                брак.append((c["id"], ид, "блоки без единого фрагмента — блок лежит внутри фрагмента темы"))
                continue
            for i, б in enumerate(т["блоки"], 1):
                кто = f"блок {i}"
                if б.get("полнота") not in _к.СПИСКИ["полнота"]:
                    брак.append((c["id"], ид, f"{кто}: полнота {б.get('полнота')!r} вне списка"))
                адрес = пара(б.get("отрезки"), верх)
                if адрес is None:
                    брак.append((c["id"], ид, f"{кто}: отрезки {б.get('отрезки')!r} — не пара номеров 1…{верх}"))
                    continue
                if not any(ф[0] <= адрес[0] and адрес[1] <= ф[1] for ф in фрагменты):
                    брак.append((c["id"], ид, f"{кто}: адрес {list(адрес)} не внутри фрагментов темы "
                                              f"{[list(ф) for ф in фрагменты]}"))
                    continue
                от = c["отрезки"][адрес[0] - 1]["начало"]
                до = c["отрезки"][адрес[1] - 1]["конец"]
                for где, ц in (("цитата", б.get("цитата")),):
                    if not ц:
                        брак.append((c["id"], ид, f"{кто}: цитата пуста"))
                        continue
                    цитат += 1
                    if _b4.найдена(ц, текст_норм):
                        н = начало_цитаты(ц, текст_норм, карта, c, из_сырого)
                        if н is not None and not (от - ОКНО <= н < до + ОКНО):
                            брак.append((c["id"], ид, f"{кто}: {где} начинается вне отрезков "
                                                      f"{адрес[0]}–{адрес[1]}"))
                    else:
                        недословных += 1
                        почему = _b4.почему_не_найдена(ц, текст_норм)
                        брак.append((c["id"], ид, f"{кто}: {где} {почему}: {ц[:120]}"))

    отчёт = {"чанков": len(разборы), "тем_в_чанках": sum(len(р["темы"]) for р in разборы),
             "цитат": цитат, "недословных": недословных,
             "брак": [{"чанк": ч, "тема": т, "что": что} for ч, т, что in брак]}
    json.dump(отчёт, open(os.path.join(папка, "03_проверка_тем.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    print(f"чанков: {отчёт['чанков']}, тем в чанках: {отчёт['тем_в_чанках']}, "
          f"цитат: {цитат}, недословных: {недословных}")
    for ч, т, что in брак:
        print(f"  ✗ {ч} {т or ''}: {что}")
    if брак:
        print("  ! ответ П1т не по требованию промта — исправить 03_темы.jsonl и повторить Б4т")
        return _общее.КОНТРАКТ
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
