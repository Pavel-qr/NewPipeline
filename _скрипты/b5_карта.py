# -*- coding: utf-8 -*-
"""
Б5, часть 2 — карта документа (скрипт).
Вход:  04_агрегат.json (измеренное) + 04_решение.json (П2: суждения о документе)
       + 00_источник.json (И1) + справочник источников
Выход: 04_карта.json — карта документа: материал, источник, суждения П2,
       темы с объёмами; 04_саммари_сырьё.json — сырьё ветки суммаризации.

Сюжетов в карте нет: сюжет принадлежит теме и собирается П2т по кандидатам.
Здесь только то, что про документ целиком.
"""
import sys, os, json, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))


def _модуль(имя, файл):
    сп = importlib.util.spec_from_file_location(имя, os.path.join(ЗДЕСЬ, файл))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


_b4 = _модуль("b4", "b4_проверка_выжимок.py")
_общее = _модуль("общее", "общее.py")
_контракты = _модуль("контракты", "контракты.py")
_источники = _модуль("источники", "источники.py")

# Что о теме видят П3, П4 и П5 через карту: объёмы и сути блоков, без самих
# блоков — блоки едут в П2т и дальше в сюжетах.
ПОЛЯ_ТЕМЫ = ("id", "название", "знаков", "доля_документа", "знаков_подряд", "доля_куска",
             "фрагментов", "блоков", "полноценных_блоков", "распределение", "инструменты")


def строки(о):
    if isinstance(о, str):
        yield о
    elif isinstance(о, dict):
        for v in о.values():
            yield from строки(v)
    elif isinstance(о, list):
        for v in о:
            yield from строки(v)


def чужие_цитаты(агрегат, решение):
    """П2 исходника не видит — её вход только агрегат. Цитата, которой в
    агрегате нет, взяться может лишь из памяти о тексте. Сравнение — той же
    функцией, что на Б4 и О4: одна нормализация на все проверки цитат."""
    текст = "\n".join(_b4.норм(т) for т in строки(агрегат))
    чужие = []
    for поле in ("жанр", "зависимость_от_продукта"):
        блок = решение.get(поле) or {}
        ц = блок.get("цитата")
        if ц and _b4.норм(ц) not in текст:
            чужие.append((поле, ц))
        for ключ in ("цитаты_способа", "цитаты_находки"):
            for i, ц in enumerate(блок.get(ключ) or [], 1):
                if ц and _b4.норм(ц) not in текст:
                    чужие.append((f"{поле}.{ключ}[{i}]", ц))
    return чужие


def main(папка):
    _общее.входы_шага(папка, "b5_карта.py")
    агрегат = json.load(open(os.path.join(папка, "04_агрегат.json"), encoding="utf-8"))
    решение = json.load(open(os.path.join(папка, "04_решение.json"), encoding="utf-8"))

    if _контракты.стоп("П2", решение, os.path.basename(папка.rstrip("/"))):
        return 4
    чужие = чужие_цитаты(агрегат, решение)
    if чужие:
        print(f"цитат не из агрегата: {len(чужие)}")
        for где, ц in чужие:
            print(f"  ✗ {где}: {ц[:120]}")
        print("  ! П2 цитирует не агрегат — исправить и повторить")
        return _общее.КОНТРАКТ

    # ----------------------------------------------------------------- источник
    # И1 отвечает за факты о публикации, П2 — за факты о содержании. Источник
    # собирается только из `00_источник.json`; второго кандидата нет.
    опознание = os.path.join(папка, "00_источник.json")
    if not os.path.exists(опознание):
        print("  ! нет 00_источник.json — сначала шаг 0 (И1 и `о_источник.py свести`)")
        return 1
    о = json.load(open(опознание, encoding="utf-8"))
    поля = о.get("поля") or {}
    источник = {наше: поля.get(из_и1) for наше, из_и1 in (
        ("название", "title"), ("автор", "author_name"), ("издание", "publisher"),
        ("дата", "publication_date"), ("issn", "issn"), ("isbn", "isbn"),
        ("doi", "doi"), ("домен", "домен"), ("year", "год"),
        ("author_credential", "author_credential"), ("author_type", "author_type"),
        ("material_type", "material_type"), ("original_language", "original_language"),
        ("license", "license"), ("source_url", "source_url"),
        ("access_type", "access_type"))}
    источник["опознание"] = {"как_получено": о.get("как_получено"),
                             "что_искал": о.get("что_искал")}
    источник["оценка"] = _источники.оценить(поля)

    if "зависимость_от_продукта" not in решение and "зависимость_от_продукту" in решение:
        решение["зависимость_от_продукта"] = решение["зависимость_от_продукту"]
    нет = [к for к in ("о_чём_материал", "отрасль_материала", "жанр",
                       "зависимость_от_продукта", "адресат", "ограничения")
           if к not in решение]
    if нет:
        print("  ! П2: в 04_решение.json нет полей: " + ", ".join(нет) +
              " — исправить ответ и повторить")
        return _общее.КОНТРАКТ

    по_ид = {б["id"]: б for б in агрегат["блоки"]}
    темы = [{**{k: т[k] for k in ПОЛЯ_ТЕМЫ},
             "сути": [по_ид[и]["суть"] for и in т["блоки"]]}
            for т in агрегат["темы"]]

    карта = {
        "материал": агрегат["материал"],
        "о_чём_материал": решение["о_чём_материал"],
        "источник": источник,
        "отрасль_материала": решение["отрасль_материала"],
        "жанр": решение["жанр"],
        "зависимость_от_продукта": решение["зависимость_от_продукта"],
        "адресат": решение["адресат"],
        "адресация": агрегат["адресация"],
        "key_concepts": решение.get("key_concepts") or None,
        "темы": темы,
        "цифры": агрегат["цифры"],
        # Ограничения — то, чего в материале нет (пишет П2); тревоги — то, что
        # в разборе пошло не так (Б2, Б5). Тревоги О4 кладёт флагами в строки.
        "ограничения": list(решение["ограничения"]) + list(агрегат.get("заметки_разбора") or []),
        "тревоги": list(агрегат["материал"]["тревоги"]),
    }
    json.dump(агрегат["для_саммари"],
              open(os.path.join(папка, "04_саммари_сырьё.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    json.dump(карта, open(os.path.join(папка, "04_карта.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)

    def напечатать():
        for т in карта["тревоги"]:
            print("  ! " + т)
        оц = источник["оценка"]
        print(f'  источник: {оц["организация"] or "не опознан"} — '
              f'{оц.get("процесс") or "?"}, S_база {_общее.знак(оц["S_база"])}'
              + (f'  ! {оц["флаг"]}' if оц["флаг"] else ""))
        print(f'карта: тем {len(темы)}, жанр — {карта["жанр"]["тип"]}, '
              f'адресат — {карта["адресат"]["тег"]}, '
              f'тип документа — {карта["источник"].get("material_type") or "не опознан"}')
        for т in темы:
            print(f'  {т["доля_документа"]:>5.0%}  {т["id"]:<34} блоков {т["блоков"]} '
                  f'(полноценных {т["полноценных_блоков"]})  {"/".join(т["распределение"])}')
    _общее.отчёт(напечатать)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]) or 0)
