# -*- coding: utf-8 -*-
"""
О1, часть 2 — предварительный балл A (скрипт).
Вход:  04_карта.json, 04_агрегат.json, 10_исключения.json (от П3), 02_чанки.jsonl,
       канон тем
Выход: 10_кандидаты.json — все темы с A и B, шортлист кандидатов;
       10_сюжеты_вход.jsonl — по строке на кандидата: блоки темы, вход П2т.

Тема к тексту привязана на Б4т, объём измерен на Б5. Здесь объём переводится в
балл, к нему добавляется B (по цифрам в чанках темы) и применяются исключения,
которые П3 решила по материалу целиком.

Шкала считается по САМОМУ ДЛИННОМУ НЕПРЕРЫВНОМУ КУСКУ документа по этой теме —
цепочке подряд идущих отрезков её фрагментов:

  5  кусок ≥ 30% документа ИЛИ ≥ 15 000 знаков
  4  ≥ 15% ИЛИ ≥ 7 000
  3  ≥  5% ИЛИ ≥ 3 500
  2  меньше, но хотя бы один полноценный блок есть
  1  тема в тексте есть, но ни куска, ни полноценного блока
  0  темы нет или уверенно сработало исключение (пограничное не обнуляет A)

Почему две меры в каждой строке, а не одна. Процент несправедлив к длинным
документам: 27 000 знаков подряд по теме внутри стандарта — это 3,6% документа
и отдельная полноценная работа сама по себе. Абсолют несправедлив к коротким: в
заметке на три страницы 3 500 знаков подряд по одной теме физически не набрать,
хотя тема занимает в ней 40%. Каждая мера ломается на своём краю, и обе вместе
не ломаются нигде.

Считается именно НЕПРЕРЫВНЫЙ кусок, а не сумма по теме. Вопрос, на который
отвечает A, — «есть ли здесь самостоятельный фрагмент, из которого можно сделать
единицу», а не «сколько всего в материале про эту тему». Полный объём темы едет
рядом, в `доля_документа`, и по нему считается роль темы в материале.

Роль (главная / сопоставимая / обслуживающая) — пометка для человека, в балл
не входит: она считается относительно других тем этого материала, то есть
зависит от того, сколько тем в каноне и насколько они узкие.
"""
import sys, os, json, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))


def _модуль(имя, файл):
    сп = importlib.util.spec_from_file_location(имя, os.path.join(ЗДЕСЬ, файл))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


_док = _модуль("доказательность", "доказательность.py")
_контракты = _модуль("контракты", "контракты.py")
_общее = _модуль("общее", "общее.py")
_канон = _модуль("канон", "канон.py")

# Тема с A=3 в o4_скоринг останавливается на гейте B: балл фиксирован и равен 3,
# вердикт ⛔ при любом исходе строгой проверки. Вызовы модели на такую тему
# ничего не решают, поэтому в кандидаты она не идёт.
ПОРОГ_КАНДИДАТА = 4

# Ступени: (доля куска от документа, знаков в куске, балл). Первая подошедшая
# строка выигрывает; внутри строки хватает любого из двух условий.
СТУПЕНИ = ((0.30, 15000, 5),
           (0.15,  7000, 4),
           (0.05,  3500, 3))
# Насколько тема сопоставима с крупнейшей темой материала. Пометка, не балл.
СОПОСТАВИМА = 0.60
ГЛАВНАЯ = 0.95

# Что П2т получает о блоке темы.
ПОЛЯ_БЛОКА = ("id", "суть", "актор", "голос", "бенефициар", "механизм", "полнота", "цитата",
              "раздел", "часть_документа", "позиция", "инструменты", "опора_под_практику")


def балл(доля_куска, знаков_подряд, полноценных):
    for доля, знаков, очки in СТУПЕНИ:
        if доля_куска >= доля or знаков_подряд >= знаков:
            return очки
    return 2 if полноценных else 1


def роль(доля_темы, доля_ведущей):
    if not доля_ведущей:
        return None
    отношение = доля_темы / доля_ведущей
    if отношение >= ГЛАВНАЯ:
        return "главная"
    return "сопоставимая" if отношение >= СОПОСТАВИМА else "обслуживающая"


def main(папка):
    _общее.входы_шага(папка, "o1_баллы.py")
    карта = json.load(open(os.path.join(папка, "04_карта.json"), encoding="utf-8"))
    агрегат = json.load(open(os.path.join(папка, "04_агрегат.json"), encoding="utf-8"))
    исключения = json.load(open(os.path.join(папка, "10_исключения.json"), encoding="utf-8"))
    if _контракты.стоп("П3", исключения, os.path.basename(папка.rstrip("/"))):
        return 4

    темы_канона = [т["id"] for т in _канон.читать()]
    ответила = {т["id"]: т for т in исключения["темы"]}
    # П3 отвечает по каждой теме канона — тема без ответа значит, что решение
    # по её исключениям не принято; тема не из канона — ответ не по этому
    # канону.
    нет = [и for и in темы_канона if и not in ответила]
    лишние = sorted(set(ответила) - set(темы_канона))
    if нет or лишние:
        if нет:
            print(f"П3 не ответила по темам канона: {', '.join(нет)}")
        if лишние:
            print(f"П3 ответила по темам не из канона: {', '.join(лишние)}")
        print("  ! ответ П3 не по этому канону — повторите О1 (П3)")
        return _общее.КОНТРАКТ

    измерено = {т["id"]: т for т in агрегат["темы"]}
    знаков_всего = max(1, карта["материал"]["знаков_содержательных"])

    цифры = _док.цифры_по_чанкам(папка, карта)
    цифр_всего, цифр_не_привязано = len(цифры), _док.не_привязано(цифры)
    хвост_B = (f" (не привязано к тексту {цифр_не_привязано} из {цифр_всего} цифр материала)"
               if цифр_не_привязано else "")

    строки = []
    for ид in темы_канона:
        искл = ответила[ид].get("исключение") or {}
        т = измерено.get(ид)
        if искл.get("сработало") and not искл.get("пограничное"):
            a, причина = 0, f'исключение: {искл.get("какое")}'
        elif not т:
            a, причина = 0, "тема в тексте не найдена"
        else:
            a = балл(т["доля_куска"], т["знаков_подряд"], т["полноценных_блоков"])
            причина = (f'{т["знаков_подряд"]} знаков подряд ({т["доля_куска"]:.0%} документа), '
                       f'вся тема {т["доля_документа"]:.0%} объёма, фрагментов {т["фрагментов"]}, '
                       f'блоков {т["блоков"]}, полноценных {т["полноценных_блоков"]}')
        B, расклад, учтено = _док.посчитать(папка, карта, агрегат, ид, цифры)
        строки.append({
            "id": ид, "A_предварительный": a, "почему_балл": причина,
            "знаков_подряд": т["знаков_подряд"] if т else 0,
            "доля_куска": т["доля_куска"] if т else 0.0,
            "доля_документа": т["доля_документа"] if т else 0.0,
            "фрагментов": т["фрагментов"] if т else 0,
            "блоков": т["блоков"] if т else 0,
            "полноценных_блоков": т["полноценных_блоков"] if т else 0,
            "части_документа": т["распределение"] if т else [],
            "исключение": искл, "пояснение_модели": ответила[ид].get("почему"),
            # Тема в тексте есть, а блоков под неё нет: упоминание без содержания.
            "упоминание_без_сюжета": bool(т and not т["блоков"]),
            "B": B, "цифры_темы": расклад, "цифр_учтено": учтено,
            "почему_B": (", ".join(f"{k} ×{v}" for k, v in расклад.items())
                         or "под этой темой цифр нет") + хвост_B,
        })

    # Свойство текста закрывает все темы разом: уверенный дескриптив — читателю
    # не передан порядок работ; зависимость от продукта — метод неотделим от
    # покупки. Пограничный дескриптив (есть и способ, и находка) скоринг не
    # режет: тип остаётся, в таблице будет флаг. Правило, не суждение, поэтому
    # здесь. Балл A не трогается: он про наличие куска.
    жанр = карта["жанр"]
    есть_способ = any(str(ц).strip() for ц in (жанр.get("цитаты_способа") or []))
    есть_находка = any(str(ц).strip() for ц in (жанр.get("цитаты_находки") or []))
    # Оба списка непусты — граница по правилу П2, даже если модель забыла флаг.
    жанр_пограничное = bool(жанр.get("пограничное")) or (есть_способ and есть_находка)
    закрыто = None
    if жанр["тип"] == "дескриптивный" and not жанр_пограничное:
        закрыто = "закрыто свойством текста: жанр дескриптивный"
    elif карта["зависимость_от_продукта"]["есть"]:
        закрыто = "закрыто свойством текста: метод неотделим от продукта автора"
    for с in строки:
        с["закрыто_свойством_текста"] = закрыто if с["A_предварительный"] >= 3 else None

    ведущая = max((с["доля_документа"] for с in строки), default=0)
    for с in строки:
        с["роль_в_материале"] = роль(с["доля_документа"], ведущая) if с["доля_документа"] else None

    строки.sort(key=lambda с: -с["A_предварительный"])
    кандидаты = [с["id"] for с in строки
                 if с["A_предварительный"] >= ПОРОГ_КАНДИДАТА
                 and not с["закрыто_свойством_текста"]]

    итог = {
        "жанр": жанр["тип"],
        "жанр_пограничное": жанр_пограничное,
        "зависимость_от_продукта": карта["зависимость_от_продукта"]["есть"],
        "отсечён_до_проверки": (жанр["тип"] == "дескриптивный" and not жанр_пограничное)
                               or карта["зависимость_от_продукта"]["есть"],
        "темы": строки,
        "кандидаты": кандидаты,
        "цифры": {"всего": цифр_всего, "не_привязано": цифр_не_привязано,
                  "в_нескольких_чанках": _док.неоднозначных(цифры)},
    }
    json.dump(итог, open(os.path.join(папка, "10_кандидаты.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)

    # Вход П2т — по строке на кандидата: блоки темы в порядке документа и её
    # карточка. Файл пишется всегда, пустым — если кандидатов нет: по пустому
    # входу прогон пропускает П2т (Д-3).
    карточки = {т["id"]: т for т in _канон.полный(кандидаты)}
    по_ид = {б["id"]: б for б in агрегат["блоки"]}
    with open(os.path.join(папка, "10_сюжеты_вход.jsonl"), "w", encoding="utf-8") as f:
        for ид in кандидаты:
            блоки = sorted((по_ид[и] for и in измерено[ид]["блоки"]), key=lambda б: б["позиция"])
            f.write(json.dumps({
                "тема": ид,
                "папка": os.path.basename(папка.rstrip("/")),
                "материал": карта["материал"].get("заголовок_из_файла") or карта["материал"]["файл"],
                "карточка_темы": {k: карточки[ид][k] for k in ("id", "название", "определение")},
                "о_чём_материал": карта["о_чём_материал"],
                "блоки": [{k: б.get(k) for k in ПОЛЯ_БЛОКА} for б in блоки],
            }, ensure_ascii=False) + "\n")

    print(f'жанр: {итог["жанр"]}'
          + (", пограничный" if итог["жанр_пограничное"] else "")
          + f', зависимость от продукта: {итог["зависимость_от_продукта"]}')
    if итог["отсечён_до_проверки"]:
        print("  → строгая проверка (П4) не запускается: свойство текста закрывает все темы")
    elif итог["жанр"] == "дескриптивный" and итог["жанр_пограничное"]:
        print("  → жанр дескриптивный, но пограничный: скоринг не закрыт")
    for с in строки:
        if с["A_предварительный"] or с["фрагментов"]:
            хвост = f' [{с["закрыто_свойством_текста"]}]' if с["закрыто_свойством_текста"] else ""
            роль_ = f' · {с["роль_в_материале"]}' if с.get("роль_в_материале") else ""
            print(f'  A={с["A_предварительный"]}  {с["id"]:<32} {с["почему_балл"]}{роль_}{хвост}')
    print("кандидаты:", кандидаты or "нет")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
