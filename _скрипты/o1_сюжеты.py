# -*- coding: utf-8 -*-
"""
О1т, часть 2 — свод сюжетов тем (скрипт).
Вход:  04_карта.json, 04_агрегат.json, 10_кандидаты.json, 10_сюжеты_вход.jsonl,
       10_сюжеты.jsonl (от П2т; нет, когда кандидатов не было), канон тем
Выход: 10_сюжеты_сведены.json — сюжеты каждого кандидата с измеренным;
       10_кандидаты_вход.jsonl — по строке на кандидата, вход П4 и П5.

Скрипт проверяет ответ П2т по требованиям промта — каждый блок темы ровно в
одном сюжете, цитаты только из блоков — и досчитывает по сюжетам то, что П2т
считать не должна: объём в знаках, долю, распределение, полноценные блоки,
инструменты и опоры под практику.

Оба файла пишутся всегда. Без кандидатов — пустыми: У1 и реестр читают свод и у
отклонённого материала, и «файла нет» значило бы «шаг не выполнялся».
"""
import sys, os, json, importlib.util
from collections import Counter

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))


def _модуль(имя, файл):
    сп = importlib.util.spec_from_file_location(имя, os.path.join(ЗДЕСЬ, файл))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


_b4 = _модуль("b4", "b4_проверка_выжимок.py")
_общее = _модуль("общее", "общее.py")
_контракты = _модуль("контракты", "контракты.py")
_канон = _модуль("канон", "канон.py")

ПОЛНОЦЕННЫЙ = {"механизм+пример", "механизм"}
МИН_ПОКРЫТИЕ = 0.9   # доля блоков темы, попавших хотя бы в один сюжет

# Что П4 и П5 получают о кандидате, кроме карты: поля строки 10_кандидаты.json.
ПОЛЯ_КАНДИДАТА = ("A_предварительный", "почему_балл", "B", "почему_B", "цифры_темы",
                  "части_документа", "полноценных_блоков", "роль_в_материале")
# Что из карты документа едет в строку кандидата. `темы` — нет: П4 и П5 судят
# об одной теме, соседние им ни к чему.
ПОЛЯ_КАРТЫ = ("материал", "о_чём_материал", "источник", "отрасль_материала", "жанр",
              "зависимость_от_продукта", "адресат", "адресация", "key_concepts",
              "цифры", "ограничения", "тревоги")


def читать(папка, имя):
    п = os.path.join(папка, имя)
    return json.load(open(п, encoding="utf-8")) if os.path.exists(п) else None


def main(папка):
    _общее.входы_шага(папка, "o1_сюжеты.py")
    карта = читать(папка, "04_карта.json")
    агрегат = читать(папка, "04_агрегат.json")
    кандидаты = читать(папка, "10_кандидаты.json")
    шортлист = list(кандидаты.get("кандидаты") or [])
    строки_к = {с["id"]: с for с in кандидаты["темы"]}
    имя_папки = os.path.basename(папка.rstrip("/"))
    всего = max(1, карта["материал"]["знаков_содержательных"])
    по_ид = {б["id"]: б for б in агрегат["блоки"]}
    темы_агрегата = {т["id"]: т for т in агрегат["темы"]}

    свод = {"темы": []}
    вход_п4 = []
    if шортлист:
        ответы = os.path.join(папка, "10_сюжеты.jsonl")
        if not os.path.exists(ответы):
            print("  ! кандидаты есть, а 10_сюжеты.jsonl нет — сначала П2т")
            return 1
        разборы = [json.loads(л) for л in open(ответы, encoding="utf-8") if л.strip()]
        if _контракты.стоп("П2т", разборы, имя_папки):
            return 4
        по_теме = {}
        for р in разборы:
            if р["тема"] not in шортлист:
                print(f"  · 10_сюжеты.jsonl: ответ по теме {р['тема']}, которой нет в шортлисте — не считается")
                continue
            по_теме[р["тема"]] = р
        нет = [и for и in шортлист if и not in по_теме]
        if нет:
            print(f"нет ответа П2т по кандидатам: {', '.join(нет)}")
            print("  ! повторите О1т на нынешнем шортлисте")
            return _общее.КОНТРАКТ

        карточки = {т["id"]: т for т in _канон.полный(шортлист)}
        for ид in шортлист:
            р = по_теме[ид]
            свои_блоки = set(темы_агрегата[ид]["блоки"])
            цитаты_блоков = {_b4.норм(по_ид[и]["цитата"]) for и in свои_блоки if по_ид[и].get("цитата")}
            ссылки = [i for с in р["сюжеты"] for i in с["блоки"]]
            чужие = sorted(set(ссылки) - свои_блоки)
            if чужие:
                print(f"{ид}: сюжеты ссылаются на блоки не этой темы или несуществующие: {', '.join(чужие[:8])}")
                print("  ! ответ П2т не от этого входа — повторите О1т")
                return _общее.КОНТРАКТ
            счёт = Counter(ссылки)
            дубли = sorted(i for i, n in счёт.items() if n > 1)
            покрытие = len(set(ссылки)) / max(1, len(свои_блоки))
            if покрытие < МИН_ПОКРЫТИЕ:
                print(f"{ид}: сюжеты покрывают {покрытие:.0%} блоков темы (допуск {МИН_ПОКРЫТИЕ:.0%})")
                print("  ! П2т разложила по сюжетам не все блоки — каждый блок ровно в одном сюжете; "
                      "исправить и повторить")
                return _общее.КОНТРАКТ
            if дубли:
                print(f"{ид}: блоки в нескольких сюжетах: {', '.join(дубли[:8])}")
                print("  ! П2т положила блок в два сюжета — каждый блок ровно в одном сюжете; "
                      "исправить и повторить")
                return _общее.КОНТРАКТ
            чужие_цитаты = [(с["название"], ц) for с in р["сюжеты"] for ц in с["цитаты"]
                            if _b4.норм(ц) not in цитаты_блоков
                            and not any(_b4.норм(ц) in ц_б for ц_б in цитаты_блоков)]
            if чужие_цитаты:
                print(f"{ид}: цитат не из блоков темы: {len(чужие_цитаты)}")
                for где, ц in чужие_цитаты:
                    print(f"  ✗ {где}: {ц[:120]}")
                print("  ! П2т цитирует не блоки входа — исправить и повторить")
                return _общее.КОНТРАКТ
            if not р["сюжеты"]:
                print(f"{ид}: П2т не собрала ни одного сюжета — у кандидата блоки есть")
                return _общее.КОНТРАКТ

            сюжеты = []
            for с in р["сюжеты"]:
                блоки = [по_ид[i] for i in с["блоки"]]
                знаков = _общее.объём_блоков(агрегат, с["блоки"])
                части = sorted({б["часть_документа"] for б in блоки},
                               key=["начало", "середина", "конец"].index)
                с.get("голос")  # голос нужен П2т; во вход П4/П5 не кладём
                сюжеты.append({
                    **{k: с.get(k) for k in ("название", "актор", "бенефициар", "механизм",
                                             "расхождение_внутри_сюжета", "цитаты")},
                    "автономность": (с.get("автономность") or {}).get("есть"),
                    "почему_автономность": (с.get("автономность") or {}).get("почему"),
                    "блоки": list(с["блоки"]),
                    "блоков": len(блоки),
                    "полноценных_блоков": sum(1 for б in блоки if б["полнота"] in ПОЛНОЦЕННЫЙ),
                    "знаков": знаков,
                    "доля_документа": round(знаков / всего, 3),
                    "распределение": части,
                    "инструменты": sorted({i for б in блоки for i in (б.get("инструменты") or [])}),
                    "цитаты_инструментов": [б["цитата_инструмента"] for б in блоки if б.get("цитата_инструмента")],
                    "опоры_под_практику": [{"что": б["опора_под_практику"], "цитата": б.get("цитата_практики")}
                                           for б in блоки if б.get("опора_под_практику")],
                })
            сюжеты.sort(key=lambda с: -с["знаков"])
            т = темы_агрегата[ид]
            свод["темы"].append({
                "id": ид, "сюжеты": сюжеты,
                "блоки": sorted(свои_блоки),
                "фрагменты": т["фрагменты"],
                "знаков": т["знаков"], "доля_документа": т["доля_документа"],
                "распределение": т["распределение"],
            })
            вход_п4.append({
                "тема": ид,
                "папка": имя_папки,
                "материал": карта["материал"].get("заголовок_из_файла") or карта["материал"]["файл"],
                "карточка_темы": карточки[ид],
                "расчёт": {**{к: строки_к[ид].get(к) for к in ПОЛЯ_КАНДИДАТА},
                           "сюжеты": [с["название"] for с in сюжеты]},
                "карта": {**{к: карта.get(к) for к in ПОЛЯ_КАРТЫ}, "сюжеты": сюжеты},
            })

    json.dump(свод, open(os.path.join(папка, "10_сюжеты_сведены.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    with open(os.path.join(папка, "10_кандидаты_вход.jsonl"), "w", encoding="utf-8") as f:
        for с in вход_п4:
            f.write(json.dumps(с, ensure_ascii=False) + "\n")

    if not шортлист:
        print("кандидатов нет — свод сюжетов и вход П4/П5 пустые")
        return 0
    for т in свод["темы"]:
        print(f'{т["id"]}: сюжетов {len(т["сюжеты"])}, блоков {len(т["блоки"])}')
        for с in т["сюжеты"]:
            метки = []
            if с["автономность"]:
                метки.append("автономен")
            if с["инструменты"]:
                метки.append("инстр.: " + ", ".join(с["инструменты"]))
            if с["опоры_под_практику"]:
                метки.append(f'практика×{len(с["опоры_под_практику"])}')
            print(f'  {с["доля_документа"]:.0%}  блоков {с["блоков"]} (полноценных {с["полноценных_блоков"]})  '
                  f'{"/".join(с["распределение"])}  {с["название"][:45]}'
                  + (f'  [{"; ".join(метки)}]' if метки else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
