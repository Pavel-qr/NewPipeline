def экранировать(s):
    return (s or "").replace("|", "\\|").replace("\n", " ").strip()


def собрать_цитаты(объект, путь=""):
    """Все значения полей, названных цитатой, на любой глубине объекта."""
    if isinstance(объект, dict):
        for k, v in объект.items():
            if k.startswith("цитат") and isinstance(v, str) and v.strip():
                yield f"{путь}.{k}".lstrip("."), v
            elif k.startswith("цитат") and isinstance(v, list):
                for i, э in enumerate(v):
                    if isinstance(э, str) and э.strip():
                        yield f"{путь}.{k}[{i}]".lstrip("."), э
            else:
                yield from собрать_цитаты(v, f"{путь}.{k}".lstrip("."))
    elif isinstance(объект, list):
        for i, э in enumerate(объект):
            yield from собрать_цитаты(э, f"{путь}[{i}]")


def живые_ответы(сырьё, шортлист, файл, печать=print):
    """Оставляет из ответа модели только темы, которые сейчас в шортлисте кандидатов.

    О2 и О3 отвечают по списку `кандидаты` из 10_кандидаты.json — это темы,
    способные изменить исход. Ответ про тему, которой в шортлисте нет, — это
    ответ на вопрос, который больше не задают: карту пересобрали, баллы A
    пересчитали, шортлист стал другим, а файл ответа остался с прошлого прогона.

    Такой осадок не безобиден. o4 читает из П4 «ложное совпадение» и закрывает
    им строку, а из П5 — обоснование и флаги, и вписывает их в итог по теме,
    которую в этом прогоне никто не проверял. На 29 материалах такие ответы
    лежали в 21 папке.

    `тема: null` в шортлисте быть не может, и такой ответ тоже выбрасывается: с
    решения 12 П5 без кандидатов не зовётся, а по кандидату поле `тема`
    заполняется всегда (контракт П5). Строку без ответа ловит проверка полноты
    ниже — она и назовёт, по какому кандидату ответа нет.

    Здесь ловится только одна из двух порч: ответ про тему, которой уже нет.
    Ответ про живого кандидата, но собранный по старой карте, ловится дальше —
    сверкой цитат: его цитат в нынешней карте не найдётся, и шаг встанет.
    Это разделение намеренное: мёртвые данные молча не считаются, живые, но
    протухшие — останавливают прогон и требуют перезапуска модели."""
    темы = сырьё.get("темы") or []
    живые = [т for т in темы if т.get("тема") in шортлист]
    выброшено = [str(т.get("тема")) for т in темы if т not in живые]
    if выброшено:
        печать(f'  {файл}: не в шортлисте кандидатов, в расчёт не идут — '
               + ", ".join(выброшено))
    return {**сырьё, "темы": живые}


def проверить_цитаты(карта, файлы):
    """Модель на шагах О2 и О3 исходника не видит и цитировать может только свой
    вход — карту документа и сюжеты темы. Цитата, которой там нет, — признак
    того, что она пришла из памяти о тексте, а не из входа. Проверяем так же
    жёстко, как Б4 проверяет цитаты из исходника."""
    # Та же функция, что на Б4 и Б5: одна нормализация на все три проверки цитат.
    # Перенос строки внутри цитаты — след вёрстки PDF, а не содержания; ровно так же
    # не содержание — другое тире или заглавная буква в начале выдержки.
    свернуть = _b4.норм

    def строки(о):
        if isinstance(о, str):
            yield о
        elif isinstance(о, dict):
            for v in о.values():
                yield from строки(v)
        elif isinstance(о, list):
            for v in о:
                yield from строки(v)

    # Склеиваем значения карты, а не её JSON-запись: в записи перенос строки
    # хранится escape-последовательностью и до сравнения не доживает.
    текст_карты = "\n".join(свернуть(т) for т in строки(карта))
    чужие = []
    for имя, содержимое in файлы.items():
        for путь, ц in собрать_цитаты(содержимое):
            if свернуть(ц) not in текст_карты:
                чужие.append((имя, путь, ц))
    return чужие


