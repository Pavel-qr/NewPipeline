# -*- coding: utf-8 -*-
"""
Связка шага И3 (строка справочника авторов) с пайплайном.

  python3 _скрипты/авторы.py вход     материалы/<папка>
  python3 _скрипты/авторы.py записать материалы/<папка>

Два скриптовых шага вокруг одного модельного:

  [вход] → (если кого-то нет в справочнике) И3 модель → [записать]

Место в пайплайне — шаг 0, сразу после И1 и И2. Вход берётся из
`00_источник.json`: имена и регалии там уже разложены параллельными списками, и
`о_источник.py свести` проверил, что длины списков совпадают.

Строка заводится ОДИН РАЗ НА АВТОРА, а не на каждый его материал: у материала с
девятнадцатью авторами девятнадцать вызовов в первый раз и ноль во второй. Это
осознанная цена — справочник авторов нужен для атрибуции готовой единицы, а не
для отбора: в формулу `A + B + S + D` он не входит ни при каких условиях.

Про ключ. У организаций ключ приходит из реестра — ISSN, префикс ISBN, домен.
Реестрового номера на человека не существует, и раньше здесь сопоставляли по имени
со всеми его пороками: однофамильцы сливались в одного, другая транслитерация
заводила второго. Дубли приходилось объявлять штатным состоянием.

Теперь иначе. У автора почти всегда есть **адрес, выданный кем-то другим**:
страница автора на сайте издания, ORCID, канал, личный домен, профиль площадки. Он
не сочиняется нами и по нему субъекта можно найти второй раз — то есть он работает
ровно как ISSN у журнала. Отсюда правило без исключений:

    Строка заводится тогда и только тогда, когда найден адрес.
    Слияние — только по совпадению адреса, никогда по имени.

Совпадение имени больше ничего не решает. Оно лишь **триггер**: повод отправить
случай в И3 вместе с адресами уже заведённых однофамильцев, чтобы модель сравнила
адреса. Ответ «адреса нет» — полноценный: строки не будет, а имя и регалия
останутся у материала, и для подписи под готовой единицей этого хватает.

Ошибки тут не равны по цене. Лишняя строка — видимый дубль, его когда-нибудь
склеят. Ошибочное слияние двух людей — неверная атрибуция в готовой единице, и
заметить её нельзя ничем. Поэтому при любом сомнении — раздельно.
"""
import os, sys, json, re, unicodedata, importlib.util

def _библиотека(модуль, кто):
    import importlib.util as _iu
    сп = _iu.spec_from_file_location("общее", os.path.join(os.path.dirname(os.path.abspath(__file__)), "общее.py"))
    м = _iu.module_from_spec(сп); сп.loader.exec_module(м)
    return м.библиотека(модуль, кто)

from datetime import date

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ЗДЕСЬ)
ИМЯ = "авторы.xlsx"
ЛИСТ = "авторы"


def найти_таблицу():
    """Один путь на чтение и запись, тем же способом, что у источников и
    канонов: переменная окружения, затем `_канон/`."""
    из_среды = os.environ.get("СПРАВОЧНИК_АВТОРОВ")
    кандидаты = ([из_среды] if из_среды else []) + [os.path.join(КОРЕНЬ, "_канон", ИМЯ)]
    for п in кандидаты:
        if п and os.path.exists(п):
            return п
    raise SystemExit("не найден справочник " + ИМЯ + "; искал:\n  " + "\n  ".join(кандидаты))
ПЕРВАЯ_КОЛОНКА = "author_id"

# Не человек — строки не заводим: организация опознаётся справочником источников,
# дублировать её в авторах незачем (И3, раздел «Тип субъекта»).
НЕ_ЧЕЛОВЕК = {"организация", "редакция"}
ПРОЧЕРК = {"—", "-", "–", "", "нет", "null", "none"}


def норм(s):
    s = unicodedata.normalize("NFC", str(s or ""))
    s = (s.replace("«", '"').replace("»", '"').replace("“", '"').replace("”", '"')
          .replace("—", "-").replace("–", "-").replace("ё", "е").replace("Ё", "Е"))
    return re.sub(r"\s+", " ", s).strip().lower()


def читать_справочник(путь=None):
    """Строки справочника авторов. Шапка ищется по первой колонке, а не по
    номеру строки: над таблицей лежит пояснение для человека, и его длина
    меняется."""
    openpyxl = _библиотека("openpyxl", "авторы")
    ws = openpyxl.load_workbook(путь or найти_таблицу())[ЛИСТ]
    шапка = None
    for r in ws.iter_rows(values_only=True):
        if r and r[0] == ПЕРВАЯ_КОЛОНКА:
            шапка = [str(h).strip() if h else "" for h in r]
            continue
        if шапка is None or not r or not r[0]:
            continue
        yield {h: v for h, v in zip(шапка, r) if h}


def норм_адрес(a):
    """Адрес для сравнения: без схемы, www и хвостовой косой черты.

    `https://health.harvard.edu/author/x/` и `health.harvard.edu/author/x` — один
    адрес. Регистр снимается у домена и пути целиком: адреса, различающиеся только
    им, в реестрах не встречаются, а вот записанные по-разному — сплошь и рядом."""
    a = норм(a)
    a = re.sub(r"^\w+://", "", a)
    a = re.sub(r"^www\.", "", a)
    return a.rstrip("/")


def по_адресу(адрес, строки):
    """Строка справочника с этим адресом. Единственный способ опознать автора."""
    a = норм_адрес(адрес)
    if not a:
        return None
    for с in строки:
        if норм_адрес(с.get("адрес")) == a:
            return с
    return None


def однофамильцы(имя, строки):
    """Строки, где такое же имя уже заведено — по имени или по варианту написания.

    Это НЕ опознание. Совпавшее имя ничего не доказывает: однофамильцы существуют,
    и решать за них по написанию — то самое ошибочное слияние, которое потом
    нечем заметить. Список идёт в И3 вместе с адресами, и сравнивает модель
    адреса, а не имена."""
    и = норм(имя)
    if not и:
        return []
    свои = []
    for с in строки:
        если = [норм(с.get("автор"))] + [норм(в) for в in
                str(с.get("варианты написания") or "").split("|")]
        if и in если:
            свои.append(с)
    return свои


def _список(значение):
    return _общее().список_авторов(значение)


def разложить(поля):
    """Имена и регалии — два параллельных списка. Их равенство уже проверено на
    `о_источник.py свести`, здесь только раскладка по парам."""
    имена = _список(поля.get("author_name"))
    регалии = _список(поля.get("author_credential"))
    if len(регалии) != len(имена):
        регалии = регалии + ["—"] * (len(имена) - len(регалии))
    return list(zip(имена, регалии[:len(имена)]))


def писать(папка, имя, данные):
    п = os.path.join(папка, имя)
    with open(п, "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False, indent=2)
    print(f"  → {п}")


# --------------------------------------------------------------------- вход
def вход(папка):
    """00_авторы_вход.jsonl — по строке на автора, которого этот материал ещё не
    опознал.

    Файл пишется всегда, в том числе пустым: пустой означает «по этому материалу
    все авторы уже опознаны», и оркестратор по нему пропускает И3. Отсутствие
    файла означало бы «шаг не выполнялся» — это разные вещи.

    Совпадение имени со строкой справочника поводом пропустить шаг больше НЕ
    является: имя не ключ. Такой автор идёт в И3 вместе с адресами тёзок — это и
    есть проверка личности."""
    _общее().входы_шага(папка, "авторы.py вход")
    п = os.path.join(папка, "00_источник.json")
    источник = json.load(open(п, encoding="utf-8"))
    поля = источник.get("поля") or {}
    тип = поля.get("author_type")

    выход = os.path.join(папка, "00_авторы_вход.jsonl")
    пары = разложить(поля)

    if not пары:
        open(выход, "w", encoding="utf-8").close()
        print("  автора у материала нет — строка не заводится")
        return 0
    if тип in НЕ_ЧЕЛОВЕК:
        open(выход, "w", encoding="utf-8").close()
        print(f"  автор — {тип}, отдельная строка в авторах не нужна")
        return 0

    строки = list(читать_справочник())
    моя_папка = os.path.basename(папка.rstrip("/"))
    нужны, были = [], []
    for имя, регалия in пары:
        тёзки = однофамильцы(имя, строки)
        # Единственный случай, когда шаг пропускается без вызова модели: этот
        # материал уже записан в строку автора. Тогда опознание по нему уже
        # состоялось, и повторять его незачем. Это сверка по папке, а не по
        # имени, — факт, а не суждение.
        уже = [с for с in тёзки
               if моя_папка in [ч.strip() for ч in
                                str(с.get("материалы_в_базе") or "").split(",")]]
        if уже:
            были.append(имя)
            continue
        нужны.append({
            "имя_в_материале": имя,
            "регалия_в_материале": None if норм(регалия) in ПРОЧЕРК else регалия,
            "язык_оригинала": поля.get("original_language"),
            "папка": моя_папка,
            "издание": поля.get("publisher"),
            "название_материала": поля.get("title"),
            "источник_url": поля.get("source_url"),
            # Главное поле, когда оно непустое: адреса уже заведённых тёзок.
            # Совпадение имени само по себе не значит ничего, и раньше оно молча
            # значило «это он» — шаг пропускался, материал приписывался чужой
            # строке. Теперь вопрос к модели ставится прямо: тот же это человек,
            # что в строке `<id>`, или другой, — а отвечает на него сравнение
            # адресов.
            "однофамильцы": [{"author_id": с.get(ПЕРВАЯ_КОЛОНКА),
                              "автор": с.get("автор"),
                              "адрес": с.get("адрес"),
                              "вид_адреса": с.get("вид_адреса"),
                              "описание": с.get("описание")}
                             for с in тёзки],
        })

    with open(выход, "w", encoding="utf-8") as f:
        for з in нужны:
            f.write(json.dumps(з, ensure_ascii=False) + "\n")
    со_столкновением = sum(1 for з in нужны if з["однофамильцы"])
    print(f"  авторов у материала: {len(пары)}, уже опознаны по этому материалу: "
          f"{len(были)}, нужен И3: {len(нужны)}"
          + (f" (из них со столкновением имён: {со_столкновением})"
             if со_столкновением else ""))
    if нужны:
        print("  → " + выход)
    return 0


# ----------------------------------------------------------------- записать

def _ряд_по_ид(ws, ряд_шапки, шапка, ид):
    """Номер ряда листа по author_id. Нужен, чтобы дописать материал в готовую
    строку: `читать_справочник` отдаёт значения, а не адреса ячеек."""
    if not ид:
        return None
    колонка = шапка.index(ПЕРВАЯ_КОЛОНКА) + 1
    for ряд in range(ряд_шапки + 1, ws.max_row + 1):
        if норм(ws.cell(ряд, колонка).value) == норм(ид):
            return ряд
    return None


def _значение(поле):
    """И3 возвращает поля объектами {значение, как_получено, чем} — кроме
    простых. Разворачиваем и то, и другое одинаково."""
    if isinstance(поле, dict) and "значение" in поле:
        return поле["значение"]
    return поле


def _общее():
    сп = importlib.util.spec_from_file_location("общее", os.path.join(ЗДЕСЬ, "общее.py"))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


def записать(папка):
    """Запись в справочник — под замком на всё чтение-правку-сохранение (Д-5)."""
    with _общее().блокировка(найти_таблицу()):
        return _записать(папка)


def _записать(папка):
    _общее().входы_шага(папка, "авторы.py записать")
    п = os.path.join(папка, "00_авторы.jsonl")
    # Контракт — там, где ответ модели впервые читают, до записи в канон. И3 был
    # единственным модельным шагом без этой проверки: значение вне закрытого
    # списка уезжало прямо в справочник.
    сп = importlib.util.spec_from_file_location("контракты", os.path.join(ЗДЕСЬ, "контракты.py"))
    _к = importlib.util.module_from_spec(сп); сп.loader.exec_module(_к)
    ответы = [json.loads(с) for с in open(п, encoding="utf-8") if с.strip()]
    if _к.стоп("И3", ответы, os.path.basename(папка.rstrip("/")), папка):
        return 4
    openpyxl = _библиотека("openpyxl", "авторы")
    СПРАВОЧНИК = найти_таблицу()
    кн = openpyxl.load_workbook(СПРАВОЧНИК)
    ws = кн[ЛИСТ]
    ряд_шапки = next(i for i, r in enumerate(ws.iter_rows(values_only=True), 1)
                     if r and r[0] == ПЕРВАЯ_КОЛОНКА)
    шапка = [c.value for c in ws[ряд_шапки]]
    было = list(читать_справочник())
    занятые = {норм(с.get(ПЕРВАЯ_КОЛОНКА)) for с in было}

    заведено, дописано, обновлено, без_адреса = [], [], [], []
    тронуто = False
    for строка_текстом in open(п, encoding="utf-8"):
        строка_текстом = строка_текстом.strip()
        if not строка_текстом:
            continue
        о = {к: _значение(v) for к, v in json.loads(строка_текстом).items()}
        имя = о.get("автор")
        адрес = о.get("адрес")
        вид = о.get("вид_адреса")

        # 0. Этот материал уже опознал этого автора — значит ответ не новый, а
        #    ПОВТОРНЫЙ, и он обновляет готовую строку. Так бывает не только при
        #    правке правил: годовой прогон добирает описание у строк со статусом
        #    «ждёт описания», и без этой ветки он заводил бы вторых тех же людей.
        #    Опознание идёт по паре «папка + имя», а не по адресу: адрес как раз и
        #    мог измениться — ради этого ответ и переспрашивали.
        моя_папка = os.path.basename(папка.rstrip("/"))
        своя_строка = None
        for с in однофамильцы(имя, было):
            папки_строки = [ч.strip() for ч in
                            str(с.get("материалы_в_базе") or "").split(",")]
            if моя_папка in папки_строки:
                своя_строка = с
                break
        if своя_строка is not None:
            ряд_строки = _ряд_по_ид(ws, ряд_шапки, шапка, своя_строка.get(ПЕРВАЯ_КОЛОНКА))
            # Строка прочитана из этой же таблицы, значит её ряд обязан
            # найтись. Не нашёлся — таблица изменилась под рукой или
            # идентификатор битый; раньше печаталось «строка обновлена», а
            # записи не было.
            if ряд_строки is None:
                raise SystemExit(f'авторы: строка «{своя_строка.get(ПЕРВАЯ_КОЛОНКА)}» '
                                 f'({имя}) есть в прочитанном справочнике, но её ряд в '
                                 f'листе не найден — запись невозможна')
            измен = []
            for колонка, значение in (("адрес", адрес), ("вид_адреса", вид),
                                      ("профиль", о.get("профиль")),
                                      ("где проверено", о.get("где_проверено")),
                                      ("описание", о.get("описание")),
                                      ("признанность", о.get("признанность")),
                                      ("почему_признанность", о.get("почему_признанность")),
                                      ("статус", о.get("статус"))):
                if колонка in шапка and значение not in (None, "") \
                        and значение != своя_строка.get(колонка):
                    ws.cell(ряд_строки, шапка.index(колонка) + 1, значение)
                    своя_строка[колонка] = значение
                    измен.append(колонка)
            if измен:
                тронуто = True
                if "проверено_дата" in шапка:
                    ws.cell(ряд_строки, шапка.index("проверено_дата") + 1, str(date.today()))
            обновлено.append((своя_строка.get(ПЕРВАЯ_КОЛОНКА), имя, измен))
            continue

        # 1. Адреса нет — строки нет. Это не пропуск и не неудача: субъекта,
        #    которого нельзя найти второй раз, нельзя ни подтвердить, ни
        #    опровергнуть, ни склеить. Имя и регалия остаются у материала.
        if not норм_адрес(адрес) or норм(вид) == "нет":
            без_адреса.append({"автор": имя,
                               "тёзки": [с.get(ПЕРВАЯ_КОЛОНКА)
                                         for с in однофамильцы(имя, было)],
                               "что_искал": о.get("что_искал")})
            continue

        # 2. Адрес совпал с уже заведённым — это тот же автор. Строка не
        #    дублируется, материал дописывается к ней. Единственный законный
        #    способ слияния.
        своя = по_адресу(адрес, было)
        if своя:
            папки = [ч.strip() for ч in
                     str(своя.get("материалы_в_базе") or "").split(",") if ч.strip()]
            ряд_строки = _ряд_по_ид(ws, ряд_шапки, шапка, своя.get(ПЕРВАЯ_КОЛОНКА))
            if ряд_строки is None:
                raise SystemExit(f'авторы: строка «{своя.get(ПЕРВАЯ_КОЛОНКА)}» ({имя}) есть в '
                                 f'прочитанном справочнике, но её ряд в листе не найден')
            if моя_папка not in папки:
                папки.append(моя_папка)
                ws.cell(ряд_строки, шапка.index("материалы_в_базе") + 1, ", ".join(папки))
                тронуто = True
            своя["материалы_в_базе"] = ", ".join(папки)
            дописано.append((своя.get(ПЕРВАЯ_КОЛОНКА), имя))
            continue

        # 3. Адрес новый — новая строка, даже если имя совпало с чужой. Разные
        #    адреса не доказывают разных людей (у одного бывает и ORCID, и
        #    канал), но и одного человека из двух они не делают: слить их может
        #    только человек, по свидетельству, где оба адреса названы вместе.
        ид = о.get("author_id_предложение") or норм(имя).replace(" ", "_")
        # Столкновение идентификаторов разводится суффиксом, а не перезаписью:
        # двух разных людей нельзя схлопнуть в одну строку из-за однофамильца.
        основа, n = ид, 2
        while норм(ид) in занятые:
            ид, n = f"{основа}_{n}", n + 1
        занятые.add(норм(ид))

        варианты = о.get("варианты_написания")
        if isinstance(варианты, list):
            варианты = "|".join(в for в in варианты if в)
        что_искал = о.get("что_искал")
        if isinstance(что_искал, list):
            что_искал = "; ".join(что_искал)

        значения = {
            ПЕРВАЯ_КОЛОНКА: ид,
            "автор": имя,
            "варианты написания": варианты,
            "тип": о.get("тип"),
            "author_credential": о.get("author_credential"),
            "описание": о.get("описание"),
            "признанность": о.get("признанность"),
            "почему_признанность": о.get("почему_признанность"),
            # Адрес — ключ строки: по нему её находят впредь. «Где проверено» —
            # другое: это страница, по которой опознали сейчас. Путать их дорого,
            # поэтому колонки разные.
            "адрес": адрес,
            "вид_адреса": вид,
            "orcid": о.get("orcid"),
            "профиль": о.get("профиль"),
            "где проверено": о.get("где_проверено"),
            "проверено_дата": str(date.today()),
            "статус": о.get("статус"),
            "материалы_в_базе": os.path.basename(папка.rstrip("/")),
            "заметка": о.get("заметка"),
            "что_искал": что_искал,
        }
        ряд = ws.max_row + 1
        for i, имя_колонки in enumerate(шапка, 1):
            ws.cell(ряд, i, значения.get(имя_колонки))
        заведено.append((ид, имя, о.get("признанность")))
        было.append(значения)
        тронуто = True

    # Файл пересохраняется только если в него что-то записано: openpyxl
    # сериализует книгу заново, и «сохранить без изменений» меняет байты — для
    # отпечатков (Д-4) это правка канона, и `авторы.py вход` устаревал бы на
    # каждом прогоне.
    if тронуто:
        кн.save(СПРАВОЧНИК)
    for ид, имя, р in заведено:
        print(f"  + {ид}: {имя}, признанность {р}")
    for ид, имя in дописано:
        print(f"  = {ид}: {имя} — адрес совпал, материал дописан к строке")
    for ид, имя, поля in обновлено:
        print(f"  ~ {ид}: {имя} — строка обновлена"
              + (f" ({', '.join(поля)})" if поля else ": изменений нет"))
    for б in без_адреса:
        хвост = (f"; имя совпало с {', '.join(б['тёзки'])}, подтверждения нет"
                 if б["тёзки"] else "")
        print(f"  · {б['автор']} — адреса нет, строка не заводится{хвост}")
    # Отчёт — то, чем материал связан со справочником. `атрибуты.py` берёт
    # author_id отсюда, а не из имени: связь ставит тот шаг, который её
    # установил, и ровно там, где он это сделал.
    писать(папка, "00_авторы_записаны.json",
           {"заведено": [{"author_id": и, "автор": а, "признанность": р}
                         for и, а, р in заведено],
            "дописано": [{"author_id": и, "автор": а} for и, а in дописано],
            "обновлено": [{"author_id": и, "автор": а, "поля": п}
                          for и, а, п in обновлено],
            "без_адреса": без_адреса,
            "дата": str(date.today())})
    return 0


КОМАНДЫ = {"вход": вход, "записать": записать}

