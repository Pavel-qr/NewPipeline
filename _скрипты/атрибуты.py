def состояние_авторов(отчёт):
    """Одна фраза про то, чем кончилось опознание авторов материала.

    Пусто — шаг И3 по этому материалу не делался. Всё остальное — названный
    результат: сколько опознано, у скольких адреса не нашлось и с кем из
    справочника совпало имя без подтверждения."""
    if not отчёт:
        return None
    опознано = len(отчёт.get("заведено") or []) + len(отчёт.get("дописано") or [])
    без = отчёт.get("без_адреса") or []
    части = []
    if опознано:
        части.append(f"опознан{'ы' if опознано > 1 else ''}: {опознано}")
    for б in без:
        тёзки = б.get("тёзки") or []
        части.append(f"{б.get('автор')} — адреса нет" +
                     (f", имя совпало с {', '.join(тёзки)}, подтверждения нет"
                      if тёзки else ""))
    return "; ".join(части) or None


def читать(папка, имя):
    """Нет файла — None («ещё не собрано»). Файл есть, но не читается — отказ с
    именем: раньше это тоже давало None, и сломанный разбор красился в листе
    как «поле пайплайн пока не собирает»."""
    п = os.path.join(папка, имя)
    if not os.path.exists(п):
        return None
    try:
        return json.load(open(п, encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError) as сбой:
        raise SystemExit(f"атрибуты: {п} не читается: {сбой} — разбор сломан, а не «не собран»")


def найти_исходники(корень_материалов=None):
    """Корпус исходников — один, объявлен в `общее.py`. Раньше здесь перебирались
    три места, и первое найденное побеждало."""
    return _модуль("общее", "общее.py").корень_корпуса("атрибуты")


def строка_материала(папка):
    мета = читать(папка, "00_мета.json") or {}
    карта = читать(папка, "04_карта.json") or {}
    итог = читать(папка, "13_итог.json") or {}
    загрузка = читать(папка, "загрузка.json") or {}

    материал = карта.get("материал") or {}
    источник = карта.get("источник") or {}
    оценка = источник.get("оценка") or {}
    из_файла = мета.get("из_файла") or {}
    атрибуция = карта.get("атрибуция") or {}
    # Связь «материал ↔ автор» ставит шаг И3 и пишет её в свой отчёт. Читать её
    # надо оттуда, а не из имени в карте: имя не ключ, и приписывать материал
    # строке справочника по совпадению написания — это то самое ошибочное
    # слияние, которого нельзя заметить потом.
    авторы = читать(папка, "00_авторы_записаны.json") or {}

    имя_файла = мета.get("исходник") or материал.get("файл")
    строки = итог.get("строки") or []
    принятые = [с for с in строки if с.get("вердикт") == "✅"]

    return {
        "папка": os.path.basename(папка),
        "material_id": материал.get("material_id"),

        "file_name": имя_файла,
        "file_format": мета.get("формат") or (
            os.path.splitext(имя_файла)[1].lstrip(".").lower() if имя_файла else None),
        "pages": мета.get("страниц") or материал.get("страниц"),
        "length_chars": мета.get("знаков") or материал.get("знаков_всего"),
        "length_chars_content": материал.get("знаков_содержательных"),
        "content_format": мета.get("content_format"),
        "file_language": мета.get("file_language"),
        "needs_ocr": ("да" if мета.get("нужен_ocr") else
                      ("нет" if "нужен_ocr" in мета else None)),
        "doi": мета.get("doi") or источник.get("doi"),
        "issn": мета.get("issn") or источник.get("issn"),
        "isbn": мета.get("isbn") or источник.get("isbn"),

        "title": источник.get("название") or материал.get("заголовок_из_файла")
                 or из_файла.get("title"),
        "author_name": источник.get("автор") or из_файла.get("author"),
        "author_credential": источник.get("author_credential"),
        "publisher": источник.get("издание"),
        "publication_date": источник.get("дата"),
        "year": источник.get("year"),
        # Без `or источник.get("тип")`: `тип` — снятое поле П2 со свободным
        # текстом, и через этот запасной путь он попадал в колонку, где И1
        # задаёт закрытый список. Пусто честнее, чем «внутренний документ
        # организации, гриф „для служебного пользования"» в графе типа.
        "material_type": источник.get("material_type"),
        "original_language": источник.get("original_language"),
        "license": источник.get("license"),
        "source_url": источник.get("source_url"),
        "access_type": источник.get("access_type"),
        # Отрасль — факт о содержании, а не об источнике: она переехала на
        # верхний уровень карты вместе с разделением контрактов И1 и П2.
        # `или` — для карт, собранных до разделения.
        "industry": (карта.get("отрасль_материала")
                     or источник.get("отрасль_материала")),
        "key_concepts": ", ".join(карта.get("key_concepts") or []) or None,

        # Канал записан в 00_мета.json шагом Б1 по пути оригинала — обратную
        # дорогу обходом корпуса по имени файла больше не восстанавливают.
        "acquisition": загрузка.get("acquisition") or мета.get("канал"),
        "added_at": загрузка.get("added_at"),

        "publisher_id": оценка.get("организация"),
        "publisher_type": оценка.get("тип") or оценка.get("процесс"),
        # Перечень поисковых запросов И1 доезжал до карты и там останавливался.
        # Это то, чем объясняется «автор не найден»: видно, искали или не искали.
        "что_искал": "; ".join((источник.get("опознание") or {}).get("что_искал") or []) or None,
        "S": оценка.get("S_база"),
        "author_id": ", ".join(
            [а.get("author_id") for а in (авторы.get("заведено") or [])] +
            [а.get("author_id") for а in (авторы.get("дописано") or [])]) or None,
        # Пустой author_id читается двояко — «не опознан» или «не заполняли», —
        # и колонка состояния эту разницу называет. Отдельный случай: имя
        # совпало с опознанным автором, а подтверждения нет. Против данных это
        # ничего не значит, а против глаз значит всё: человек, увидев одно имя
        # в материале и в справочнике, достроит связь сам.
        "автор_опознан": состояние_авторов(авторы),
        "author_orcid": источник.get("author_orcid"),
        "проверено_дата": оценка.get("проверено_дата"),

        "строка_атрибуции": атрибуция.get("строка"),
        "атрибуция_полная": атрибуция.get("полнота"),

        "тем_принято": len(принятые) if строки else None,
        "баллы_тем": ", ".join(str(с.get("балл")) for с in принятые) or None,
        "жанр": (карта.get("жанр") or {}).get("тип"),
    }


def собрать(корень=None):
    # Корень — от расположения скрипта, не от cwd; ноль папок — отказ: раньше
    # из чужой директории лист выходил пустым, а напротив каждой колонки
    # печаталось «не собирается» — диагноз пайплайну вместо «папка не нашлась».
    о = _модуль("общее", "общее.py")
    корень = о.корень_материалов(корень, "атрибуты")
    папки = о.папки_материалов(корень, "атрибуты")
    return [строка_материала(п) for п in папки]




# ------------------------------------------------------------------ входящие
ЧИТАЕМЫЕ = {".pdf", ".docx"}          # то, что умеет b1_нормализация
ПРОПУСК = {".ds_store", ".tmp", ".part"}


def входящие(корень_материалов):
    """[(файл, канал, размер, формат, статус)] по файлам, у которых ещё нет папки.

    Канал — папка верхнего уровня в исходниках: ЧД, ПОИСК, ПАРСИНГ, СБ, база_А.
    Это acquisition, единственное поле, которое заполняет человек, — и заполняет
    он его раскладкой файлов, а не таблицей. Файл в корне исходников канала не
    имеет: его положили мимо раскладки, и это видно."""
    # Корпуса нет — отказ с адресом (`общее.корень_корпуса`), а не пустой лист.
    исходники = найти_исходники(корень_материалов)
    разобраны = set()
    for папка in sorted(glob.glob(os.path.join(корень_материалов, "*"))):
        if not os.path.isdir(папка):
            continue
        мета = читать(папка, "00_мета.json") or {}
        карта = читать(папка, "04_карта.json") or {}
        for имя in (мета.get("исходник"), ((карта.get("материал") or {}).get("файл"))):
            if имя:
                разобраны.add(_имена.ключ(имя))

    строки = []
    for путь, _, файлы in os.walk(исходники):
        for ф in sorted(файлы):
            расш = os.path.splitext(ф)[1].lower()
            if ф.startswith(".") or расш in ПРОПУСК:
                continue
            if _имена.ключ(ф) in разобраны:
                continue
            отн = os.path.relpath(путь, исходники)
            канал_ = отн.split(os.sep)[0] if отн != "." else "не разложен"
            мб = os.path.getsize(os.path.join(путь, ф)) / 1048576
            статус = ("ожидает разбора" if расш in ЧИТАЕМЫЕ
                      else f"нет читателя для {расш} — нужен PDF")
            строки.append((ф, канал_, round(мб, 1), расш.lstrip("."), статус))
    строки.sort(key=lambda с: (с[4] == "ожидает разбора", с[1], с[0]))
    return строки


if __name__ == "__main__":
    корень = sys.argv[1] if len(sys.argv) > 1 else None
    строки = собрать(корень)
    print(f"материалов: {len(строки)}, колонок: {len(КОЛОНКИ)}\n")
    print(f'{"атрибут":24} {"заполнено":>10}')
    for имя, _ in КОЛОНКИ:
        n = sum(1 for с in строки if с.get(имя) not in (None, "", []))
        метка = "" if n else "   ← не собирается"
        print(f"{имя:24} {n:>6} / {len(строки)}{метка}")
