"""
Таблица атрибутов: одна строка на материал, колонки — из `атрибуты_спецификация.xlsx`.

  python3 _скрипты/атрибуты.py            — напечатать, чего сколько собрано
Используется из `сводная.py`: лист «Атрибуты».

Зачем отдельно от сводной. Сводная отвечает на вопрос «что принято по темам» —
строка там на тему, и одна и та же книга занимает четыре строки. Здесь строка на
материал и колонки те, что описаны в спецификации: что за документ, кто за ним
стоит, откуда пришёл. Это разрез не про отбор, а про саму базу материалов.

Главное свойство таблицы: **пустая ячейка значит, что поле ещё не собирается**.
Спецификация описывает сорок с лишним атрибутов, а пайплайн сегодня заполняет
меньше половины: шага опознания (И1) нет, файла загрузки нет, справочника
авторов в прогоне нет. Показывать это пустотой честнее, чем прятать колонку:
видно ровно, чего не хватает, и сколько работы до полной карточки.

Откуда что берётся — написано в самой спецификации, колонка «где оседает».
Здесь только чтение готовых файлов, ни одного вызова модели и ни одного суждения.
"""
import os, sys, json, glob, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))


def _модуль(имя, файл):
    сп = importlib.util.spec_from_file_location(имя, os.path.join(ЗДЕСЬ, файл))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


_имена = _модуль("имена", "имена.py")

