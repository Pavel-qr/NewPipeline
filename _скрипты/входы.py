# -*- coding: utf-8 -*-
"""
Проверка полноты входов перед расчётом.

Зачем. 16 сентября `o4_скоринг.py` посчитал 16_weak_ties и выдал балл 5 вместо 0:
файла `11_проверка.json` не было, скрипт молча подставил пустой список тем, не
увидел отметки «ложное совпадение» и посчитал строку как живую. Результат
выглядел совершенно нормально — ни ошибки, ни предупреждения.

Дыра не в том, что файл потерялся, а в том, что у каждого чтения стояло значение
по умолчанию. `читать("11_проверка.json", {"темы": []})` не отличает «проверка
прошла, ложных совпадений нет» от «проверки не было вовсе». Первое — факт,
второе — отсутствие данных, и складывать их в одно значение нельзя.

Отсюда правило: скрипт, который считает, обязан сначала убедиться, что считать
есть из чего, и при нехватке падать с именем недостающего файла. Молчаливый
пропуск хуже падения: падение видно сразу, а неверное число живёт в таблице,
пока кто-нибудь его случайно не перепроверит.

Условная часть. Не все файлы обязаны существовать всегда: `11_проверка.json` и
`12_скоринг.json` появляются, только если модели было о ком отвечать. Если все
кандидаты закрыты свойством текста или не дотянули до A = 4, О2 и О3 не
вызываются, и отсутствие обоих файлов — законное состояние, а не пропажа
"""
import os, json, importlib.util


def _общее():
    сп = importlib.util.spec_from_file_location(
        "общее", os.path.join(os.path.dirname(os.path.abspath(__file__)), "общее.py"))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


def _шаги():
    сп = importlib.util.spec_from_file_location(
        "шаги", os.path.join(os.path.dirname(os.path.abspath(__file__)), "шаги.py"))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


def _есть(папка, имя):
    return os.path.exists(os.path.join(папка, имя))


def живые_кандидаты(папка):
    """Шортлист кандидатов — темы, по которым зовутся П4 и П5. Список считает
    `o1_баллы.py` (A >= порога и не закрыты свойством текста) и кладёт в
    `10_кандидаты.json` под ключом `кандидаты`; здесь он только читается — второй
    копии правила нет. Пустой список — П4 и П5 не зовутся, их файлы законно
    отсутствуют."""
    п = os.path.join(папка, "10_кандидаты.json")
    if not os.path.exists(п):
        return []
    try:
        return list((json.load(open(п, encoding="utf-8")) or {}).get("кандидаты") or [])
    except json.JSONDecodeError as сбой:
        # Битый файл — не «кандидатов нет»: иначе О2 и О3 молча пропускаются.
        raise SystemExit(f"{п} не читается как JSON: {сбой}")


def проверить(папка, обязательные, условные=()):
    """Возвращает список недостающих файлов. Условные проверяются только тогда,
    когда в папке есть живые кандидаты."""
    нет = [и for и in обязательные if not _есть(папка, и)]
    if условные and живые_кандидаты(папка):
        нет += [и for и in условные if not _есть(папка, и)]
    # битый JSON — та же пропажа: считать по нему нельзя
    # list + tuple роняет сложение типом: скрипты передают сюда и списки, и
    # кортежи. Приводим оба к списку — иначе проверка на битый JSON падает
    # ровно там, где должна была сработать.
    for и in list(обязательные) + list(условные):
        if not _есть(папка, и):
            continue
        try:
            if и.endswith(".json"):
                json.load(open(os.path.join(папка, и), encoding="utf-8"))
            elif и.endswith(".jsonl"):
                for н, строка in enumerate(open(os.path.join(папка, и), encoding="utf-8"), 1):
                    if строка.strip():
                        json.loads(строка)
        except json.JSONDecodeError as e:
            нет.append(f"{и} (не читается как JSON: {e})")
    return нет


def требовать(папка, обязательные, условные=(), кто=""):
    """Падает с именами недостающих файлов. Никаких значений по умолчанию."""
    нет = проверить(папка, обязательные, условные)
    if нет:
        raise SystemExit(
            f'{кто or "расчёт"}: не хватает входов в {папка} — считать нельзя.\n  '
            + "\n  ".join(нет)
            + "\n\nЭто не предупреждение: на неполных входах скрипт посчитает "
              "неверно и не заметит. Прогоните недостающие шаги или заберите файлы.")


def требовать_шага(папка, чем, кто=None):
    """Входы шага по объявлению `шаги.py`: файлы папки, объявленные входами
    шага `чем` («b2_структура.py», «о_уровень.py вход»), кроме необязательных.
    Исходник и канон сюда не входят — их проверяет сам шаг, открывая.

    Один вызов в начале `main` вместо списка файлов в каждом скрипте: список
    входов записан один раз, в объявлении, и скрипт, читающий больше, чем
    объявил, ловит `карта_файлов.py`. До 17 сентября `требовать` стоял в двух
    скриптовых шагах из одиннадцати, остальные падали
    трассировкой `FileNotFoundError` или, хуже, читали пустое значение."""
    ш = _шаги()
    шаги_ = [с for с in ш.ШАГИ if с["чем"] == чем]
    if not шаги_:
        raise SystemExit(f"{кто or чем}: шага «{чем}» нет в объявлении шаги.py")
    обязательные = [в for с in шаги_ for в in ш.файлы_входа(с) if в not in с["необязательные"]]
    требовать(папка, обязательные, кто=кто or чем)


# Набор входов О4 — из объявления шагов, не копия: `o4_скоринг.py` требует ровно
# это, и команда ниже проверяет ровно это же, чтобы проверка руками и проверка
# на расчёте не разошлись.
_О4 = next(ш for ш in _шаги().ШАГИ if ш["чем"] == "o4_скоринг.py")
ВХОДЫ_О4 = tuple(в for в in _О4["входы"] if в not in _О4["необязательные"])
УСЛОВНЫЕ_О4 = _О4["необязательные"]


def main(корень=None):
    """Пройти по всем папкам и сказать, где считать нельзя.

    Раньше этого блока не было: `входы.py` работал только как библиотека, и
    `python3 _скрипты/входы.py материалы` молча выходил с нулём — выглядело так,
    будто проверка прошла. Предохранитель, который нельзя запустить и посмотреть,
    доверия не добавляет.

    Корень — от расположения скрипта, не от cwd (`общее.корень_материалов`):
    запущенный из чужой директории, сторож раньше печатал «папок: 0» и «все
    считаны на полных входах» с кодом 0. Ноль папок — отказ.
    """
    о = _общее()
    корень = о.корень_материалов(корень, "входы")
    папки = о.папки_материалов(корень, "входы")
    # Полнота входов — для КАЖДОГО шага, чей выход в папке есть, по объявлению
    # `шаги.py`; раньше проверялся один О4. Необязательные входы
    # (11_проверка.json и 12_скоринг.json у О4, свод У1 у реестра) вправе
    # отсутствовать.
    _ш = _шаги()
    считанные = [d for d in папки if _есть(d, "13_итог.json")]
    плохие = 0
    for д in папки:
        нет = []
        for ш in _ш.ШАГИ:
            if not all(_есть(д, ф) for ф in ш["выходы"] if ф not in ш["условные"]):
                continue
            # Заявка (условный выход) после исполнения снимается — её отсутствие
            # у сделанного шага законно.
            обязательные = [в for в in _ш.файлы_входа(ш)
                            if в not in ш["необязательные"] and в not in _ш.условные_выходы()]
            нет += [f'{ш["код"]} {ш["чем"]}: {н}' for н in проверить(д, обязательные)]
        if _есть(д, "13_итог.json"):
            нет += проверить(д, ВХОДЫ_О4, УСЛОВНЫЕ_О4)
        if нет:
            плохие += 1
            print(f"✗ {os.path.basename(д)}")
            for н in dict.fromkeys(нет):
                print(f"    {н}")
    незавершённые = len(папки) - len(считанные)
    print(f"\nпапок: {len(папки)} | посчитано до итога: {len(считанные)} | "
          f"ещё в работе: {незавершённые}")
    if плохие:
        print(f"папок с выходами без входов: {плохие} — числа в них недостоверны")
        return 1
    print("у каждого шага, чей выход есть, на месте и все его входы")
    return 0


if __name__ == "__main__":
    import sys
    raise SystemExit(main(sys.argv[1] if len(sys.argv) > 1 else None))
