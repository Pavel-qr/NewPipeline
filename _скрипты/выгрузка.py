# -*- coding: utf-8 -*-
"""
В — выгрузка принятого материала для аналитика (скрипт, без модели).
Вход:  реестр.json, 13_итог.json, 04_карта.json, 04_агрегат.json, 00_текст.txt,
       00_мета.json, 00_источник.json, отбор.md, 00_авторы.jsonl (если И3 был),
       оригинал материала, справочник авторов, канон уровней
Выход: выгружено.json — в папке материала: что и куда выгружено (или почему нет);
       выгрузка/<папка>/ — папка для аналитика по контракту `контракты.ВЫГРУЗКА`.

  python3 _скрипты/выгрузка.py материалы/<папка> <исходник>

Последний шаг прогона. Выгружается только принятый материал — тот, у которого
в `13_итог.json` есть хотя бы одна строка с вердиктом ✅; у остальных шаг пишет
`выгружено.json` с причиной и папку не создаёт. Пограничный (⚠) не выгружается:
решение о нём ещё не принято.

Состав папки задан контрактом, а не этим скриптом: поля — из
`контракты.ВЫГРУЗКА`, файлы без контракта — `ВЫГРУЗКА_ПРОСТЫЕ`, общий канон
уровней — `ВЫГРУЗКА_ОБЩЕЕ`. Сторож `контракты.py материалы` проверяет папку по
тому же объявлению, поэтому расхождение сборки с контрактом не проходит молча.

Что кладётся и откуда:
  паспорт.json   — материал, автор (И1 + справочник авторов), источник (И1 +
                   справочник источников), о чём, жанр, адресат, понятия, цифры,
                   ограничения; имя копии оригинала.
  заготовки.json — по строке на принятую тему из реестра: уровни У1 с цитатами,
                   сюжеты, фрагменты с координатами в тексте, блоки темы целиком
                   (из агрегата), цитаты, приоритет, S.
  решение.json   — `13_итог.json` как есть.
  текст.txt      — `00_текст.txt`; по нему координаты фрагментов и блоков.
  решение.md     — `отбор.md`, таблица отбора.
  <оригинал>     — копия исходного файла под его именем.

Уровни у заготовки могут быть пустыми: У1 отвечает по каждой ячейке канона
отдельно, и принятый текст может не лечь ни на одну. Это сигнал аналитику, не
причина прятать материал: решение о принятии уже состоялось на скоринге.

Автор: И1 отдаёт авторов списком через «; ». Паспорт описывает одного —
первого, у кого есть строка справочника, иначе первого по списку; имя и
регалии едут списком как у И1, идентификаторы — всех найденных.
"""
import sys, os, json, shutil, importlib.util
from datetime import date

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ЗДЕСЬ)


def _модуль(имя, файл):
    сп = importlib.util.spec_from_file_location(имя, os.path.join(ЗДЕСЬ, файл))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


_общее = _модуль("общее", "общее.py")
_к = _модуль("контракты", "контракты.py")
_авторы = _модуль("авторы", "авторы.py")
_источники = _модуль("источники", "источники.py")

ПРИНЯТ = "✅"
МАРКЕР = "выгружено.json"

# Что о блоке видит аналитик. Служебные адреса (`отрезки_ид`, `позиция`) — нет:
# координаты в тексте даёт `отрезки_док`.
ПОЛЯ_БЛОКА = ("id", "раздел", "часть_документа", "отрезки_док", "суть", "актор",
              "бенефициар", "механизм", "полнота", "цитата", "инструменты",
              "цитата_инструмента", "опора_под_практику", "цитата_практики")
# Что о закрытом уровне едет в заготовку.
ПОЛЯ_УРОВНЯ = ("сюжеты", "что_покрыто", "чего_нет", "цитата", "почему")


def читать(папка, имя, обязательно=True):
    п = os.path.join(папка, имя)
    if not os.path.exists(п):
        if обязательно:
            raise SystemExit(f"выгрузка: нет {имя} в {папка}")
        return None
    if имя.endswith(".jsonl"):
        return [json.loads(л) for л in open(п, encoding="utf-8") if л.strip()]
    return json.load(open(п, encoding="utf-8"))


def записать(папка, имя, данные):
    with open(os.path.join(папка, имя), "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False, indent=2)


# ----------------------------------------------------------------------- автор

def _разделить(значение):
    return [x.strip() for x in str(значение or "").split(_общее.РАЗДЕЛИТЕЛЬ_АВТОРОВ) if x.strip()]


def автор(источник, ответы_и3):
    """Запись «автор» паспорта: состояние авторства по И1, состояние строки и
    её поля — по справочнику авторов. Опознание строки — только по адресу,
    как везде в пайплайне: имя ничего не доказывает."""
    поля = источник.get("поля") or {}
    как = (источник.get("как_получено") or {})
    тип = поля.get("author_type")
    if not тип:
        авторство = "не опознан" if как.get("author_type") == "не найдено" else "аноним"
    else:
        авторство = тип
    имена = _разделить(поля.get("author_name"))

    строки = list(_авторы.читать_справочник()) if имена else []
    адреса = {}
    for о in ответы_и3 or []:
        имя = _к.значение(о.get("автор"))
        if имя and о.get("адрес"):
            адреса[_авторы.норм(имя)] = о["адрес"]
    найденные = []
    for имя in имена:
        а = адреса.get(_авторы.норм(имя))
        с = _авторы.по_адресу(а, строки) if а else None
        if с:
            найденные.append((имя, с))

    строка = найденные[0][1] if найденные else None
    return {
        "авторство": авторство,
        "строка": (строка.get("статус") or "ждёт описания") if строка else "строки нет",
        "author_id": _общее.РАЗДЕЛИТЕЛЬ_АВТОРОВ.join(str(с.get("author_id")) for _, с in найденные) or None,
        "имя": поля.get("author_name"),
        "author_credential": поля.get("author_credential"),
        "описание": строка.get("описание") if строка else None,
        "признанность": строка.get("признанность") if строка else None,
        "почему_признанность": строка.get("почему_признанность") if строка else None,
        "адрес": строка.get("адрес") if строка else None,
    }


# -------------------------------------------------------------------- источник

def источник_паспорта(карта):
    и = карта["источник"]
    о = и.get("оценка") or {}
    if not о.get("id"):
        raise SystemExit("выгрузка: источник не сопоставлен со справочником (нет org_id) — "
                         "принятый материал без строки справочника невозможен, проверьте И1/И2")
    return {
        "org_id": о["id"],
        "название": о.get("организация") or и.get("издание"),
        "publisher_type": о.get("тип"),
        "процесс": о.get("процесс"),
        "маркер": о.get("маркер"),
        "S_база": о.get("S_база"),
        "имя_в_тэг": bool(о.get("имя_в_тэг")),
        "домен": и.get("домен"),
    }


# ------------------------------------------------------------------- заготовки

def заготовки_выгрузки(реестр, агрегат):
    по_ид = {б["id"]: б for б in агрегат["блоки"]}
    строки = []
    for з in реестр["заготовки"]:
        разбор = (з.get("уровни") or {}).get("разбор") or {}
        уровни = [{"уровень": int(у), **{к: р.get(к) for к in ПОЛЯ_УРОВНЯ}}
                  for у, р in sorted(разбор.items(), key=lambda x: int(x[0]))
                  if р.get("закрыт")]
        строки.append({
            "тема": з["тема"],
            "роль_в_материале": з["роль_в_материале"],
            "часть_документа": з["часть_документа"],
            "приоритет": з["приоритет"],
            "S": з["S"],
            "знаков": з["знаков"],
            "уровни": уровни,
            "сюжеты": з["сюжеты"],
            "фрагменты": з["фрагменты"],
            "блоки": [{к: по_ид[и].get(к) for к in ПОЛЯ_БЛОКА} for и in з["блоки"] if и in по_ид],
            "цитаты": з["цитаты"],
            "актор": з["актор"],
            "бенефициар": з["бенефициар"],
            "механизм": з["механизм"],
        })
    return строки


# ------------------------------------------------------------------------ main

def main(папка, исходник):
    _общее.входы_шага(папка, "выгрузка.py")
    папка = папка.rstrip("/")
    имя_папки = os.path.basename(папка)
    итог = читать(папка, "13_итог.json")
    принятые = [с["тема"] for с in итог["строки"] if с.get("вердикт") == ПРИНЯТ]

    if not принятые:
        записать(папка, МАРКЕР, {"выгружено": False, "снято": date.today().isoformat(),
                                 "почему": "принятых тем нет — выгружаются только материалы с ✅"})
        print("принятых тем нет — выгрузки не будет")
        return 0

    реестр = читать(папка, "реестр.json")
    карта = читать(папка, "04_карта.json")
    агрегат = читать(папка, "04_агрегат.json")
    мета = читать(папка, "00_мета.json")
    источник = читать(папка, "00_источник.json")
    ответы_и3 = читать(папка, "00_авторы.jsonl", обязательно=False)
    исходник = _общее.путь_исходника(исходник, "выгрузка")

    # Реестр и итог собраны одним прогоном, но проверить дешевле, чем верить:
    # заготовка на каждую принятую тему.
    темы_реестра = {з["тема"] for з in реестр["заготовки"]}
    if set(принятые) != темы_реестра:
        print(f"  ! принятые темы {sorted(принятые)} ≠ заготовки реестра {sorted(темы_реестра)}")
        return _общее.ОТКАЗ

    куда = os.path.join(КОРЕНЬ, _к.ВЫГРУЗКА_КОРЕНЬ, имя_папки)
    os.makedirs(куда, exist_ok=True)
    имя_оригинала = os.path.basename(исходник)

    паспорт = {
        "материал": карта["материал"].get("заголовок_из_файла") or карта["материал"]["файл"],
        "папка": имя_папки,
        "снято": date.today().isoformat(),
        "исходник": имя_оригинала,
        "автор": автор(источник, ответы_и3),
        "источник": источник_паспорта(карта),
        "о_чём_материал": карта["о_чём_материал"],
        "жанр": карта["жанр"],
        "адресат": карта["адресат"],
        "key_concepts": карта.get("key_concepts") or [],
        # В карте цифры — сводка {всего, по_источникам, список}; аналитику нужен список.
        "цифры": (карта.get("цифры") or {}).get("список") or [],
        "ограничения": карта.get("ограничения") or [],
    }
    записать(куда, "паспорт.json", паспорт)
    записать(куда, "заготовки.json", заготовки_выгрузки(реестр, агрегат))
    записать(куда, "решение.json", итог)
    shutil.copyfile(os.path.join(папка, "00_текст.txt"), os.path.join(куда, "текст.txt"))
    shutil.copyfile(os.path.join(папка, "отбор.md"), os.path.join(куда, "решение.md"))
    shutil.copyfile(исходник, os.path.join(куда, имя_оригинала))

    # Общий канон уровней — один на выгрузку. Кладётся, если его нет; если есть
    # и разошёлся с `_канон/`, сторож сообщит, а переписывать его — решение
    # человека: производство может работать по старому.
    for имя, откуда in _к.ВЫГРУЗКА_ОБЩЕЕ.items():
        общий = os.path.join(КОРЕНЬ, _к.ВЫГРУЗКА_КОРЕНЬ, имя)
        if not os.path.exists(общий):
            shutil.copyfile(os.path.join(КОРЕНЬ, откуда), общий)

    # Сборка проверяется тем же сторожем, что и вся выгрузка: собранное не по
    # контракту не считается собранным.
    нарушения = [н for н in _к.проверить_выгрузку() if н.startswith(имя_папки + "/")]
    if нарушения:
        for н in нарушения:
            print("  ✗ " + н)
        shutil.rmtree(куда)
        print("  ! выгрузка не по контракту — папка не оставлена")
        return _общее.ОТКАЗ

    записать(папка, МАРКЕР, {
        "выгружено": True, "снято": паспорт["снято"],
        "куда": os.path.relpath(куда, КОРЕНЬ),
        "темы": принятые,
        "файлы": sorted(os.listdir(куда)),
    })
    print(f"выгружено в {os.path.relpath(куда, КОРЕНЬ)}: тем {len(принятые)} "
          f"({', '.join(принятые)}), файлов {len(os.listdir(куда))}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("python3 _скрипты/выгрузка.py материалы/<папка> <исходник>")
    raise SystemExit(main(sys.argv[1], sys.argv[2]))
