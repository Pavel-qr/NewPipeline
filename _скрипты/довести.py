# -*- coding: utf-8 -*-
"""Довести материалы до конца, повторяя то, что чинится само.

  python3 _скрипты/довести.py test/01_Online_Review_Analysis.pdf
  python3 _скрипты/довести.py --канал test
  python3 _скрипты/довести.py --канал test --попыток 8
  python3 _скрипты/довести.py --канал test --потоков 1   # по одному, как раньше
  python3 _скрипты/довести.py --все                      # весь корпус

Материалов идёт `--потоков` штук одновременно (по умолчанию 10, см.
`прогон_корпус.параллельно`): попытки, правки и вызовы модели у каждого
материала свои, общий на всех канон пишется под замком.

`прогон.py` на коде 4 останавливается: ответ модели не по контракту, решать
человеку. `прогон_последовательно.довести` тоже не повторяет — пишет отказ в
журнал и стоп («автоповтора нет»). Но часть отказов чинится без человека:
недословная цитата правится по эталону, адрес блока — по позиции его же
цитаты. Здесь тот же арбитраж, что в `прогон_последовательно`, только в цикле.

Порядок на отказе:
  1. точечная правка ответа (`правка_цитат`: П1, П1т, П1т-адреса, П4, У1) —
     дешевле перевызова и не теряет остальной ответ;
  2. правки нет — снять выход упавшего шага (`СНЯТЬ_ПО_ШАГУ`), модель ответит
     заново;
  3. код не 4 — стоп: упал скрипт, а не забракован ответ, это к человеку.

Корпус исходников берётся из `общее.КОРПУС` — по умолчанию `<проект>/ИСХОДНИКИ`;
другое место задаётся переменной `КОРПУС_ИСХОДНИКОВ`.
"""
import os, sys, subprocess

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ЗДЕСЬ)
sys.path.insert(0, ЗДЕСЬ)
import прогон_корпус
import прогон_последовательно as пп

ПОПЫТОК = 8


def очередь_по_аргументам(аргументы, канал):
    """[(путь в корпусе, папка материала)] — как у `прогон_корпус.очередь`."""
    пары = прогон_корпус.очередь()
    if канал:
        пары = [(о, п) for о, п in пары if о.split("/")[0] == канал]
        if not пары:
            raise SystemExit(f"довести: в корпусе нет канала «{канал}»")
        return пары
    выбор, по_пути = [], {о: п for о, п in пары}
    for а in аргументы:
        а = а.replace(os.sep, "/")
        совпало = [(о, п) for о, п in по_пути.items() if о == а or о.endswith("/" + а)]
        if not совпало:
            raise SystemExit(f"довести: в корпусе нет «{а}»")
        выбор.extend(совпало)
    return выбор


def прогон(отн, папка):
    p = subprocess.Popen(
        [sys.executable, "-u", os.path.join(ЗДЕСЬ, "прогон.py"), отн, папка],
        cwd=КОРЕНЬ, text=True, stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT, bufsize=1)
    части = []
    for строка in p.stdout:
        sys.stdout.write(строка); sys.stdout.flush()
        части.append(строка)
    return p.wait(), "".join(части)


def довести(отн, папка, попыток):
    метка = os.path.basename(папка)
    print(f"\n######## {метка} ########", flush=True)
    if прогон_корпус.готов(папка):
        print(f"---- {метка}: уже доведён ----", flush=True)
        return 0
    for попытка in range(1, попыток + 1):
        код, лог = прогон(отн, папка)
        if код == 0:
            print(f"---- {метка}: пройдено до конца (попытка {попытка}) ----", flush=True)
            return 0
        шаг = пп.последний_стоп(лог)
        print(f"---- {метка}: код {код}, шаг {шаг}, попытка {попытка}/{попыток} ----",
              flush=True)
        # Обрыв связи — не брак ответа и не поломка: те же входы, пробуем снова.
        if "вызов API не удался" in лог:
            print(f"     сбой связи — повтор без правок", flush=True)
            continue
        if код != 4:
            print(f"---- {метка}: код {код} — упал скрипт, это к человеку ----", flush=True)
            return код
        что = пп.правка_цитат(лог, папка)
        if что:
            print(f"     точечная правка: {что}", flush=True)
            # После правки отчёт проверки снимается, иначе шаг считается сделанным.
            снять = пп.СНЯТЬ_ПРОВЕРКУ_ПОСЛЕ_ПРАВКИ.get(что.split("+")[0])
            if снять and os.path.exists(os.path.join(папка, снять)):
                os.remove(os.path.join(папка, снять))
            continue
        снять = пп.файл_снять(лог)
        if not снять:
            print(f"---- {метка}: снимать нечего, шаг {шаг} не в СНЯТЬ_ПО_ШАГУ ----",
                  flush=True)
            return код
        п = os.path.join(папка, снять)
        if not os.path.exists(п):
            print(f"---- {метка}: {снять} уже нет — повторять нечего ----", flush=True)
            return код
        os.remove(п)
        print(f"     снято для перевызова: {снять}", flush=True)
    print(f"---- {метка}: не доведён за {попыток} попыток ----", flush=True)
    return 4


def main(argv):
    потоков, argv = прогон_корпус.сколько_потоков(argv)
    канал, попыток, пути, все = None, ПОПЫТОК, [], False
    i = 0
    while i < len(argv):
        а = argv[i]
        if а == "--все":
            все = True; i += 1
        elif а == "--канал" and i + 1 < len(argv):
            канал = argv[i + 1]; i += 2
        elif а == "--попыток" and i + 1 < len(argv):
            попыток = int(argv[i + 1]); i += 2
        else:
            пути.append(а); i += 1
    if not (все or канал or пути):
        raise SystemExit(__doc__.strip().splitlines()[2].strip())
    пары = прогон_корпус.очередь() if все else очередь_по_аргументам(пути, канал)
    print(f"довести: материалов {len(пары)}, попыток на материал {попыток}, "
          f"одновременно {потоков}")
    коды = прогон_корпус.параллельно(
        пары, lambda отн, папка: довести(отн, папка, попыток), потоков)
    плохо = sum(1 for к in коды if к)
    print(f"\nдовести: доведено {len(пары) - плохо} из {len(пары)}")
    return 1 if плохо else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
