# -*- coding: utf-8 -*-
"""
B — доказательность темы. Считает скрипт, модель не участвует.

  python3 _скрипты/доказательность.py материалы/<папка>   — показать расклад по темам

Шкала 1-2-3. Три категории источника — это порядок, а не расстояние: внешний
источник не «вдвое лучше» внутреннего, он на ступень выше.

Сначала вопрос: у большинства чисел источник есть. Потом — какой он.
Внешние и внутренние складываются против «без источника», иначе таблица без
подписи в ячейке роняет свой же эксперимент.

  3 — с источником больше, чем без, и внешних больше, чем внутренних;
  2 — с источником больше, чем без, внутренних не меньше, чем внешних;
  1 — без источника не меньше, чем с источником, либо чисел под темой нет.
      Одна ссылка пачку пустых не вытягивает.

Категорию ставит П1 у каждой цифры, разбирая свой чанк. Вопрос «есть ли что
применить» в B не входит: за материал на него отвечает жанр П2 (уверенный
дескриптив режет до скоринга, пограничный — нет), за тему — паттерн из кейса
(П4).

Как цифра привязывается к теме. У каждой цифры в карте есть дословная цитата.
Цитата ищется в чанках; чанк относится к теме, если в нём лежит хотя бы один
фрагмент темы (агрегат, Б5). Чанк — крупная единица, и это известное
ограничение метода: ссылки на литературу и содержание темы в одном чанке не
различаются.
"""
import json, os, sys, collections, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))

_сп = importlib.util.spec_from_file_location(
    "b4", os.path.join(ЗДЕСЬ, "b4_проверка_выжимок.py"))
_b4 = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(_b4)
_сп = importlib.util.spec_from_file_location("контракты", os.path.join(ЗДЕСЬ, "контракты.py"))
_к = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(_к)

КАТЕГОРИЯ = {
    "исследование/отчёт": 3,
    "внутренние данные компании": 2,
    "не указан": 1,
}
# Ступени — ровно по закрытому списку контракта П1: значение вне списка не
# доезжает сюда (Б4 останавливает прогон), а список, разошедшийся с этой
# таблицей, ловится при импорте, не в расчёте.
if set(КАТЕГОРИЯ) != set(_к.СПИСКИ["источник_цифры"]):
    raise SystemExit("доказательность: КАТЕГОРИЯ расходится с контракты.СПИСКИ['источник_цифры'] — "
                     "ступени B и закрытый список П1 должны совпадать")
ИМЯ = {3: "внешний источник", 2: "внутренние данные", 1: "без источника"}
МИН_ЦИТАТА = 25   # короче — не опознать однозначно
ОКНО = 80         # по скольки знакам цитаты ищем чанк


def _чанки(папка):
    """Чанки обязательны: без них ни одна цифра не привяжется к теме, и B у всех
    тем станет «цифр нет» — неотличимо от честного результата."""
    п = os.path.join(папка, "02_чанки.jsonl")
    if not os.path.exists(п):
        raise SystemExit(f"доказательность: нет {п} — цифры привязать не к чему")
    out = []
    for строка in open(п, encoding="utf-8"):
        if строка.strip():
            ч = json.loads(строка)
            out.append((ч["id"], _b4.норм(ч["текст"])))
    return out


def цифры_по_чанкам(папка, карта):
    """[(чанк_или_None, ступень, значение, неоднозначно)] по всем цифрам материала.
    `неоднозначно` — цитата нашлась не в одном чанке: взят первый по тексту, и
    это выбор, а не факт; такие цифры считаются отдельно."""
    чанки = _чанки(папка)
    итог = []
    for ц in (карта.get("цифры") or {}).get("список", []):
        цит = _b4.норм(ц.get("цитата") or "")
        ид, неоднозначно = None, False
        if len(цит) >= МИН_ЦИТАТА:
            фрагмент = цит[:ОКНО]
            где = [к for к, т in чанки if фрагмент in т]
            ид, неоднозначно = (где[0] if где else None), len(где) > 1
        # Ключ, а не `.get(…, 1)`: незнакомое написание источника раньше молча
        # становилось «источника нет» и роняло B.
        источник = ц.get("источник")
        if источник not in КАТЕГОРИЯ:
            raise SystemExit(f"доказательность: у цифры «{ц.get('значение', '')}» источник "
                             f"{источник!r} вне списка {sorted(КАТЕГОРИЯ)} — карта собрана "
                             f"по выжимке не по контракту П1")
        итог.append((ид, КАТЕГОРИЯ[источник], ц.get("значение", ""), неоднозначно))
    return итог


def неоднозначных(цифры):
    """Сколько цифр нашлось не в одном чанке (привязаны к первому)."""
    return sum(1 for *_, н in цифры if н)


def не_привязано(цифры):
    """Сколько цифр материала не нашлось ни в одном чанке: цитата короче
    МИН_ЦИТАТА или не найдена. Эти цифры не входят в счёт ни одной темы, и
    материал, где не привязалась половина цифр, без этого числа выглядел бы как
    материал без цифр."""
    return sum(1 for ид, *_ in цифры if ид is None)


def чанки_темы(агрегат, тема):
    """Чанки, в которых лежат фрагменты этой темы (агрегат Б5)."""
    т = next((т for т in агрегат.get("темы") or [] if т["id"] == тема), None)
    return {ф["чанк"] for ф in (т or {}).get("фрагменты") or []}


def балл(счёт):
    """Сначала наличие источника, потом его ступень.

    внешние+внутренние не больше «без источника» → 1.
    иначе внешних больше внутренних → 3, иначе 2.
    Пустой счёт — 1 (цифр под темой нет).
    """
    if not счёт:
        return 1
    внешние = счёт.get(3, 0)
    внутренние = счёт.get(2, 0)
    без = счёт.get(1, 0)
    if внешние + внутренние <= без:
        return 1
    return 3 if внешние > внутренние else 2


def посчитать(папка, карта, агрегат, тема, цифры=None):
    """(B, счёт по категориям, сколько цифр учтено) для одной темы."""
    цифры = цифры if цифры is not None else цифры_по_чанкам(папка, карта)
    свои = чанки_темы(агрегат, тема)
    счёт = collections.Counter(к for ид, к, *_ in цифры if ид and ид in свои)
    return балл(счёт), {ИМЯ[k]: v for k, v in sorted(счёт.items(), reverse=True)}, sum(счёт.values())


if __name__ == "__main__":
    папка = sys.argv[1]
    карта = json.load(open(os.path.join(папка, "04_карта.json"), encoding="utf-8"))
    агрегат = json.load(open(os.path.join(папка, "04_агрегат.json"), encoding="utf-8"))
    цифры = цифры_по_чанкам(папка, карта)
    нет = не_привязано(цифры)
    print(f"цифр в материале: {len(цифры)}, не нашлось в тексте: {нет}, "
          f"нашлось в нескольких чанках: {неоднозначных(цифры)}\n")
    for т in агрегат["темы"]:
        B, счёт, n = посчитать(папка, карта, агрегат, т["id"], цифры)
        подпись = ", ".join(f"{k} ×{v}" for k, v in счёт.items()) or "цифр нет"
        print(f'  B={B}  {т["id"]:34} {подпись}')
