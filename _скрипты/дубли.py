# -*- coding: utf-8 -*-
"""
Шаг 0. Дубли в исходниках. Запускается первым, до всего остального.

  python3 _скрипты/дубли.py                 — проверить ИСХОДНИКИ
  python3 _скрипты/дубли.py путь/к/папке     — другую папку

Ничего не переименовывает и не удаляет: только показывает.

Код возврата 1 — только на настоящих дублях: один файл под двумя именами или один
материал в двух форматах. «Уже разобран» на код возврата не влияет: исходники
никто не выбрасывает после разбора, и девятнадцать пройденных материалов лежат в
папке законно. Гейт, который срабатывает всегда, — это не гейт, а шум.

Зачем шаг 0. Разбор материала стоит дорого: десятки вызовов модели на документ.
Дубль обнаруживается обычно в конце, когда в сводной появляются две строки об
одном тексте с разными баллами — и непонятно, какой из них правильный. Дешевле
поймать это за секунду до старта.

Три проверки, от надёжной к вероятностной.

  1. Побайтовые дубли. Одинаковый sha256 — один и тот же файл под двумя именами.
     Сомнений нет. Сначала группируем по размеру, хэшируем только внутри групп:
     на семидесяти файлах это доли секунды.

  2. Один материал в разных форматах. Имена, совпавшие после нормализации без
     расширения: «Сложные решения.epub» и «Сложные решения.pdf» — это одна книга,
     из которой сделали PDF. Оба файла лежат, разбирать нужно один.

  3. Уже разобранные. Файл, у которого в «материалы» есть папка: имя исходника
     записано в 04_карта.json. Сравнение идёт по тому же нормализованному ключу,
     что и в имена.py, поэтому «Технологическая республика — копия.pdf» узнаётся
     как уже пройденная «Технологическая республика.pdf».

Чего скрипт НЕ ловит: два разных файла с одинаковым содержанием, но разными
именами и байтами — например один и тот же отчёт, скачанный с двух сайтов.
Для этого нужно сравнивать текст, а текста на шаге 0 ещё нет: он появляется
только после Б1. Если такие случаи пойдут — проверку можно будет добавить после
нормализации, но это уже не шаг 0.
"""
import os, sys, json, hashlib, collections, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
_сп = importlib.util.spec_from_file_location("имена", os.path.join(ЗДЕСЬ, "имена.py"))
_имена = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(_имена)

ПРОПУСК = {".ds_store", ".tmp", ".part"}


def файлы(корень):
    for путь, _, имена in os.walk(корень):
        for ф in sorted(имена):
            if ф.startswith(".") or os.path.splitext(ф)[1].lower() in ПРОПУСК:
                continue
            yield os.path.join(путь, ф)


def хэш(путь, кусок=1 << 20):
    h = hashlib.sha256()
    with open(путь, "rb") as f:
        while True:
            блок = f.read(кусок)
            if not блок:
                break
            h.update(блок)
    return h.hexdigest()


def побайтовые(пути):
    """[[путь, путь, …]] — группы файлов с одинаковым содержимым."""
    по_размеру = collections.defaultdict(list)
    for п in пути:
        по_размеру[os.path.getsize(п)].append(п)
    группы = []
    for размер, список in по_размеру.items():
        if len(список) < 2:
            continue
        по_хэшу = collections.defaultdict(list)
        for п in список:
            по_хэшу[хэш(п)].append(п)
        группы += [гр for гр in по_хэшу.values() if len(гр) > 1]
    return группы


def по_имени(пути, уже_в_группах):
    """Файлы с одинаковым именем после нормализации, но разным содержимым.
    Обычно это один материал в двух форматах: epub и сделанный из него pdf."""
    по_ключу = collections.defaultdict(list)
    for п in пути:
        if п in уже_в_группах:
            continue
        по_ключу[_имена.ключ(п)].append(п)
    return [гр for гр in по_ключу.values() if len(гр) > 1]


def разобранные(корень_материалов):
    """{нормализованный ключ: папка материала}."""
    итог = {}
    if not os.path.isdir(корень_материалов):
        return итог
    for имя in sorted(os.listdir(корень_материалов)):
        папка = os.path.join(корень_материалов, имя)
        if not os.path.isdir(папка):
            continue
        for файл in ("04_карта.json", "00_мета.json"):
            п = os.path.join(папка, файл)
            if not os.path.exists(п):
                continue
            try:
                d = json.load(open(п, encoding="utf-8"))
            except (json.JSONDecodeError, UnicodeDecodeError) as сбой:
                # По битой карте материал выпадал из списка разобранных, и его
                # дубль прошёл бы шаг 0 незамеченным.
                raise SystemExit(f"дубли: {п} не читается: {сбой} — список разобранных неполон")
            исходник = (d.get("исходник")
                        or ((d.get("материал") or {}).get("файл")))
            if исходник:
                итог[_имена.ключ(исходник)] = имя
    return итог


def main(корень, корень_материалов):
    if not os.path.isdir(корень):
        raise SystemExit(f"нет такой папки: {корень}")
    пути = list(файлы(корень))
    коротко = lambda п: os.path.relpath(п, корень)

    группы_байт = побайтовые(пути)
    в_группах = {п for гр in группы_байт for п in гр}
    группы_имён = по_имени(пути, в_группах)
    известные = разобранные(корень_материалов)
    повторы = [(п, известные[_имена.ключ(п)]) for п in пути
               if _имена.ключ(п) in известные]

    print(f"{корень}: файлов {len(пути)}\n")
    нашлось = 0

    if группы_байт:
        нашлось += sum(len(гр) - 1 for гр in группы_байт)
        print(f"ОДИН И ТОТ ЖЕ ФАЙЛ под разными именами — групп {len(группы_байт)}:")
        for гр in группы_байт:
            размер = os.path.getsize(гр[0]) / 1048576
            print(f"  ({размер:.1f} МБ)")
            for п in sorted(гр):
                print(f"    {коротко(п)}")
        print()

    if группы_имён:
        нашлось += sum(len(гр) - 1 for гр in группы_имён)
        print(f"ОДНО НАЗВАНИЕ, РАЗНОЕ СОДЕРЖИМОЕ — обычно один материал в двух "
              f"форматах, групп {len(группы_имён)}:")
        for гр in группы_имён:
            for п in sorted(гр):
                print(f"    {коротко(п)}  ({os.path.getsize(п)/1048576:.1f} МБ)")
            print()

    if повторы:
        print(f"УЖЕ РАЗОБРАНЫ — {len(повторы)}. Это не проблема: исходник остаётся "
              f"в папке после разбора. Просто не берите их в работу снова.")
        for п, папка in повторы:
            print(f"    {коротко(п):<70} → {папка}")
        print()

    if not нашлось:
        print("настоящих дублей нет, можно запускать разбор")
        return 0

    print(f"итого лишних файлов: {нашлось}")
    print("Ничего не удалено — решение за человеком. После уборки запустите снова.")
    return 1


if __name__ == "__main__":
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    _сп = importlib.util.spec_from_file_location("общее", os.path.join(ЗДЕСЬ, "общее.py"))
    _общее = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(_общее)
    sys.exit(main(аргументы[0] if аргументы else _общее.корень_корпуса("дубли"),
                  os.path.join(os.path.dirname(ЗДЕСЬ), "материалы")))
