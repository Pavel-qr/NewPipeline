# -*- coding: utf-8 -*-
"""
Проверка самих скриптов: каждый запускается и делает то, чем назван.

  python3 _скрипты/запуск.py

Третий сторож рядом с двумя уже стоящими. `контракты.py` отвечает за выходы
моделей, `инварианты.py` — за справочники, `входы.py` — за полноту входов папки.
Этот — за код: предмет проверки всегда лежит рядом с самой проверкой.

Почему он появился. 17 сентября выяснилось, что `сводная.py` обрезана прежней
правкой: пропали функция `xlsx`, вспомогательная `чисто` и запуск из командной
строки. `python3 _скрипты/сводная.py` при этом **не падал**: ни ошибки, ни вывода,
таблица просто не пересобиралась. Замечено случайно, по дате файла, через сутки.

Это тот же класс, что «печать роняет шаг»: **шаг молча ничего не делает, и
по выводу этого не видно.** Молчание неотличимо от работы, и чем дольше оно длится,
тем дороже: всё это время человек смотрит в таблицу, считая её свежей.

Три правила, каждое ловит свою половину того случая.

**1. Скрипт, запуск которого где-то обещан, обязан запускаться.** Обещание живёт
в двух местах, и оба читаются как есть: `прогон.py` печатает «запустите X», а
документация пишет `python3 _скрипты/X.py`. Скрипт без `__main__` при таком
запуске молча возвращает ноль — интерпретатор читает определения и выходит,
сделав ровно ничего. Именно это и случилось со `сводная.py`, чей запуск обещан
в инструкции, а не в оркестраторе: правило, смотрящее в один `прогон.py`, её бы не
поймало.

**2. Всё, что код вызывает, должно быть определено.** Проверяются имена в позиции
вызова — `xlsx(...)`, а не всякое упоминание: у вызова нет законного способа
ссылаться на несуществующее имя, и ложных тревог эта узость почти не даёт.
Именно это правило ловит выпавшую функцию, а не только выпавший `__main__`.

**3. Модуль обязан компилироваться.** Дешёвая проверка, но без неё первые две
молчат на сломанном файле.

**Чего проверка не даёт.** Она не запускает скрипты и потому не отвечает на
вопрос «пишет ли шаг свои выходные файлы на настоящих данных» — на это есть
`пересчёт.py --проверка`, который прогоняет все 29 папок и сверяет результат.
Здесь — только то, что видно в коде, зато без данных и мгновенно.
"""
import ast, os, re, sys, builtins, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ВСТРОЕННЫЕ = set(dir(builtins))


def _обещан_запуск(корень):
    """Имена скриптов, чей запуск где-то обещан: оркестратором или документацией.

    Второй источник — строки вида `python3 _скрипты/X.py` в .md проекта. Документация
    тут не украшение, а обязательство: если написано, что скрипт запускают такой
    командой, он обязан на неё отвечать. Читается из файлов, а не переписывается
    списком, по той же причине, что и первый источник."""
    обещаны = set(_скрипты_прогона())
    for и in sorted(os.listdir(корень)):
        if not и.endswith(".md"):
            continue
        текст = open(os.path.join(корень, и), encoding="utf-8", errors="replace").read()
        обещаны |= {f"{имя}.py" for имя in
                    re.findall(r"python3\s+_скрипты/([^\s/]+)\.py", текст)}
    return sorted(обещаны)


def _скрипты_прогона():
    """Имена файлов, которые оркестратор велит запускать как скрипты.

    Читается из объявления `шаги.py`, а не переписывается сюда списком: копия
    списка разошлась бы с оригиналом — ровно то, от чего заведён `контракты.py`."""
    сп = importlib.util.spec_from_file_location("шаги", os.path.join(ЗДЕСЬ, "шаги.py"))
    м = importlib.util.module_from_spec(сп)
    сп.loader.exec_module(м)
    return sorted({с["чем"].split()[0] for с in м.скриптовые()})   # «о_уровень.py вход» → «о_уровень.py»


class _Область(ast.NodeVisitor):
    """Имена, определённые внутри одной функции: параметры и всё, что ей присвоено.

    Полного разбора областей видимости здесь нет и не нужно: проверяются только
    имена в позиции вызова, а такое имя либо определено в модуле, либо пришло
    параметром, либо присвоено рядом. Узость — сознательная цена за отсутствие
    ложных тревог."""

    def __init__(self):
        self.свои = set()

    def visit_Name(self, у):
        if isinstance(у.ctx, (ast.Store, ast.Del)):
            self.свои.add(у.id)

    def visit_arg(self, у):
        self.свои.add(у.arg)

    def visit_ExceptHandler(self, у):
        if у.name:
            self.свои.add(у.name)
        self.generic_visit(у)

    def visit_FunctionDef(self, у):
        self.свои.add(у.name)
        self.generic_visit(у)

    visit_AsyncFunctionDef = visit_FunctionDef

    def visit_ClassDef(self, у):
        self.свои.add(у.name)
        self.generic_visit(у)

    def visit_Import(self, у):
        for и in у.names:
            self.свои.add((и.asname or и.name).split(".")[0])

    def visit_ImportFrom(self, у):
        for и in у.names:
            self.свои.add(и.asname or и.name)


def _определённые(дерево):
    о = _Область()
    for узел in дерево.body:
        о.visit(узел)
    # тело функций модуля тоже определяет имена — но только для себя;
    # здесь собирается именно модульный уровень.
    return о.свои


def _вызовы(узел):
    """Имена, вызываемые как функции, внутри одного узла."""
    for у in ast.walk(узел):
        if isinstance(у, ast.Call) and isinstance(у.func, ast.Name):
            yield у.func.id, у.func.lineno


def проверить_файл(путь):
    имя = os.path.basename(путь)
    исходник = open(путь, encoding="utf-8").read()
    try:
        дерево = ast.parse(исходник, filename=путь)
    except SyntaxError as ош:
        return [f"{имя}: не компилируется — строка {ош.lineno}: {ош.msg}"]

    нарушения = []
    модульные = _определённые(дерево)

    # вызовы на уровне модуля
    for узел in дерево.body:
        if isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        for кого, строка in _вызовы(узел):
            if кого not in модульные and кого not in ВСТРОЕННЫЕ:
                нарушения.append(f"{имя}:{строка}: вызывается `{кого}`, "
                                 f"которого в модуле нет")

    # вызовы внутри функций: модульные имена плюс свои
    for узел in ast.walk(дерево):
        if not isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        о = _Область()
        о.visit(узел.args)
        for т in узел.body:
            о.visit(т)
            for вложенный in ast.walk(т):
                if вложенный is not т:
                    о.visit(вложенный)
        видно = модульные | о.свои | ВСТРОЕННЫЕ
        for кого, строка in _вызовы(узел):
            if кого not in видно:
                нарушения.append(f"{имя}:{строка}: в `{узел.name}` вызывается "
                                 f"`{кого}`, которого в модуле нет")
    return нарушения


def есть_запуск(путь):
    дерево = ast.parse(open(путь, encoding="utf-8").read(), filename=путь)
    for узел in дерево.body:
        if (isinstance(узел, ast.If) and isinstance(узел.test, ast.Compare)
                and isinstance(узел.test.left, ast.Name)
                and узел.test.left.id == "__name__"):
            return True
    return False


def main(папка=None):
    папка = папка or ЗДЕСЬ
    файлы = sorted(os.path.join(папка, и) for и in os.listdir(папка)
                   if и.endswith(".py"))
    # Окружение — первым: разбор синтаксиса не видит отсутствующей библиотеки,
    # а `import openpyxl` внутри функции для него способ удовлетворить правило,
    # а не предмет проверки.
    сп = importlib.util.spec_from_file_location("окружение", os.path.join(ЗДЕСЬ, "окружение.py"))
    _окр = importlib.util.module_from_spec(сп); сп.loader.exec_module(_окр)
    нарушения = [f"окружение: {о}" for о in _окр.проверить()]
    for ф in файлы:
        нарушения += проверить_файл(ф)

    обещаны = _обещан_запуск(os.path.dirname(папка.rstrip("/")) or ".")
    for и in обещаны:
        путь = os.path.join(папка, и)
        if not os.path.exists(путь):
            нарушения.append(f"{и}: запуск обещан, но файла нет")
        elif not есть_запуск(путь):
            нарушения.append(f"{и}: запуск обещан, но запускать нечего — "
                             f"нет `if __name__ == \"__main__\"`. "
                             f"Такой запуск молча вернёт ноль")

    print(f"скриптов проверено: {len(файлы)}, "
          f"из них с обещанным запуском: {len(обещаны)}")
    запускаемых = sum(1 for ф in файлы if есть_запуск(ф))
    print(f"запускаются из командной строки: {запускаемых}, "
          f"остальные {len(файлы)-запускаемых} — библиотеки, их зовут из других скриптов")
    for н in нарушения:
        print("  ! " + н)
    print("\n" + ("все скрипты запускаются и вызывают только то, что в них есть"
                  if not нарушения else
                  f"нарушений: {len(нарушения)}"))
    return 1 if нарушения else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else None))
