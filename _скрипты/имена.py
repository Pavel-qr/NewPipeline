# -*- coding: utf-8 -*-
"""
Нормализация имён файлов в исходниках.

  python3 _скрипты/имена.py                     — показать, что будет переименовано
  python3 _скрипты/имена.py --применить         — переименовать
  python3 _скрипты/имена.py путь/к/папке         — другая папка

По умолчанию НИЧЕГО НЕ ТРОГАЕТ: печатает таблицу «было → станет» и останавливается.
Переименование необратимо, а исходники — единственная копия материала.

Зачем это нужно. Файлы с «—» в названии недоступны через мост: он показывает их в
листинге, но при обращении отвечает «does not exist». Проверено 16 сентября на
четырёх примерах: `Five ways demographics are transforming the world.pdf` из папки
Disrupt забирается, `AI_Costs_More_Than_People_EN — копия.pdf` из той же папки —
нет. Пробовал три разных тире, ни одно не подошло. Пока имя содержит этот символ,
материал нельзя ни забрать, ни прогнать.

Что делается с именем:

  1. NFC — macOS хранит «й» разложенным на «и» + знак; после нормализации имя
     совпадает с тем, как его пишут все остальные;
  1а. невидимые служебные символы — нулевой ширины, мягкий перенос, BOM, метки
     направления письма — убираются совсем: в имени они не видны, но ключ делают
     другим;
  2. тире — «—», «–», «―», «−» становятся обычным дефисом;
  3. хвосты копирования — « — копия», « - копия», « (1)» убираются: это не часть
     названия, а след файловой системы;
  4. кавычки « » “ ” убираются, типографский апостроф ’ становится обычным;
  5. знаки, которые ломают пути, — : ? * | < > / \\ " — заменяются пробелом;
  6. пробелы схлопываются, хвостовые точки и пробелы срезаются.

Про невидимые символы отдельно, потому что это класс, а не курьёз. Имя,
отличающееся от соседнего одним неотображаемым знаком, выглядит тем же самым — и
человеку, и в листинге, — но ключ у него другой, и `дубли.py` такую пару не
поймает. Неразрывный пробел (U+00A0) и узкий неразрывный (U+202F) сворачиваются
сами: их ловит `\\s` при схлопывании пробелов. А нулевой ширины (U+200B), мягкий
перенос (U+00AD), BOM (U+FEFF) и метки направления письма — не пробелы вовсе, и
пролезали в ключ насквозь. Убираются по категории Unicode (Cc, Cf, Co), а не
перечислением: перечислять невидимое — значит однажды не вписать в список
очередной знак и снова его не заметить.

Что НЕ делается: кириллица не транслитерируется, регистр не меняется, пробелы не
заменяются подчёркиваниями. Имя должно остаться читаемым человеком — оно попадает
в сводную и в карту материала.

Функция `нормализовать` используется ещё и в `сводная.py`: раздел «Входящие»
сравнивает файлы с уже разобранными именно по нормализованному имени, иначе после
переименования разобранный материал снова попадёт в очередь.
"""
import os, re, sys, unicodedata, importlib.util

ТИРЕ = {"—": "-", "–": "-", "―": "-", "−": "-", "‒": "-"}
КАВЫЧКИ = "«»“”„‟‹›″"          # убираются совсем
АПОСТРОФЫ = {"’": "'", "‘": "'", "′": "'"}   # It’s → It's, читаемость важнее
ЛОМАЮЩИЕ = ':?*|<>/\\"'   # заменяются пробелом: «дата-центры: есть ли» → «дата-центры есть ли»
ХВОСТЫ_КОПИИ = [
    re.compile(r"\s*[-—–]\s*копия\s*$", re.I),
    re.compile(r"\s*копия\s*$", re.I),
    re.compile(r"\s*-?\s*copy\s*$", re.I),
    re.compile(r"\s*\(\d+\)\s*$"),
]


def нормализовать(имя, с_расширением=True):
    """Имя файла, приведённое к стандарту. Расширение сохраняется как есть."""
    основа, расш = os.path.splitext(os.path.basename(имя))
    основа = unicodedata.normalize("NFC", основа)
    # Невидимые служебные — до всего остального: они могут стоять внутри тире,
    # кавычек и хвостов копирования и помешать их узнать.
    основа = "".join(с for с in основа
                     if unicodedata.category(с) not in ("Cc", "Cf", "Co"))
    for из_, в in ТИРЕ.items():
        основа = основа.replace(из_, в)
    основа = "".join("" if с in КАВЫЧКИ else АПОСТРОФЫ.get(с, с) for с in основа)
    основа = "".join(" " if с in ЛОМАЮЩИЕ else с for с in основа)
    # хвосты копирования снимаются по кругу: бывает «… — копия (1)»
    прошлое = None
    while прошлое != основа:
        прошлое = основа
        for шаблон in ХВОСТЫ_КОПИИ:
            основа = шаблон.sub("", основа)
    основа = re.sub(r"\s+", " ", основа)
    основа = основа.strip(" .-_")
    основа = основа or "без имени"
    return (основа + расш.lower()) if с_расширением else основа


def ключ(имя):
    """Имя для сравнения: нормализованное, без расширения, в нижнем регистре.
    По нему сводная понимает, что файл — это уже разобранный материал."""
    return нормализовать(имя, с_расширением=False).lower()


def свободное(папка, имя):
    """Имя, которое ещё не занято в этой папке: к совпавшему дописывается _2."""
    основа, расш = os.path.splitext(имя)
    кандидат, n = имя, 2
    while os.path.exists(os.path.join(папка, кандидат)):
        кандидат = f"{основа}_{n}{расш}"
        n += 1
    return кандидат


def собрать(корень):
    """[(папка, было, станет)] — только те файлы, чьё имя меняется."""
    планы = []
    for путь, _, файлы in os.walk(корень):
        for ф in sorted(файлы):
            if ф.startswith("."):
                continue
            новое = нормализовать(ф)
            if новое != ф:
                планы.append((путь, ф, новое))
    return планы


def main(корень, применить=False):
    if not os.path.isdir(корень):
        raise SystemExit(f"нет такой папки: {корень}")
    планы = собрать(корень)
    if not планы:
        print(f"{корень}: переименовывать нечего, все имена уже в норме")
        return

    print(f"{корень}: к переименованию {len(планы)} файлов\n")
    for путь, было, станет in планы:
        где = os.path.relpath(путь, корень)
        print(f'  {где if где != "." else "—"}')
        print(f'    было:   {было}')
        print(f'    станет: {станет}')

    if not применить:
        print(f"\nЭто предпросмотр: ничего не изменено. Чтобы переименовать:"
              f"\n  python3 _скрипты/имена.py {корень} --применить")
        return

    сделано = 0
    for путь, было, станет in планы:
        цель = свободное(путь, станет)
        os.rename(os.path.join(путь, было), os.path.join(путь, цель))
        сделано += 1
    print(f"\nпереименовано: {сделано}")
    print("Дальше пересоберите сводную: python3 _скрипты/сводная.py")


if __name__ == "__main__":
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
    _сп = importlib.util.spec_from_file_location("общее", os.path.join(ЗДЕСЬ, "общее.py"))
    _общее = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(_общее)
    по_умолчанию = _общее.корень_корпуса("имена")
    raise SystemExit(main(аргументы[0] if аргументы else по_умолчанию,
                          применить="--применить" in sys.argv))
