# -*- coding: utf-8 -*-
"""
Инварианты справочников: свойства, которые обязаны держаться при ЛЮБОМ наборе
материалов.

  python3 _скрипты/инварианты.py            — проверить
  python3 _скрипты/инварианты.py --корпус   — плюс сверка по разобранным материалам

Почему инварианты, а не снимок «как сейчас». Снимок текущего поведения
замораживает и сегодняшние ошибки тоже: если строка подбирается неправильно, он
запишет это как ожидаемое. И покрывает он ровно те материалы, которые у нас
случайно есть, — это выборка, а не спецификация.

Инвариант формулирует правило, из которого выборка не нужна. Пример из жизни:
16 сентября миграция ключей чуть не записала `nature.com` в строку одного
журнала — одна строка перехватила бы все журналы платформы. Снимок бы этого не
поймал; инвариант «идентификатор принадлежит одной строке» ловит по построению.

Проверка по корпусу оставлена вторым эшелоном: она отвечает не «правильно ли»,
а «не сдвинулось ли» — и потому включается отдельным ключом.
"""
import os, re, sys, json, importlib.util
from collections import defaultdict

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ЗДЕСЬ)

сп = importlib.util.spec_from_file_location("источники", os.path.join(ЗДЕСЬ, "источники.py"))
_ист = importlib.util.module_from_spec(сп); сп.loader.exec_module(_ист)

# Имена полей после карты `источники.КОЛОНКИ` — одно место, не копия.
# Копия `("issn", "isbn_префикс", "домен")` искала заголовок в уже
# переименованных полях, и три проверки по ISBN были мертвы.
КЛЮЧИ = _ист.КЛЮЧИ
# У этих типов идентификатора нет по природе: это описания процесса, а не
# организации. Только им разрешено жить в справочнике без ключа.
БЕЗ_КЛЮЧА_ПО_ПРИРОДЕ = {"препринт-сервер", "блог, канал, самиздат", "нет издателя"}
# Значения поля «актор» в каноне тем; смысл каждого — в П4, сверка «Актор».
АКТОРЫ = {"сотрудник", "руководитель"}


def _значения(строка, поле):
    return [в.strip() for в in str(строка.get(поле) or "").split("|") if в.strip()]


def проверить_источники(ряды):
    нарушения = []

    # 1. Идентификатор принадлежит одной строке. Иначе материал с этим ключом
    #    достанется той строке, которая окажется раньше в файле, — то есть
    #    случаю.
    занято = defaultdict(list)
    for р in ряды:
        for поле in КЛЮЧИ:
            for в in _значения(р, поле):
                занято[(поле, _ист.норм(в))].append(р.get("id"))
    for (поле, в), кто in занято.items():
        if len(кто) > 1:
            нарушения.append(f"{поле} «{в}» стоит сразу у {len(кто)} строк: {', '.join(кто)}")

    # 2. Префикс ISBN одной строки не является началом префикса другой.
    #    Сопоставление по ISBN идёт по началу номера, и вложенный префикс
    #    перехватывал бы книги соседа.
    префиксы = [(р.get("id"), re.sub(r"\D", "", в))
                for р in ряды for в in _значения(р, "isbn")]
    for ид, п in префиксы:
        for другой, д in префиксы:
            if ид != другой and п and д and (п.startswith(д) or д.startswith(п)):
                нарушения.append(f"префиксы ISBN вложены: {ид} «{п}» и {другой} «{д}»")

    # 3. Домен одной строки не является поддоменом домена другой. Поддомен
    #    находит родителя намеренно (`unesdoc.unesco.org` → `unesco.org`), и
    #    если родитель и потомок стоят у разных строк, материал уйдёт не туда.
    домены = [(р.get("id"), _ист.норм(в)) for р in ряды for в in _значения(р, "домен")]
    for ид, д in домены:
        for другой, е in домены:
            if ид != другой and д.endswith("." + е):
                нарушения.append(f"домен {ид} «{д}» — поддомен {другой} «{е}»")

    # 4. Строка без ключа недостижима: сопоставление по названию
    #    организации снято, и найти её нечем. Разрешено только тем типам, у
    #    которых идентификатора не бывает.
    for р in ряды:
        if р.get("id") in _ист.СЛУЖЕБНЫЕ:
            continue
        if str(р.get("тип") or "").strip() in БЕЗ_КЛЮЧА_ПО_ПРИРОДЕ:
            continue
        if not any(р.get(к) for к in КЛЮЧИ):
            нарушения.append(f"строка «{р.get('id')}» ({р.get('организация')}) не имеет "
                             f"ни ISSN, ни префикса ISBN, ни домена — её не найдёт "
                             f"ни один материал")

    # 5. Служебная строка не несёт ISSN и префикс ISBN: эти ключи принадлежат
    #    конкретному изданию и конкретному издательству, а служебная строка
    #    описывает состояние. Домен ей, наоборот, разрешён — им ловятся площадки
    #    самиздата (`t.me`, `substack.com`), и это тот же ключ из реестра, а не
    #    название.
    for р in ряды:
        if р.get("id") in _ист.СЛУЖЕБНЫЕ and any(р.get(к) for к in ("issn", "isbn")):
            нарушения.append(f"служебная строка «{р.get('id')}» несёт ISSN или префикс ISBN")

    # 6. Каждое служебное состояние имеет свою строку. Если состояние есть, а
    #    строки нет, материал провалится в None и уедет в И2 без надежды: И2
    #    заведёт под него ИМЕННУЮ строку, как было с «БТР».
    for ид in _ист.СЛУЖЕБНЫЕ:
        if not any(р.get("id") == ид for р in ряды):
            нарушения.append(f"служебного состояния «{ид}» нет в справочнике — "
                             f"материалы в этом состоянии уедут в И2 за именной строкой")

    # 7. Идентификатор должен быть годным. Мусор, записанный ключом, остаётся
    #    в каноне навсегда и уводит настоящий материал мимо его строки.
    ои = importlib.util.spec_from_file_location("ои", os.path.join(ЗДЕСЬ, "о_источник.py"))
    _ои = importlib.util.module_from_spec(ои); ои.loader.exec_module(_ои)
    for р in ряды:
        for в in _значения(р, "issn"):
            if not _ои.годен("issn", в):
                нарушения.append(f"у «{р.get('id')}» ISSN «{в}» не проходит контрольную цифру")

    # 8. `org_id` уникален. Две строки с одним id молча схлопывались в
    #    `сопоставить` (`по_id`), и какая из них отвечала — решал порядок в
    #    файле.
    ид = defaultdict(int)
    for р in ряды:
        ид[_ист.норм(р.get("id"))] += 1
    for и, n in ид.items():
        if n > 1:
            нарушения.append(f"org_id «{и}» стоит у {n} строк")
    return нарушения


def проверить_авторов():
    ав = importlib.util.spec_from_file_location("авторы", os.path.join(ЗДЕСЬ, "авторы.py"))
    _ав = importlib.util.module_from_spec(ав); ав.loader.exec_module(_ав)
    нарушения, занято, адреса, ид = [], defaultdict(list), defaultdict(list), defaultdict(int)
    for р in _ав.читать_справочник():
        занято[_ав.норм(р.get("author_id"))].append(р.get("автор"))
        for в in str(р.get("варианты написания") or "").split("|"):
            if в.strip():
                занято[_ав.норм(в)].append(р.get("автор"))
        # Ключ автора — адрес (ORCID, профиль), а не имя: два автора с одним
        # адресом — одна строка, заведённая дважды.
        for поле in ("адрес", "orcid"):
            а = _ав.норм(р.get(поле)).rstrip("/")
            if а:
                адреса[(поле, а)].append(р.get("author_id"))
        ид[_ав.норм(р.get("author_id"))] += 1
    for ключ, кто in занято.items():
        if len(set(кто)) > 1:
            нарушения.append(f"имя «{ключ}» ведёт сразу на {len(set(кто))} строк авторов")
    for (поле, а), кто in адреса.items():
        if len(set(кто)) > 1:
            нарушения.append(f"{поле} «{а}» стоит у {len(set(кто))} авторов: {', '.join(map(str, set(кто)))}")
    for и, n in ид.items():
        if n > 1:
            нарушения.append(f"author_id «{и}» стоит у {n} строк")
    return нарушения


def проверить_каноны():
    """Канон тем и канон уровней — форма и согласованность между собой. До
    17 сентября их не охранял никто."""
    нарушения = []
    к = importlib.util.spec_from_file_location("канон", os.path.join(ЗДЕСЬ, "канон.py"))
    _к = importlib.util.module_from_spec(к); к.loader.exec_module(_к)
    у = importlib.util.spec_from_file_location("уровни", os.path.join(ЗДЕСЬ, "уровни.py"))
    _у = importlib.util.module_from_spec(у); у.loader.exec_module(_у)
    темы = _к.читать()
    ид = [т.get("id") for т in темы]
    if len(ид) != len(set(ид)):
        нарушения.append("канон тем: topic_id повторяется")
    for т in темы:
        пусто = [п for п in ("id", "название", "определение", "актор", "бенефициар", "механизм")
                 if not т.get(п)]
        if пусто:
            нарушения.append(f"канон тем: у «{т.get('id')}» пусто {', '.join(пусто)}")
    # Словарь актора — два значения, и их смысл задан в П4 один раз («сотрудник» —
    # любая роль, «руководитель» — человек с командой). Третье написание — это
    # третий смысл, которого промт не знает.
    for т in темы:
        if т.get("актор") not in АКТОРЫ:
            нарушения.append(f"канон тем: у «{т.get('id')}» актор «{т.get('актор')}» "
                             f"вне словаря {sorted(АКТОРЫ)}")
    # Граница пары записана у обеих тем: П4 читает границы только у проверяемой
    # темы, и односторонняя запись видна одной теме из двух.
    границы = {т.get("id"): {с.split(" — ")[0].strip() for с in str(т.get("границы") or "").split("\n")
                             if с.strip()} for т in темы}
    for а, соседи in границы.items():
        for б in соседи:
            if б not in границы:
                нарушения.append(f"канон тем: граница «{а}» → «{б}» — такой темы нет")
            elif а not in границы[б]:
                нарушения.append(f"канон тем: граница «{а}» → «{б}» записана, обратной у «{б}» нет")
    канон_уровней = _у.читать()
    for уровень, свои in канон_уровней.items():
        нет = [и for и in ид if и not in свои]
        if нет:
            нарушения.append(f"канон уровней, лист {уровень}: нет тем {', '.join(нет)}")
    return нарушения


def по_корпусу():
    """Второй эшелон: не «правильно ли», а «не сдвинулось ли»."""
    сп = importlib.util.spec_from_file_location("общее", os.path.join(ЗДЕСЬ, "общее.py"))
    _о = importlib.util.module_from_spec(сп); сп.loader.exec_module(_о)
    МАТЕРИАЛЫ = _о.корень_материалов(os.environ.get("МАТЕРИАЛЫ"), "инварианты")
    строки = []
    for папка in sorted(os.listdir(МАТЕРИАЛЫ)):
        ф = os.path.join(МАТЕРИАЛЫ, папка, "00_источник.json")
        if not os.path.exists(ф):
            continue
        оценка = (json.load(open(ф, encoding="utf-8")).get("оценка")) or {}
        строки.append((папка, оценка.get("организация"), оценка.get("S_база"),
                       оценка.get("сопоставлено_по")))
    return строки


def main(корпус):
    нарушения = (проверить_источники(list(_ист.читать())) + проверить_авторов()
                 + проверить_каноны())
    if нарушения:
        print(f"ИНВАРИАНТЫ НАРУШЕНЫ — {len(нарушения)}:")
        for н in нарушения:
            print("  ✗ " + н)
    else:
        print("инварианты справочников держатся")

    if корпус:
        print("\nсопоставление по разобранным материалам:")
        for папка, орг, S, чем in по_корпусу():
            print(f"  {папка:34} S={str(S):>5}  {str(чем or '—'):32} {орг}")
    return 1 if нарушения else 0


if __name__ == "__main__":
    sys.exit(main("--корпус" in sys.argv))
