КЛЮЧИ = ("issn", "isbn", "домен")

# Без этих полей строка справочника не строка: по ним ищется шапка и по ним
# писатель проверяет, что запись ляжет в существующие колонки.
ОБЯЗАТЕЛЬНЫЕ = {"id", "организация", "issn", "isbn", "домен", "процесс", "тип",
                "маркер", "S_база", "статус", "материалы"}


def найти_таблицу():
    из_среды = os.environ.get("СПРАВОЧНИК_ИСТОЧНИКОВ")
    кандидаты = ([из_среды] if из_среды else []) + [
        os.path.join(КОРЕНЬ, "_канон", ИМЯ),
        os.path.join(КОРЕНЬ, ИМЯ),
        os.path.join(os.path.dirname(КОРЕНЬ), ИМЯ),
    ]
    for п in кандидаты:
        if п and os.path.exists(п):
            return п
    raise SystemExit("не найден справочник " + ИМЯ + "; искал:\n  " + "\n  ".join(кандидаты))


def норм(s):
    """Одна нормализация на сопоставление: регистр, ё, кавычки, тире, пробелы."""
    s = unicodedata.normalize("NFC", str(s or ""))
    s = (s.replace("«", '"').replace("»", '"').replace("“", '"').replace("”", '"')
          .replace("—", "-").replace("–", "-").replace("ё", "е").replace("Ё", "Е"))
    return re.sub(r"\s+", " ", s).strip().lower()


def шапка_листа(ws, кто="источники"):
    """(номер строки шапки, заголовки, {поле: номер колонки}).

    Шапка — та строка, чьи заголовки через `КОЛОНКИ` дают все `ОБЯЗАТЕЛЬНЫЕ`
    поля; порядок колонок и пробелы в заголовках роли не играют. Раньше шапка
    искалась по `r[0] == "org_id"`, и перестановка колонок молча давала ноль
    строк. Заголовок, которого нет в `КОЛОНКИ`, — отказ, а не
    тихая потеря колонки: карту надо дополнить, а не обойти."""
    for i, r in enumerate(ws.iter_rows(values_only=True), 1):
        заголовки = [str(h).strip() if h else "" for h in (r or ())]
        поля = {КОЛОНКИ[h] for h in заголовки if h in КОЛОНКИ}
        if ОБЯЗАТЕЛЬНЫЕ <= поля:
            чужие = [h for h in заголовки if h and h not in КОЛОНКИ]
            if чужие:
                raise SystemExit(f"{кто}: в шапке {ИМЯ} колонки, которых нет в "
                                 f"источники.КОЛОНКИ: {чужие_текст(чужие)} — "
                                 f"дополните карту, иначе колонка молча потеряется")
            место = {}
            for н, h in enumerate(заголовки, 1):
                if h in КОЛОНКИ:
                    место.setdefault(КОЛОНКИ[h], н)
            return i, заголовки, место
    raise SystemExit(f"{кто}: в {ИМЯ} не найдена шапка с полями "
                     f"{sorted(ОБЯЗАТЕЛЬНЫЕ)} — проверьте лист «источники»")


def чужие_текст(чужие):
    return ", ".join(f"«{h}»" for h in чужие)


def открыть(путь=None, кто="источники"):
    """Книга, лист и разобранная шапка — одна точка входа для читателя и
    писателя, чтобы они не разошлись ни в пути, ни в именах колонок."""
    openpyxl = _библиотека("openpyxl", "источники")
    путь = путь or найти_таблицу()
    кн = openpyxl.load_workbook(путь)
    ws = кн["источники"]
    ряд_шапки, заголовки, место = шапка_листа(ws, кто)
    return путь, кн, ws, ряд_шапки, заголовки, место


def проверить_ключи_записи(значения, место, кто="источники"):
    """Писатель обязан класть только в существующие колонки. Ключ без колонки
    раньше молча не писался."""
    нет = [к for к in значения if к not in место]
    if нет:
        raise SystemExit(f"{кто}: пишу поля, которых нет в шапке {ИМЯ}: "
                         f"{', '.join(нет)} — дополните таблицу или карту КОЛОНКИ")


def читать(путь=None):
    _, _, ws, ряд_шапки, заголовки, место = открыть(путь)
    к_id = место["id"] - 1
    for н, r in enumerate(ws.iter_rows(values_only=True), 1):
        # Строка есть, если есть id — в той колонке, где он стоит по шапке.
        if н <= ряд_шапки or not r or len(r) <= к_id or not r[к_id]:
            continue
        yield {КОЛОНКИ[h]: v for h, v in zip(заголовки, r) if h in КОЛОНКИ}


ЗАПАСНАЯ = "нет_организации"   # строка, которая срабатывает только если не нашлось ничего

# Служебные строки описывают СОСТОЯНИЕ ИСТОЧНИКА, а не организацию: «препринт» —
# это не издатель, а отсутствие рецензирования; «самиздат» — не площадка, а
# публикация без редакции. Организацию за ними искать бессмысленно, поэтому они
# выбираются ВЫЧИСЛЕНИЕМ по полям И1 — см. `состояние()`. По названию не ловится
# ничто и нигде: колонка «варианты написания» осталась подписью для человека.
НЕ_ОПОЗНАН = "не_опознан"
СЛУЖЕБНЫЕ = {ЗАПАСНАЯ, НЕ_ОПОЗНАН, "препринт", "самиздат"}


def _по_ключу(строки, поле, значение):
    """Точное совпадение по идентификатору. Идентификатор либо равен, либо нет —
    подстрокой тут искать нечего."""
    з = норм(значение).replace(" ", "")
    if not з:
        return (None, None)
    for с in строки:
        for вариант in str(с.get(поле) or "").split("|"):
            в = норм(вариант).replace(" ", "")
            if not в:
                continue
            # ISBN в строке — префикс издателя, у материала — номер книги.
            # Домен в строке — сайт организации, у материала может быть
            # поддомен: `unesdoc.unesco.org` — это по-прежнему ЮНЕСКО.
            совпало = (в == з
                       or (поле == "isbn" and з.startswith(в))
                       or (поле == "домен" and з.endswith("." + в)))
            if совпало:
                return (с, f"{поле}: {вариант}")
    return (None, None)


def состояние(поля):
    """Состояние источника по полям И1. Возвращает id служебной строки, либо
    None — «это настоящая организация, ищи её строку», либо «ждёт И2».

    Порядок проверок задаёт `сопоставить()`: **форма публикации бьёт
    организацию** — препринт проверяется до поиска строки по ключу, кто бы его
    ни выложил, рецензирования не было независимо от хозяина сайта.

    Раньше эти строки ловились подстрокой в названии издателя, и это давало три
    разные поломки сразу. `04_ai_observatory` перестал попадать в «препринт»,
    как только И1 назвала издателя «Data Provenance Initiative» вместо фразы
    «препринт, размещён без публикации». `03_adoption` попадал в «самиздат»
    только потому, что «Dasha's Notes» кто-то вписал в варианты руками.
    А `09_маск_луна` и `13_чехов`, у которых издателя нет, а автор назван,
    уезжали в «нет организации и нет автора» с баллом −1 вместо 0.
    """
    издатель = str(поля.get("publisher") or "").strip()
    автор = str(поля.get("author_name") or "").strip()
    тип = str(поля.get("material_type") or "").lower()
    домен = норм(поля.get("домен")).replace(" ", "")
    ключ = any(поля.get(к) for к in ("issn", "isbn", "doi")) or bool(домен)

    if "препринт" in тип or "preprint" in тип:
        return "препринт"
    if not издатель:
        # Автор назван — за текстом стоит человек, и это «только автор», S = 0.
        # Не назван никто — «нет организации и нет автора», S = −1.
        return "самиздат" if автор else ЗАПАСНАЯ
    if ключ:
        return None          # настоящая организация: ищем её строку, иначе И2
    # Издатель назван, но опознать его нечем: ни ISSN, ни префикса ISBN, ни
    # домена. «БТР» в колонтитуле служебной записки — три буквы, а не
    # организация. Под такое состояние раньше заводили ИМЕННУЮ строку; теперь
    # оно общее, и следующая нерасшифрованная аббревиатура новой строки не
    # потребует.
    return НЕ_ОПОЗНАН


def сопоставить(поля, справочник=None):
    """Строка справочника для этого источника, либо None.
    Возвращает (строка_или_None, чем_сопоставилось).

    Три прохода, и ни в одном из них не участвует название организации.

    0. По форме публикации: препринт — служебная строка до всякого ключа
       (форма бьёт организацию).
    1. По идентификатору: ISSN, префикс ISBN, домен. Ключ приходит из реестра и
       никем не сочиняется. Заодно это снимает вопрос «издание или издатель»:
       тип идентификатора разводит их сам. Сюда же попадают площадки самиздата —
       у строки «самиздат» в колонке домена стоят `t.me`, `substack.com` и
       прочие, то есть она ловится ровно так же, как все остальные.
    2. По состоянию источника — см. `состояние()`. Это служебные строки:
       препринт, самиздат, «нет организации», «издатель назван, но не опознан».

    Прохода «по названию организации» нет вовсе. Он работал у 12 материалов из
    29 и опирался на колонку «варианты написания», которую модель пишет один
    раз, увидев один материал, и должна при этом угадать все будущие написания.
    Два отказа: слишком широкий вариант подстрокой перехватывает весь портфель
    издательства, слишком узкий — И2 зовётся снова и заводит вторую строку на то
    же издание. Лучшим промтом это не чинится."""
    справочник = list(справочник if справочник is not None else читать())
    по_id = {с.get("id"): с for с in справочник}
    причины = {
        "препринт": "препринт: рецензирования не было",
        "самиздат": ("издателя нет, автор назван" if not поля.get("publisher")
                     else "площадка самиздата"),
        ЗАПАСНАЯ: "нет ни издателя, ни автора",
        НЕ_ОПОЗНАН: "издатель назван, но идентификатора нет нигде",
    }

    # Форма публикации бьёт организацию: препринт остаётся
    # препринтом, даже если его домен совпал со строкой университета —
    # рецензирования на этом домене не было. До 17 сентября проход по ключу шёл
    # первым, и препринт на опознанном домене получил бы S организации. Порядок записан здесь один раз; `состояние()` порядка не задаёт.
    ид = состояние(поля)
    if ид == "препринт":
        строка = по_id.get(ид)
        return (строка, причины[ид]) if строка is not None else (None, None)

    for поле, ключ in (("issn", "issn"), ("isbn", "isbn"), ("домен", "домен")):
        значение = поля.get(ключ)
        if значение:
            найдено = _по_ключу(справочник, поле, значение)
            if найдено[0] is not None:
                return найдено

    if ид is None:
        return (None, None)          # организация настоящая, строки ещё нет → И2
    строка = по_id.get(ид)
    return (строка, причины[ид]) if строка is not None else (None, None)


def оценить(поля, справочник=None):
    """Что справочник говорит про этот источник: база, потолок, состояние, флаг.

    Строки нет — S не ставится вовсе. Раньше здесь стояло −1: незнание
    справочника выдавалось за факт о материале, и любой источник, которого мы
    ещё не занесли, получал столько же, сколько документ без выходных данных.
    Теперь это состояние «не найден»: балл не считается, материал ждёт, пока
    шаг И2 заведёт организацию."""
    строка, чем = сопоставить(поля, справочник)
    if строка is None:
        return {"id": None, "организация": None, "S_база": None, "потолок": None,
                "состояние": "не найден", "имя_в_тэг": False,
                "флаг": ("источник не сопоставлен со справочником — запустить И2 "
                         "(_промты/И2_строка_справочника.md) и завести организацию"),
                "сопоставлено_по": None, "процесс": None, "тип": None, "маркер": None}
    # Через `норм`, как всё сопоставление: «Ждет подтверждения» без ё снимало
    # потолок и флаг разом.
    ждёт = норм(строка.get("статус")) in {норм(с) for с in ЖДУТ_РЕШЕНИЯ}
    return {
        "id": строка.get("id"),
        "организация": строка.get("организация"),
        "S_база": строка.get("S_база"),
        "потолок": ПОТОЛОК_БЕЗ_ПОДТВЕРЖДЕНИЯ if ждёт else None,
        "состояние": "ждёт подтверждения" if ждёт else "найден",
        "имя_в_тэг": str(строка.get("имя_в_тэг") or "").strip().lower() == "да",
        "флаг": (f'строка справочника: {строка.get("статус")}' if ждёт else None),
        "сопоставлено_по": чем,
        "процесс": строка.get("процесс"),
        "тип": строка.get("тип"),
        "маркер": строка.get("маркер"),
        "где_проверено": строка.get("где_проверено"),
        "проверено_дата": строка.get("проверено_дата"),
    }


