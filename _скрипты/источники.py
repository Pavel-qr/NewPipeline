# -*- coding: utf-8 -*-
"""
Справочник источников: читает `_канон/источники.xlsx` и сопоставляет с ним издание,
опознанное И1 по первым страницам оригинала.

  python3 _скрипты/источники.py                     — показать справочник
  python3 _скрипты/источники.py "Crown Currency"    — с чем сопоставится эта строка

Новый источник добавляется по процедуре на листе «как добавлять» в том же файле:
десять вопросов сверху вниз, ответ «да» на первом подходящем даёт процесс и балл.
Процедура лежит рядом со справочником намеренно — отдельный документ про то, как
заполнять таблицу, теряется раньше самой таблицы.

Зачем. Кто отвечает за текст — это факт об организации, а не суждение о материале.
Организаций конечное число, и решение по каждой принимается один раз. Справочник
даёт `S_база`, и это окончательное значение: поправок модели к S не осталось — П5
поле S больше не возвращает вовсе. Единственная правка балла — потолок 0 у строки,
чей маркер ещё не подтверждён реестром.

Три состояния, и путать их нельзя.

  «найден» — строка есть, маркер подтверждён реестром. S = S_база.

  «ждёт подтверждения» — организация опознана, но маркера в реестре пока нет.
  Потолок S = 0 и флаг. Состояние временное: прогон базы проверяет такие строки
  заново, реестры пополняются.

  «не найден» — организации в справочнике нет. S НЕ СТАВИТСЯ ВОВСЕ. Раньше здесь
  стояло −1, и это была ошибка в самой сути: незнание справочника выдавалось за
  факт о материале, и статья в сильном, но ещё не занесённом издании получала
  столько же, сколько скан без выходных данных. Теперь материал уходит в «в
  работе», а шаг И2 заводит организацию.

Сопоставление — только по ключу и по состоянию: сперва форма публикации
(препринт), потом идентификаторы (ISSN, префикс ISBN, домен) — они не зависят от
того, как издание названо в шапке, — потом служебные строки состояния. По названию
не ищется (см. `сопоставить`).
"""
