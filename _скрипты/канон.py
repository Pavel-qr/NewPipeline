# -*- coding: utf-8 -*-
"""
Канон тем: читает topics_индикаторы.xlsx и отдаёт его в двух видах.
Источник правды — сама таблица. В промтах тем нет, они подставляются отсюда.

  разбор():   все темы, только id + название + определение + направления — вход
              для П1т (разметка тем по фрагменту текста); исключений там нет
              намеренно, их применяет П3 к материалу целиком.
  короткий(): все темы, только id + название + определение + исключения — вход
              для П3 (исключения).
  полный(ids): полные карточки названных тем — o1_сюжеты вкладывает карточку
              кандидата в его строку 10_кандидаты_вход.jsonl, вход для П4 и П5.
"""
import os

def _библиотека(модуль, кто):
    import importlib.util as _iu
    сп = _iu.spec_from_file_location("общее", os.path.join(os.path.dirname(os.path.abspath(__file__)), "общее.py"))
    м = _iu.module_from_spec(сп); сп.loader.exec_module(м)
    return м.библиотека(модуль, кто)


ИМЯ = "topics_индикаторы.xlsx"
ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ЗДЕСЬ)          # пайплайн_отбора
ВЫШЕ = os.path.dirname(КОРЕНЬ)           # папка проекта


def найти_таблицу():
    """Таблица канона лежала в разных местах по мере переездов проекта, а жёсткий
    путь тихо ломает канон целиком. Ищем по списку и говорим, где искали.
    Переопределяется переменной окружения КАНОН_ТАБЛИЦА."""
    из_среды = os.environ.get("КАНОН_ТАБЛИЦА")
    # Одно место и одна переменная окружения — как у остальных трёх таблиц.
    # Наследство переездов (пять кандидатов) снято: перебор мест — это и есть
    # «четыре мнения о том, где лежит таблица».
    кандидаты = ([из_среды] if из_среды else []) + [os.path.join(КОРЕНЬ, "_канон", ИМЯ)]
    for п in кандидаты:
        if п and os.path.exists(п):
            return п
    raise SystemExit("не найдена таблица канона " + ИМЯ + "; искал:\n  "
                     + "\n  ".join(кандидаты))
КОЛОНКИ = {
    "topic_id": "id", "human_name": "название",
    "business_definition (дословно)": "определение",
    "directions (дословно)": "направления",
    "exclusions (дословно)": "исключения",
    "actor": "актор", "beneficiary": "бенефициар", "mechanism": "механизм",
    "false_trigger": "ложный_триггер", "false_trigger_check": "проверка_триггера",
    "boundary_with (смежные темы и чем отличаются)": "границы",
}


def читать(путь=None):
    openpyxl = _библиотека("openpyxl", "канон")
    ws = openpyxl.load_workbook(путь or найти_таблицу())["topics (индикаторы)"]
    строки = list(ws.iter_rows(values_only=True))
    шапка = [str(h).strip() if h else "" for h in строки[0]]
    темы = []
    for r in строки[1:]:
        if not r[0]:
            continue
        т = {}
        for h, c in zip(шапка, r):
            if h in КОЛОНКИ:
                т[КОЛОНКИ[h]] = (str(c).strip() if c else "")
        темы.append(т)
    return темы


КОРОТКИЙ = ("id", "название", "определение", "исключения")     # что видит П3
РАЗБОР = ("id", "название", "определение", "направления")       # что видит П1т
# Вид канона по имени — так его выбирает `прогон.py` по объявлению шага.
ВИДЫ = {"короткий": КОРОТКИЙ, "разбор": РАЗБОР}


def короткий(темы=None):
    темы = темы or читать()
    return [{k: т[k] for k in КОРОТКИЙ} for т in темы]


def разбор(темы=None):
    темы = темы or читать()
    return [{k: т[k] for k in РАЗБОР} for т in темы]


def вид(имя, темы=None):
    темы = темы or читать()
    return [{k: т[k] for k in ВИДЫ[имя]} for т in темы]


def полный(ids, темы=None):
    темы = темы or читать()
    return [т for т in темы if т["id"] in set(ids)]


def в_текст(темы):
    куски = []
    for т in темы:
        куски.append("\n".join(f"{k}: {v}" for k, v in т.items() if v))
    return "\n\n---\n\n".join(куски)


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 1 and sys.argv[1] == "полный":
        print(в_текст(полный(sys.argv[2:])))
    elif len(sys.argv) > 1 and sys.argv[1] == "разбор":
        т = разбор()
        текст = в_текст(т)
        print(f"[тем: {len(т)}, знаков: {len(текст)}]\n")
        print(текст)
    else:
        т = короткий()
        текст = в_текст(т)
        print(f"[тем: {len(т)}, знаков: {len(текст)}]\n")
        print(текст)
