ВЫГРУЗКА_КООРДИНАТЫ = ("чанк", "начало", "конец")


def значение(поле):
    """И1 отдаёт поля объектами {значение, как_получено, чем}; остальные — прямо."""
    if isinstance(поле, dict) and "значение" in поле:
        return поле["значение"]
    return поле


def _по_пути(данные, путь):
    """Значение по пути `а.б.в`. Обёртку {значение, как_получено, чем} НЕ
    разворачиваем по дороге: поле может само называться `значение` , и разворот на полпути
    подменял бы словарь его собственным содержимым."""
    для = данные
    куски = путь.split(".")
    for н, кусок in enumerate(куски, 1):
        if not isinstance(для, dict):
            return ОТСУТСТВУЕТ
        для = для.get(кусок, ОТСУТСТВУЕТ)
        if для is ОТСУТСТВУЕТ:
            return ОТСУТСТВУЕТ
        # `null` на середине пути означает, что до листа не добрались: ключа нет.
        # `null` на самом листе — это ответ, и его надо вернуть как есть.
        if для is None and н < len(куски):
            return ОТСУТСТВУЕТ
    return для


def _проверить_поле(где, имя, сырое, правило, нарушения, устаревшее=None):
    обязательно, тип, список = правило

    # Состояние первое: ключа в ответе нет вовсе.
    if сырое is ОТСУТСТВУЕТ:
        if обязательно is ПОЗЖЕ:
            if устаревшее is not None:
                устаревшее.append(f"{где}: «{имя}» — поле введено в контракт позже "
                                  f"этого разбора")
        elif обязательно in (ОБЯЗАТЕЛЬНО, ПУСТОЕ_ЗАКОННО):
            нарушения.append(f"{где}: поля «{имя}» нет вовсе")
        return

    # Состояние второе: ключ есть, значение пустое. Это ОТВЕТ, и законен он
    # ровно там, где так объявлено.
    v = значение(сырое)
    # Пустая строка — та же пустота, что null, только записанная иначе: у
    # ОБЯЗАТЕЛЬНОГО поля она проходила и доезжала до таблицы пустой ячейкой.
    if v is None or (isinstance(v, str) and not v.strip()):
        if обязательно is ОБЯЗАТЕЛЬНО:
            нарушения.append(f"{где}: «{имя}» = {v!r} — поле есть, но пустое. "
                             f"Если пустое значение здесь законный ответ, "
                             f"объяви поле как ПУСТОЕ_ЗАКОННО")
        return
    if тип is int and isinstance(v, bool):
        нарушения.append(f"{где}: «{имя}» = {v!r}, ожидалось число")
        return
    if тип and not isinstance(v, тип):
        нарушения.append(f"{где}: «{имя}» = {v!r} ({type(v).__name__}), "
                         f"ожидался {тип.__name__}")
        return
    if список and v not in СПИСКИ[список]:
        нарушения.append(f"{где}: «{имя}» = {v!r} вне закрытого списка "
                         f"«{список}»; допустимо: {', '.join(map(str, СПИСКИ[список]))}")


def проверить(шаг, данные, где="", устаревшее=None):
    """Нарушения контракта шага. Пустой список — всё в порядке."""
    к = КОНТРАКТЫ[шаг]
    нарушения = []
    записи = данные if к["корень"] == "строки" else [данные]
    for н, запись in enumerate(записи, 1):
        метка = f"{где or шаг}" + (f", строка {н}" if к["корень"] == "строки" else "")
        if not isinstance(запись, dict):
            нарушения.append(f"{метка}: ожидался объект, пришёл {type(запись).__name__}")
            continue
        for имя, правило in (к.get("поля") or {}).items():
            _проверить_поле(метка, имя, запись.get(имя, ОТСУТСТВУЕТ),
                            правило, нарушения, устаревшее)
        # Провенанс: проверяется там же, где поля, и по тем же объявлениям.
        if к.get("как_получено"):
            for имя in (к.get("поля") or {}):
                обёртка = запись.get(имя, ОТСУТСТВУЕТ)
                if обёртка is ОТСУТСТВУЕТ or not isinstance(обёртка, dict):
                    continue          # отсутствие ключа уже названо выше
                откуда = обёртка.get("как_получено", ОТСУТСТВУЕТ)
                if откуда is ОТСУТСТВУЕТ:
                    нарушения.append(f"{метка}: у «{имя}» нет «как_получено» — "
                                     f"непонятно, откуда взято значение")
                elif откуда not in СПИСКИ["как_получено"]:
                    нарушения.append(f"{метка}: «{имя}.как_получено» = {откуда!r} "
                                     f"вне закрытого списка «как_получено»; "
                                     f"допустимо: {', '.join(СПИСКИ['как_получено'])}")
                elif обёртка.get("значение") is None and откуда != "не найдено":
                    нарушения.append(f"{метка}: «{имя}» пусто, но «как_получено» = "
                                     f"{откуда!r}. Пустое значение законно только "
                                     f"при «не найдено»: сказано, что факт взят, "
                                     f"а факта нет")
        for путь, список in (к.get("пути") or {}).items():
            _проверить_поле(метка, путь, _по_пути(запись, путь),
                            (ОБЯЗАТЕЛЬНО, None, список), нарушения, устаревшее)
        for путь, тип in (к.get("пути_типы") or {}).items():
            _проверить_поле(метка, путь, _по_пути(запись, путь),
                            (ОБЯЗАТЕЛЬНО, тип, None), нарушения, устаревшее)
        for ключ, правила in (к.get("вложенные") or {}).items():
            for i, эл in enumerate(запись.get(ключ) or [], 1):
                for имя, правило in правила.items():
                    _проверить_поле(f"{метка}, {ключ}[{i}]", имя,
                                    (эл or {}).get(имя, ОТСУТСТВУЕТ),
                                    правило, нарушения, устаревшее)
        for путь, список in (к.get("пути_вложенных") or {}).items():
            ключ, остаток = путь.split(".", 1)
            for i, эл in enumerate(запись.get(ключ) or [], 1):
                _проверить_поле(f"{метка}, {ключ}[{i}]", остаток,
                                _по_пути(эл, остаток), (ОБЯЗАТЕЛЬНО, None, список),
                                нарушения)
        for путь, тип in (к.get("пути_вложенных_типы") or {}).items():
            ключ, остаток = путь.split(".", 1)
            for i, эл in enumerate(запись.get(ключ) or [], 1):
                _проверить_поле(f"{метка}, {ключ}[{i}]", остаток,
                                _по_пути(эл, остаток), (ОБЯЗАТЕЛЬНО, тип, None),
                                нарушения)
        for путь, список in (к.get("списки_значений") or {}).items():
            ключ, имя = путь.split(".", 1)
            for i, эл in enumerate(запись.get(ключ) or [], 1):
                for v in (эл or {}).get(имя) or []:
                    if v not in СПИСКИ[список]:
                        нарушения.append(f"{метка}, {ключ}[{i}]: «{имя}» содержит "
                                         f"{v!r} вне списка «{список}»")
    return нарушения


def _записать_ответ(папка, шаг, данные):
    к = КОНТРАКТЫ[шаг]
    путь = os.path.join(папка, к["файл"])
    if к["корень"] == "строки":
        with open(путь, "w", encoding="utf-8") as f:
            for о in данные:
                f.write(json.dumps(о, ensure_ascii=False) + "\n")
    else:
        with open(путь, "w", encoding="utf-8") as f:
            json.dump(данные, f, ensure_ascii=False, indent=2)
            f.write("\n")


def _пустое(v):
    return v is None or (isinstance(v, str) and not v.strip())


def починить(шаг, данные):
    """Типичный сбой формы ответа, без смены смысла. True — трогали.

    И1: пустое поле с «поиск/текст/метаданные» → «не найдено»; нет как_получено.
    И3: строка — list объектов → объекты.
    П1: цифра без цитаты выбрасывается, материал не валится целиком.
    """
    if шаг == "И1":
        return _починить_и1(данные)
    if шаг == "И3":
        return _починить_и3(данные)
    if шаг == "П1":
        return _починить_п1(данные)
    return False


def _починить_и1(ответ):
    if not isinstance(ответ, dict):
        return False
    трогали = False
    for сырое in ответ.values():
        if not isinstance(сырое, dict) or "значение" not in сырое:
            continue
        пусто = _пустое(сырое.get("значение"))
        откуда = сырое.get("как_получено", ОТСУТСТВУЕТ)
        if откуда is ОТСУТСТВУЕТ:
            сырое["как_получено"] = "не найдено" if пусто else "текст"
            трогали = True
        elif пусто and откуда in ("поиск", "текст", "метаданные"):
            сырое["как_получено"] = "не найдено"
            сырое["значение"] = None
            трогали = True
    return трогали


def _починить_и3(строки):
    if not isinstance(строки, list):
        return False
    трогали = False
    i = 0
    while i < len(строки):
        с = строки[i]
        if isinstance(с, list):
            куски = [x for x in с if isinstance(x, dict)]
            строки[i:i + 1] = куски or строки[i:i + 1]
            трогали = True
            i += max(len(куски), 1)
        else:
            i += 1
    return трогали


def _починить_п1(строки):
    if not isinstance(строки, list):
        return False
    трогали = False
    for в in строки:
        if not isinstance(в, dict) or not isinstance(в.get("цифры"), list):
            continue
        цифры = в["цифры"]
        держим = [э for э in цифры
                  if isinstance(э, dict) and str(э.get("цитата") or "").strip()]
        if len(держим) != len(цифры):
            в["цифры"] = держим
            трогали = True
    return трогали


def стоп(шаг, данные, где="", папка=None):
    """Проверка на границе: True — шаг должен остановиться.

    Сначала починить известную форму (И1/И3/П1), затем проверить.
    Смысл и закрытые списки по-прежнему не подменяются."""
    if починить(шаг, данные):
        if папка:
            _записать_ответ(папка, шаг, данные)
        print(f"  · {шаг}: поправлена форма ответа")
    нарушения = проверить(шаг, данные, где=где, устаревшее=[])
    for н in нарушения:
        print("  ! " + н)
    if нарушения:
        print(f"  ! {шаг}: ответ модели не по контракту "
              f"(_скрипты/контракты.py) — исправить и повторить")
    return bool(нарушения)


class Битый(Exception):
    """Файл есть, но не читается как JSON: это нарушение, которое сторож обязан
    назвать, а не трассировка, которая его роняет."""


def прочитать(папка, шаг):
    к = КОНТРАКТЫ[шаг]
    путь = os.path.join(папка, к["файл"])
    if not os.path.exists(путь):
        return None
    try:
        if к["корень"] == "строки":
            return [json.loads(л) for л in open(путь, encoding="utf-8") if л.strip()]
        return json.load(open(путь, encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError) as e:
        raise Битый(f"{к['файл']}: не читается как JSON — {e}")


def проверить_папку(папка, устаревшее=None):
    нарушения = []
    где = os.path.basename(папка.rstrip("/"))
    for шаг in КОНТРАКТЫ:
        try:
            данные = прочитать(папка, шаг)
        except Битый as e:
            нарушения.append(f"{где}/{шаг}: {e}")
            continue
        if данные is None:
            continue
        нарушения += проверить(шаг, данные, устаревшее=устаревшее, где=f"{где}/{шаг}")
    return нарушения


def проверить_канон_уровней():
    """Ведущие W уровней обязаны совпадать в каноне и в объявлении здесь.

    `_канон/уровни.json` — производственное ТЗ платформы: чтобы СДЕЛАТЬ единицу
    уровня 2, в ней должно быть то-то. Примечание 4 в самом файле это оговаривает:
    «таблица готовится под производство контента, а не под разметку существующего».
    У1 делает обратное — размечает чужой готовый текст.

    Вписывать ведущие W в промт У1 нельзя: как ведущий критерий они роняют
    воспроизводимость уровня (замер: с 71% до 23%). Поэтому сверка
    идёт не с промтом, а с объявлением в `СПИСКИ["ведущие_W"]`: если контентная
    команда поменяет определение уровня, пайплайн обязан это заметить, даже если
    сам по этому определению напрямую не работает.
    """
    нарушения = []
    файл = os.path.join(КОРЕНЬ, "_канон", "уровни.json")
    if not os.path.exists(файл):
        return [f"нет {файл}"]
    канон = json.load(open(файл, encoding="utf-8"))
    нашлось = 0
    for строка in канон:
        имя = str(строка.get("Уровень платформы") or "")
        w = str(строка.get("Ведущие W") or "").strip()
        # Уровень от примечания отличаем по ДАННЫМ, а не по виду номера: внизу
        # файла лежат договорённости, и одна из них начинается с «3.». У
        # настоящего уровня заполнен когнитивный фокус, у примечания — нет.
        if not w or not str(строка.get("Когнитивный фокус") or "").strip():
            continue
        нашлось += 1
        if re.sub(r"\s+", " ", w) not in [re.sub(r"\s+", " ", x)
                                           for x in СПИСКИ["ведущие_W"]]:
            нарушения.append(f"_канон/уровни.json: ведущие W уровня «{имя}» — «{w}» — "
                             f"не совпадают с объявленными в контрактах; канон "
                             f"правили, а пайплайн об этом не знает")
    if нашлось != 4:
        нарушения.append(f"_канон/уровни.json: уровней с ведущими W {нашлось}, "
                         f"ожидалось 4")
    return нарушения


def схема_промта(шаг):
    """Имена полей из схемы выхода в тексте промта — последний блок ```json.

    Схема в промте — псевдо-JSON («true|false», «... или null»), парсить его как
    JSON нельзя; но имена ключей в нём настоящие, и их достаточно, чтобы сверить
    с контрактом: поле, которое контракт требует, а схема не показывает, модель
    не вернёт (промт, требующий поле прозой и исключающий его схемой, поля не получит)."""
    путь = os.path.join(КОРЕНЬ, "_промты", ПРОМТ[шаг])
    текст = open(путь, encoding="utf-8").read()
    блоки = re.findall(r"```json\s*(.*?)```", текст, re.S)
    if not блоки:
        return None
    return set(re.findall(r'"([^"\n]+)"\s*:', блоки[-1]))


def поля_контракта(шаг):
    """Имена полей, которые контракт шага требует от ответа, — плоским множеством."""
    к = КОНТРАКТЫ[шаг]
    имена = set(к.get("поля") or {})
    for путь in (к.get("пути") or {}):
        имена.update(путь.split("."))
    for ключ, правила in (к.get("вложенные") or {}).items():
        имена.add(ключ)
        имена.update(правила)
    for путь in (к.get("пути_вложенных") or {}):
        имена.update(путь.split("."))
    for путь in (к.get("пути_вложенных_типы") or {}):
        имена.update(путь.split("."))
    for путь in (к.get("списки_значений") or {}):
        имена.update(путь.split("."))
    return имена


def _абзацы(текст):
    return [re.sub(r"\s+", " ", а) for а in re.split(r"\n\s*\n", текст) if а.strip()]


def проверить_промты():
    """Дрейф: промт обязан перечислять ровно те значения, что объявлены здесь,
    и показывать в схеме выхода все поля, которые контракт от него требует.

    Это то самое место, где родилась ошибка: список жил в промте прозой, код про
    него не знал, и `CC-BY-NC-ND` оказалась «не предусмотрена» молча.

    Значение списка ищется не подстрокой по всему тексту, а внутри перечисления:
    в абзаце, где стоит хотя бы половина значений списка (или в блоке схемы).
    Подстрока по всему тексту находила «не определено» в самой запрещающей фразе
    «верни `не определено`», хотя в перечислении его не было."""
    нарушения = []
    for шаг, списки in СПИСКИ_ПРОМТА.items():
        путь = os.path.join(КОРЕНЬ, "_промты", ПРОМТ[шаг])
        if not os.path.exists(путь):
            нарушения.append(f"{шаг}: промта {ПРОМТ[шаг]} нет")
            continue
        сырой = open(путь, encoding="utf-8").read()
        # Переносы строк схлопываем: в промте список свободно переносится, и
        # «книжное\nиздательство» — это то же значение, а не другое.
        текст = re.sub(r"\s+", " ", сырой)
        абзацы = _абзацы(сырой)
        for имя in списки:
            вне = {з for (ш, сп, з) in ВНЕ_ОБЛАСТИ if ш == шаг and сп == имя}
            значения = [re.sub(r"\s+", " ", str(v)) for v in СПИСКИ[имя] if str(v) not in вне]
            # Абзацы-перечисления: где стоит хотя бы половина значений.
            перечисления = [а for а in абзацы
                            if sum(1 for з in значения if з in а) * 2 >= max(len(значения), 1)]
            нет = [з for з in значения if not any(з in а for а in перечисления)]
            if нет:
                где = "нет ни в одном перечислении" if перечисления else "перечисления нет вовсе"
                нарушения.append(f"{ПРОМТ[шаг]}: списка «{имя}» не хватает значений: "
                                 f"{', '.join(нет)} — {где}; модель их не вернёт, "
                                 f"потому что о них не знает")
            # Обратная сторона: объявили «вне области» — значит, в промте этого
            # значения быть не должно.
            лгут = [з for з in sorted(вне)
                    if re.sub(r"\s+", " ", з) in текст]
            if лгут:
                нарушения.append(f"{ПРОМТ[шаг]}: значения {', '.join(лгут)} списка "
                                 f"«{имя}» объявлены вне области шага, но в промте "
                                 f"встречаются — объявление не совпадает с промтом")
        # Схема выхода в промте против контракта.
        схема = схема_промта(шаг)
        if схема is None:
            нарушения.append(f"{ПРОМТ[шаг]}: в промте нет блока ```json со схемой выхода")
            continue
        нет = sorted(поля_контракта(шаг) - схема)
        if нет:
            нарушения.append(f"{ПРОМТ[шаг]}: контракт {шаг} требует поля, которых нет в "
                             f"схеме выхода промта: {', '.join(нет)}")
    return нарушения




def _темы_канона():
    """Идентификаторы тем канона. Ленивый импорт: канон тянет openpyxl, а
    большинству вызовов контрактов он не нужен."""
    сп = importlib.util.spec_from_file_location(
        "_канон_тем", os.path.join(ЗДЕСЬ, "канон.py"))
    м = importlib.util.module_from_spec(сп)
    сп.loader.exec_module(м)
    return {т["id"] for т in м.читать()}


def проверить_выгрузку(корень=None):
    """Полнота и форма выгрузки в производство.

    Выгрузки может не быть вовсе — это не нарушение: её собирает шаг В
    (`выгрузка.py`) у принятых и пограничных материалов. Нарушение — выгрузка,
    которая есть и неполна: производство читает её как единственный вход и
    отличить «поля не бывает» от «поле забыли» не может."""
    корень = корень or os.path.join(КОРЕНЬ, ВЫГРУЗКА_КОРЕНЬ)
    нарушения = []
    if not os.path.isdir(корень):
        return нарушения

    for имя, откуда in ВЫГРУЗКА_ОБЩЕЕ.items():
        свой, канон = os.path.join(корень, имя), os.path.join(КОРЕНЬ, откуда)
        if not os.path.exists(свой):
            нарушения.append(f"{ВЫГРУЗКА_КОРЕНЬ}/{имя}: файла нет, а он общий "
                             f"на всю выгрузку")
        elif (open(свой, encoding="utf-8").read()
              != open(канон, encoding="utf-8").read()):
            нарушения.append(f"{ВЫГРУЗКА_КОРЕНЬ}/{имя} разошёлся с {откуда}. "
                             f"Это копия производственного ТЗ; обновлять её — "
                             f"решение человека, сторож только сообщает")

    темы = _темы_канона()
    for папка in sorted(os.listdir(корень)):
        путь = os.path.join(корень, папка)
        if not os.path.isdir(путь):
            continue
        for файл in ВЫГРУЗКА_ПРОСТЫЕ:
            if not os.path.exists(os.path.join(путь, файл)):
                нарушения.append(f"{папка}/{файл}: файла нет")
        for файл, контракт in ВЫГРУЗКА.items():
            п = os.path.join(путь, файл)
            if not os.path.exists(п):
                нарушения.append(f"{папка}/{файл}: файла нет")
                continue
            try:
                данные = json.load(open(п, encoding="utf-8"))
            except json.JSONDecodeError as e:
                нарушения.append(f"{папка}/{файл}: не читается как JSON — {e}")
                continue
            записи = данные if контракт["корень"] == "строки" else [данные]
            if контракт["корень"] == "строки" and not isinstance(данные, list):
                нарушения.append(f"{папка}/{файл}: ожидался список записей")
                continue
            for н, запись in enumerate(записи, 1):
                метка = f"{папка}/{файл}" + (
                    f", строка {н}" if контракт["корень"] == "строки" else "")
                if not isinstance(запись, dict):
                    нарушения.append(f"{метка}: запись не объект")
                    continue
                for поле, правило in контракт["поля"].items():
                    _проверить_поле(метка, поле, _по_пути(запись, поле),
                                    правило, нарушения)
                оригинал = запись.get("исходник")
                if файл == "паспорт.json" and оригинал and not os.path.exists(
                        os.path.join(путь, оригинал)):
                    нарушения.append(f"{метка}: копии оригинала {оригинал!r} в папке нет")
                тема = запись.get("тема")
                if файл == "заготовки.json" and тема and тема not in темы:
                    нарушения.append(
                        f"{метка}: темы {тема!r} в каноне нет. Карточки тем в "
                        f"выгрузку не едут, склейка идёт по идентификатору — "
                        f"значит переименование темы рвёт её молча")
    return нарушения


