def _читаемые_имена(исходник):
    """Имена полей, которые ЧИТАЕТ этот скрипт, и префиксы обходов по правилу.

    Чтением считаются `о["имя"]`, `о.get("имя")`, `о.pop("имя")`,
    `о.setdefault("имя")` — то есть обращение к уже существующему полю. Ключ в
    собираемом словаре (`{"имя": значение}`) и присваивание (`о["имя"] = …`)
    — это запись, и потребителем не делает."""
    имена, префиксы = set(), set()
    try:
        дерево = ast.parse(исходник)
    except SyntaxError:
        return имена, префиксы
    ЧИТАЮЩИЕ = {"get", "pop", "setdefault"}
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Subscript) and isinstance(узел.ctx, ast.Load):
            если = узел.slice
            if isinstance(если, ast.Constant) and isinstance(если.value, str):
                имена.add(если.value)
        elif isinstance(узел, ast.Call) and isinstance(узел.func, ast.Attribute):
            if узел.func.attr in ЧИТАЮЩИЕ and узел.args:
                первый = узел.args[0]
                if isinstance(первый, ast.Constant) and isinstance(первый.value, str):
                    имена.add(первый.value)
            elif узел.func.attr == "startswith" and узел.args:
                первый = узел.args[0]
                if isinstance(первый, ast.Constant) and isinstance(первый.value, str):
                    префиксы.add(первый.value)
    return имена, префиксы


def _кто_читает():
    """Тексты, в которых поле может быть востребовано: код скриптов и промты.

    Промт САМОГО шага сюда не входит, и это главное различение проверки. Он поле
    не потребляет, а **заказывает**: «верни мне `ограничения`» — это производитель.
    Считать заказчика потребителем — значит объявить востребованным всё, что модель
    вообще возвращает, и проверка станет тавтологией. Именно на этом первая версия
    признала `ограничения` нужными: их просит П2 и не читает никто.

    Два настоящих потребителя, и они ищутся по-разному — в этом точность проверки.

    В КОДЕ считается только **чтение**, и отличить его от записи можно лишь
    разбором кода, а не поиском строки. `.get("жанр")` и `["сюжеты"]` — чтение;
    ключ `"ограничения":` в собираемом словаре — запись. Разница решающая:
    `ограничения` собирает `b5_карта`, имя стоит в её исходнике в кавычках, и по
    простому поиску поле выглядит востребованным. На деле его никто не читает —
    объявление без потребителя.

    Упоминание в комментарии тоже не потребление: про поле можно написать целый
    абзац и ни разу его не прочитать. Первая версия проверки считала иначе и
    потому не заметила `doi_или_issn` — её имя стояло в комментарии о переезде
    источника в И1.

    Отдельно — обращение НЕ по имени, а по правилу: `o4_скоринг` собирает цитаты
    обходом всех ключей, начинающихся на «цитат», и потому не называет ни одного
    из них. Такое обращение тоже читается: из кода берутся литералы всех
    `.startswith(...)`, и поле, попадающее под такой префикс, считается
    востребованным. Код, назвавший класс полей вместо одного поля, сказал о
    потребности не меньше, чем прямое обращение.

    В ПРОМТЕ ДРУГОГО ШАГА достаточно простого упоминания: промт — это текст для
    модели, там поле называют словами, а не синтаксисом. Но одного упоминания
    мало: **поле должно ещё и приходить в этот промт**. Имена полей повторяются
    у разных шагов — `ограничения` просят у себя и П2, и У1, — и без проверки
    входа чужой заказ выглядит потреблением. Что приходит в промт, известно
    точно: `прогон.py` называет входные файлы каждого шага, а какие поля в этих
    файлах лежат, видно в самих файлах.

    Больше потребителей у поля нет: всё, что не читает ни код, ни следующая
    модель, — не данные, а груз."""
    def прочесть(подпапка, имя):
        return open(os.path.join(КОРЕНЬ, подпапка, имя),
                    encoding="utf-8", errors="replace").read()

    # Имена читаются ПО СКРИПТАМ, а не одним плоским множеством: скрипт —
    # потребитель поля только у того файла, который он открывает. Плоское
    # множество обнуляло проверку, стоило имени поля совпасть у двух шагов:
    # `уровень` читали у выхода У1, и 193 сюжета `04_решение.json` с мёртвым
    # `уровень` числились востребованными.
    # Какие файлы скрипт ОТКРЫВАЕТ, знает разбор кода в `карта_файлов.py`;
    # упоминание имени файла в докстроке читателем не делает.
    сп = importlib.util.spec_from_file_location("карта_файлов", os.path.join(ЗДЕСЬ, "карта_файлов.py"))
    _карта = importlib.util.module_from_spec(сп); сп.loader.exec_module(_карта)
    по_скрипту = {}
    for и in sorted(os.listdir(os.path.join(КОРЕНЬ, "_скрипты"))):
        if not и.endswith(".py"):
            continue
        текст = прочесть("_скрипты", и)
        try:
            читает, _, _ = _карта.разобрать(os.path.join(КОРЕНЬ, "_скрипты", и))
        except SyntaxError:
            читает = set()
        по_скрипту[и] = (читает, *_читаемые_имена(текст))
    промты = {шаг: прочесть("_промты", файл) for шаг, файл in ПРОМТ.items()}
    return по_скрипту, промты


def _читатели_файла(по_скрипту, файл):
    """Скрипты, открывающие этот файл, — его читатели.
    Возвращает (имена полей, префиксы), собранные только по ним."""
    имена, префиксы = set(), set()
    for исходник, (читает, ч, п) in по_скрипту.items():
        if файл in читает:
            имена |= ч
            префиксы |= п
    return имена, tuple(sorted(префиксы))


def груз(корень_материалов):
    """Поля, которые едут в модель и не названы её промтом. Возвращает список
    (шаг, поле, байт).

    Вторая половина вопроса «у данных нет потребителя» — и та, где деньги.
    Первая (`сироты`) смотрит, читает ли кто выход модели. Эта смотрит с другой
    стороны: **что модель получает и не использует**. Поле, которого промт не
    называет, модель читает и не применяет — а платится за него каждым вызовом,
    на каждом материале, столько раз, во сколько промтов едет файл.

    Почему меряется в байтах, а не в штуках. Штук всегда немного, и по ним
    кажется, что чинить нечего; а вес распределён крайне неровно: `ограничения`
    в карте — одно поле и десятая часть объёма. Решение принимается по весу.

    Чего проверка НЕ утверждает: что поле можно выкинуть. Она говорит, что за
    него платят без спроса. Дальше человек решает — назвать его в промте или
    убрать из входа. И убирать надо с замером: вход модели в этом пайплайне уже
    один раз меняли «очевидно к лучшему», и воспроизводимость упала с 72% до 54%."""
    _, промты = _кто_читает()
    папки = [os.path.join(корень_материалов, и)
             for и in sorted(os.listdir(корень_материалов))
             if os.path.isdir(os.path.join(корень_материалов, и))]
    найдено = {}
    for шаг, файлы in _входы_модельных().items():
        if шаг not in промты:
            continue
        текст = промты[шаг]
        for имя_файла in файлы:
            for папка in папки:
                путь = os.path.join(папка, имя_файла)
                if not os.path.exists(путь):
                    continue
                try:
                    записи = ([json.loads(л) for л in open(путь, encoding="utf-8") if л.strip()]
                              if имя_файла.endswith(".jsonl")
                              else [json.load(open(путь, encoding="utf-8"))])
                except (json.JSONDecodeError, UnicodeDecodeError):
                    continue
                for з in записи:
                    if not isinstance(з, dict):
                        continue
                    for имя, значение in з.items():
                        вес = len(json.dumps(значение, ensure_ascii=False))
                        ключ = (шаг, имя_файла, имя, назван_в(имя, текст))
                        найдено[ключ] = найдено.get(ключ, 0) + вес
    return найдено


def _входы_промтов(корень_материалов):
    """Шаг → множество имён полей, которые в его промт реально приходят.

    Имена входных файлов берутся из `прогон.py` — там они и объявлены, — а поля
    читаются из самих файлов в папках материалов. Ни список файлов, ни список
    полей сюда не переписывается: обе копии разошлись бы с оригиналом."""
    папки = [os.path.join(корень_материалов, и)
             for и in sorted(os.listdir(корень_материалов))
             if os.path.isdir(os.path.join(корень_материалов, и))]
    поля_файла = {}

    def поля(имя_файла):
        if имя_файла in поля_файла:
            return поля_файла[имя_файла]
        собрано = set()
        for папка in папки:
            путь = os.path.join(папка, имя_файла)
            if not os.path.exists(путь):
                continue
            try:
                записи = ([json.loads(л) for л in open(путь, encoding="utf-8") if л.strip()]
                          if имя_файла.endswith(".jsonl")
                          else [json.load(open(путь, encoding="utf-8"))])
            except (json.JSONDecodeError, UnicodeDecodeError):
                continue
            for з in записи:
                собрано |= set(_имена_полей(з))
            if собрано:
                break          # одного материала достаточно: состав полей один
        поля_файла[имя_файла] = собрано
        return собрано

    входы = {}
    for шаг, файлы in _входы_модельных().items():
        свои = set()
        for имя_файла in файлы:
            свои |= поля(имя_файла)
        входы.setdefault(шаг, set()).update(свои)
    return входы


def _ключи_везде(объект, собрано=None):
    """Все имена ключей объекта на любой глубине."""
    собрано = set() if собрано is None else собрано
    if isinstance(объект, dict):
        for к, v in объект.items():
            собрано.add(к)
            _ключи_везде(v, собрано)
    elif isinstance(объект, list):
        for v in объект:
            _ключи_везде(v, собрано)
    return собрано


ЛИТЕРАЛЫ = {"null", "true", "false"}


def обещания_входа(корень_материалов):
    """Промт называет во входе только то, что ему дают.

    Раздел «## Вход» каждого промта читается буквально: всякое имя в обратных
    кавычках — либо файл из объявленных входов шага (`шаги.py`), либо ключ,
    который в этих файлах есть (ключи берутся из настоящих файлов в папках
    материалов, на любой глубине), либо литерал JSON. Промт без раздела «Вход»
    — нарушение: что модель получает, должно быть написано в одном месте.

    Класс, а не случай: П5 обещала модели баллы A и B, которых ей не давали, и
    модель их додумывала; П1 не называла обязательный
    `чанк_id` (1.3); И3 называла файл, которого нет (1.15). Правило одно на все
    девять промтов и не даёт разойтись снова.

    Возвращает (нарушения, непроверенные): непроверенные — шаги, чьих входных
    файлов нет ни в одной папке корня, там ключи взять неоткуда."""
    ш = _шаги()
    папки = [os.path.join(корень_материалов, и) for и in sorted(os.listdir(корень_материалов))
             if os.path.isdir(os.path.join(корень_материалов, и))]

    def ключи_файла(имя):
        if имя == "topics_индикаторы.xlsx":
            # Канон тем модель получает одним из видов (см. `прогон._вызов`):
            # ключи — объединение полей всех видов `канон.ВИДЫ`.
            сп = importlib.util.spec_from_file_location("канон", os.path.join(ЗДЕСЬ, "канон.py"))
            к = importlib.util.module_from_spec(сп); сп.loader.exec_module(к)
            return {п for в in к.ВИДЫ.values() for п in в}
        if имя == "00_справочник_вход.json":
            # Заявка на И2 снимается после исполнения и в готовых папках не
            # лежит; её поля известны там, где она пишется.
            сп = importlib.util.spec_from_file_location("о_источник", os.path.join(ЗДЕСЬ, "о_источник.py"))
            м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
            return set(м.ПОЛЯ_ЗАЯВКИ)
        # Ключи — объединение по всем папкам, а не по первой: у материала без
        # тем список `темы` пуст, и ключи его элементов в одной папке не видны.
        собрано, было = set(), False
        for папка in папки:
            путь = os.path.join(папка, имя)
            if not os.path.exists(путь):
                continue
            try:
                записи = ([json.loads(л) for л in open(путь, encoding="utf-8") if л.strip()]
                          if имя.endswith(".jsonl") else [json.load(open(путь, encoding="utf-8"))])
            except (json.JSONDecodeError, UnicodeDecodeError):
                continue
            if записи:
                было = True
                собрано |= _ключи_везде(записи)
        return собрано if было else None

    нарушения, непроверенные = [], []
    for с in ш.модельные():
        промт = с["чем"]
        текст = open(os.path.join(КОРЕНЬ, "_промты", промт), encoding="utf-8").read()
        м = re.search(r"^## Вход\s*$(.*?)(?=^## |\Z)", текст, re.S | re.M)
        if not м:
            нарушения.append(f"{промт}: нет раздела «## Вход» — что модель получает, не записано")
            continue
        файлы = set(ш.файлы_входа(с)) | {в[len(ш.КАНОН):] for в in с["входы"] if в.startswith(ш.КАНОН)}
        ключи, нет_файлов = set(), []
        for имя in list(ш.файлы_входа(с)) + [в[len(ш.КАНОН):] for в in с["входы"] if в.startswith(ш.КАНОН)]:
            к = ключи_файла(имя)
            if к is None:
                нет_файлов.append(имя)
            else:
                ключи |= к
        if нет_файлов:
            непроверенные.append(f"{промт}: в {os.path.basename(корень_материалов)} нет "
                                 f"{', '.join(нет_файлов)} — ключи входа проверить не на чем")
            continue
        for имя in sorted(set(re.findall(r"`([^`\n]+)`", м.group(1)))):
            if имя in ЛИТЕРАЛЫ or имя in файлы or os.path.basename(имя) in файлы:
                continue
            if all(ч in ключи for ч in имя.split(".")):
                continue
            нарушения.append(f"{промт}, раздел «Вход»: `{имя}` — ни файл из входов шага "
                             f"({', '.join(sorted(файлы))}), ни ключ в них")
    return нарушения, непроверенные


def сироты(корень_материалов):
    """Поля модельных выходов, у которых не видно потребителя.

    Ответ делится надвое, и это разные диагнозы.

    **Отказ** — поле, которое промт шага заказывает, а читать некому: модель
    тратит на него вызов, файл его возит, и всё зря. Это то, ради чего проверка
    и написана.

    **Реликт** — поле, которого нынешний промт уже не заказывает: оно осталось в
    старых разборах от прежней версии вопроса. Ронять из-за него нельзя — иначе
    единственным способом позеленеть станет правка сохранённых ответов модели, а
    подменять то, что модель на самом деле сказала, в этом пайплайне запрещено.
    Реликты печатаются отдельной строкой, как `устаревшие разборы` выше: это
    история, а не нарушение.

    Что проверка НЕ говорит ни в одном из двух случаев: что поле бесполезно. Она
    говорит, что потребителя не видно, — решение за человеком: либо полю дают
    потребителя, либо его убирают из промта. Молча лежать оно после этого не может.

    Почему без списка разрешённых исключений. Список исключений — это та самая
    щель, через которую класс возвращается: первое же поле, записанное в него
    «на время», останется там навсегда, и проверка снова начнёт молчать."""
    по_скрипту, промты = _кто_читает()
    входы = _входы_промтов(корень_материалов)
    найдено = {}

    def прямо(имя, чей_выход, читаемые, префиксы):
        """Прямое обращение: по имени в кавычках или по префиксу — в скриптах,
        читающих ЭТОТ файл, — либо из чужого промта, в который поле приходит."""
        if имя in читаемые:
            return True
        if префиксы and имя.startswith(префиксы):
            return True
        return any(чей != чей_выход and назван_в(имя, текст)
                   and имя in входы.get(чей, ())
                   for чей, текст in промты.items())

    for шаг, контракт in КОНТРАКТЫ.items():
        читаемые, префиксы = _читатели_файла(по_скрипту, контракт["файл"])
        for папка in sorted(os.listdir(корень_материалов)):
            путь = os.path.join(корень_материалов, папка)
            if not os.path.isdir(путь):
                continue
            try:
                данные = прочитать(путь, шаг)
            except Битый:
                continue          # уже названо в проверить_папку
            if данные is None:
                continue
            записи = данные if контракт["корень"] == "строки" else [данные]
            for запись in записи:
                родня = _имена_полей(запись)
                for имя, (потомки, предки) in родня.items():
                    if прямо(имя, шаг, читаемые, префиксы):
                        continue
                    if any(прямо(п, шаг, читаемые, префиксы) for п in потомки):   # дорога к нужному
                        continue
                    # Едет внутри нужного: контейнер читают по имени — его
                    # содержимое востребовано. Граница метода: поле внутри
                    # контейнера, который читают целиком, а разбирают по другим
                    # полям, статически не отличить от
                    # нужного — попытка отличать по «подписным» полям дала ложные
                    # тревоги на тезисах и сверках. Такие поля ловятся иначе:
                    # схема выхода в промте сверяется с контрактом (см.
                    # `проверить_промты`), и поле, которого нет в схеме, новые
                    # ответы не несут.
                    if any(прямо(р, шаг, читаемые, префиксы) for р in предки):
                        continue
                    заказан = имя in промты.get(шаг, "")
                    ключ = (шаг, имя, заказан)
                    найдено.setdefault(ключ, [0, set()])
                    найдено[ключ][0] += 1
                    найдено[ключ][1].add(папка)
    return найдено


