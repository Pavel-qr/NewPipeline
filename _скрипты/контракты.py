РЕЖИМЫ = ("промты", "материалы")
ПОДСКАЗКА = ("python3 _скрипты/контракты.py промты              — промты и канон против контракта\n"
             "python3 _скрипты/контракты.py материалы [корень]  — плюс выходы моделей в папках")


def main(режим=None, корень_материалов=None):
    """Два разных сторожа — два явных режима. Раньше режим выбирался тем, есть
    ли аргумент, и «зелёный» без аргумента путали с полной проверкой: узкий режим давал 0 там, где широкий давал 1."""
    if режим not in РЕЖИМЫ:
        print(ПОДСКАЗКА)
        return 1
    if режим == "материалы":
        корень_материалов = _общее().корень_материалов(корень_материалов, "контракты")
    нарушения = проверить_промты() + проверить_канон_уровней()
    if нарушения:
        print(f"ПРОМТЫ РАСХОДЯТСЯ С КОНТРАКТОМ — {len(нарушения)}:")
        for н in нарушения:
            print("  ✗ " + н)
    else:
        print("промты перечисляют ровно объявленные значения; "
              "ведущие W уровней совпадают с каноном")

    # Объявление без потребителя — та же ошибка, и объявлять контракт
    # выгрузки, не проверяя его, значило бы завести ещё один.
    выг = проверить_выгрузку()
    if выг:
        print(f"ВЫГРУЗКА РАСХОДИТСЯ С КОНТРАКТОМ — {len(выг)}:")
        for н in выг:
            print("  ✗ " + н)
    elif os.path.isdir(os.path.join(КОРЕНЬ, ВЫГРУЗКА_КОРЕНЬ)):
        print("выгрузка полна по контракту")
    else:
        # Не молчать: контракт объявлен, а проверять его не на чем.
        print(f"выгрузки ({ВЫГРУЗКА_КОРЕНЬ}/) нет — контракт выгрузки объявлен, но не проверен")

    if режим == "материалы":
        всего, устаревшее = 0, []
        for путь in _общее().папки_материалов(корень_материалов, "контракты"):
            свои = проверить_папку(путь, устаревшее)
            всего += len(свои)
            for н in свои:
                print("  ✗ " + н)
        обещано, непроверено = обещания_входа(корень_материалов)
        if обещано:
            print(f"\nпромты обещают модели то, чего ей не дают — {len(обещано)}:")
            for н in обещано:
                print("  ✗ " + н)
            нарушения += [1] * len(обещано)
        else:
            print("\nпромты во входе называют только свои файлы и их поля")
        for н in непроверено:
            print("  ? " + н)
        безхозные = сироты(корень_материалов)
        отказы = {к: v for к, v in безхозные.items() if к[2]}
        реликты = {к: v for к, v in безхозные.items() if not к[2]}
        print(f"\nнарушений контракта в выходах моделей: {всего}")
        if отказы:
            print(f"поля без потребителя: {len(отказы)} — промт их заказывает, "
                  f"а читать некому: модель платит за них каждым вызовом")
            for (шаг, имя, _), (сколько, папки) in sorted(отказы.items()):
                print(f"  ✗ {шаг} · {имя}: встречается {сколько} раз "
                      f"в {len(папки)} папках; ни один скрипт и ни один чужой "
                      f"промт его не называет")
            нарушения += [1] * len(отказы)
        else:
            print("полей без потребителя нет: всё, что заказывают промты, кто-то читает")
        неназванное = {к: в for к, в in груз(корень_материалов).items() if not к[3]}
        if неназванное:
            по_файлам = {}
            for (шаг, файл, имя, _), вес in неназванное.items():
                по_файлам.setdefault((шаг, файл), []).append((вес, имя))
            print("\nгруз в модельном входе — поля, которые промт не называет:")
            for (шаг, файл), поля in sorted(по_файлам.items()):
                всего_файла = sum(в for (ш, ф, _, _), в in груз(корень_материалов).items()
                                  if (ш, ф) == (шаг, файл))
                вес_груза = sum(в for в, _ in поля)
                print(f"  {шаг} ← {файл}: {вес_груза/1024:.0f} КБ из "
                      f"{всего_файла/1024:.0f} КБ = {вес_груза/всего_файла:.0%}")
                for вес, имя in sorted(поля, reverse=True)[:6]:
                    print(f"      {имя:28} {вес/1024:7.1f} КБ")
        if реликты:
            имена = ", ".join(f"{ш}·{и}" for ш, и, _ in sorted(реликты))
            print(f"реликты прежних версий промтов: {len(реликты)} — {имена}. "
                  f"Нынешний промт их не заказывает, новые разборы их не дадут")
        if устаревшее:
            папки = {н.split("/")[0] for н in устаревшее}
            print(f"устаревших разборов: {len(папки)} папок, {len(устаревшее)} полей "
                  f"из более нового контракта — это не нарушение модели")
        нарушения += [1] * всего
    return 1 if нарушения else 0


