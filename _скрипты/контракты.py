def _имена_полей(объект):
    """Имена ключей ответа с их потомками: {имя: множество имён внутри него}.

    Берутся из настоящих ответов в папках материалов, а не из промта: промт может
    просить одно, а приходить будет другое — ровно так `doi_или_issn` пережила
    свой вопрос на полтора месяца.

    Возвращается {имя: (потомки, предки)} — родня нужна для двух правил, и они
    работают в разные стороны.

    ВВЕРХ: контейнер, ведущий к востребованному полю, — дорога к нему, а не груз.
    `сверки` в ответе П4 по имени не читает никто, но внутри лежат цитаты, которые
    собирает `o4_скоринг`.

    ВНИЗ: если сам контейнер читают по имени, его содержимое едет вместе с ним и
    сиротой не является. `термины` берёт `b5_агрегат` целиком — значит и `термин`
    внутри востребован, спрашивать про каждый листок отдельно бессмысленно.

    Важно, что вниз передаётся только ПРЯМОЕ обращение — по имени или по
    префиксу. Иначе правила схлопнутся: `сверки` стали бы востребованы через
    лежащую внутри цитату, а потом сами очистили бы `совпало` и `в_карточке`,
    которые не читает никто."""
    потомки, предки = {}, {}

    def обойти(узел, родня):
        """Возвращает множество всех имён внутри узла."""
        внутри = set()
        if isinstance(узел, dict):
            for имя, значение in узел.items():
                предки.setdefault(имя, set()).update(родня)
                ниже = обойти(значение, родня | {имя})
                потомки.setdefault(имя, set()).update(ниже)
                внутри.add(имя)
                внутри |= ниже
        elif isinstance(узел, list):
            for элемент in узел[:5]:   # пяти хватает: ключи в списке одни и те же
                внутри |= обойти(элемент, родня)
        return внутри

    обойти(объект, set())
    return {имя: (потомки.get(имя, set()), предки.get(имя, set()))
            for имя in потомки}


def назван_в(имя, текст):
    """Назван ли `имя` в тексте промта — с поправкой на склонение.

    Промт — человеческий текст: поле `сюжеты` там упомянуто как «сюжетов» или
    «сюжетам», а `ограничения` — как «ограничения». Точное вхождение даёт ложную
    тревогу на каждом склоняемом имени: первая версия объявила грузом 563 КБ
    сюжетов, которые П5 обсуждает в каждом абзаце.

    Правило: имя делится по подчёркиваниям, у каждого слова длиной больше пяти
    букв отсекаются две последние, и от текста требуется содержать все основы.
    Слова короче трёх букв («о», «к») отбрасываются: они есть в любом тексте и
    ничего не подтверждают."""
    слова = [ч for ч in имя.split("_") if len(ч) >= 3]
    if not слова:
        слова = [имя]
    основы = [ч[:-2] if len(ч) > 5 else ч for ч in слова]
    return all(о in текст for о in основы)


