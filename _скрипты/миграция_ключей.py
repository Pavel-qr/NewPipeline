# -*- coding: utf-8 -*-
"""
Разовая миграция: проставляет идентификаторы в строки справочника
источников, чтобы можно было снять сопоставление по названию.

  python3 _скрипты/миграция_ключей.py           — показать, что будет сделано
  python3 _скрипты/миграция_ключей.py записать  — записать

Идентификаторы не придумываются и не ищутся: они уже лежат в `00_источник.json`
разобранных материалов. Скрипт смотрит, какой материал на какую строку сел, и
переносит ключ в строку.

Три правила переноса — по убыванию надёжности ключа:

ISSN переносится как есть. Он принадлежит изданию и больше ничему.

ISBN переносится префиксом издателя, а не целиком: в справочнике строка на
издательство, а ISBN — на конкретную книгу. Префикс берётся из дефисной формы
(`978-1-62825-891-2` → `978-1-62825`); если дефисов нет, но на строку село два и
более ISBN — берётся их общее начало не короче семи цифр (`9780593798690` и
`9780593832691` → `9780593`, это и есть префикс Penguin Random House). Одиночный
ISBN без дефисов пропускается: разложить его на группы без реестра нельзя.

Домен переносится, только если КАЖДАЯ его часть уже названа в самой строке.
`health.harvard.edu` в строку Harvard Health Publishing — да, обе части там есть.
`nvidia.com` в строку Schneider Electric — нет: презентацию Schneider выложили на
сайте NVIDIA, и это домен площадки, а не издателя. `nature.com` в строку
Humanities and Social Sciences Communications — тоже нет: иначе одна строка
перехватит все журналы платформы Nature. Без этого правила миграция сама
наплодила бы ровно те ложные совпадения, ради устранения которых затевалась.
"""
import os, sys, json, re, importlib.util
from collections import defaultdict

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ЗДЕСЬ)

def _материалы():
    сп = importlib.util.spec_from_file_location("общее", os.path.join(ЗДЕСЬ, "общее.py"))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м.корень_материалов(os.environ.get("МАТЕРИАЛЫ"), "миграция_ключей")
МИН_ПРЕФИКС = 7          # цифр: 978 + группа регистрации + регистрант

сп = importlib.util.spec_from_file_location("источники",
                                            os.path.join(ЗДЕСЬ, "источники.py"))
_ист = importlib.util.module_from_spec(сп); сп.loader.exec_module(_ист)

ВЕРХНИЙ = {"com", "org", "net", "ru", "edu", "gov", "int", "info", "io", "ai",
           "me", "co", "uk", "de", "fr", "cn", "eu", "pro", "news", "press"}


def префикс_isbn(значения):
    """Префикс издателя из списка ISBN, севших на одну строку."""
    дефисные = [з for з in значения if "-" in str(з) or "–" in str(з)]
    for з in дефисные:
        группы = re.split(r"[-–—]", str(з).strip())
        if len(группы) >= 4:
            return "-".join(группы[:-2]), f"дефисная форма {з}"
    цифры = sorted({re.sub(r"\D", "", str(з)) for з in значения})
    if len(цифры) < 2:
        return None, None
    общее = os.path.commonprefix(цифры)
    if len(общее) >= МИН_ПРЕФИКС:
        return общее, f"общее начало {len(цифры)} ISBN: {', '.join(цифры)}"
    return None, None


def домен_свой(домен, строка):
    """Каждая часть домена названа в самой строке справочника?"""
    хост = re.sub(r"^www\.", "", str(домен or "").strip().lower())
    части = [ч for ч in хост.split(".") if ч and ч not in ВЕРХНИЙ]
    if not части:
        return False
    текст = _ист.норм(f"{строка.get('организация')} {строка.get('варианты')}")
    текст = re.sub(r"[^a-zа-я0-9]", "", текст)
    return all(ч in текст for ч in части)


def собрать():
    """Что каждая строка справочника могла бы взять у своих материалов."""
    по_строке = defaultdict(lambda: {"issn": set(), "isbn": set(),
                                     "домен": set(), "папки": []})
    МАТЕРИАЛЫ = _материалы()
    for папка in sorted(os.listdir(МАТЕРИАЛЫ)):
        ф = os.path.join(МАТЕРИАЛЫ, папка, "00_источник.json")
        if not os.path.exists(ф):
            continue
        о = json.load(open(ф, encoding="utf-8"))
        оценка, поля = о.get("оценка") or {}, о.get("поля") or {}
        if оценка.get("состояние") != "найден" or not оценка.get("организация"):
            continue
        с = по_строке[оценка["организация"]]
        с["папки"].append(папка)
        for к in ("issn", "isbn", "домен"):
            if поля.get(к):
                с[к].add(поля[к])
    return по_строке


def main(записывать):
    строки = {с["организация"]: с for с in _ист.читать()}
    собранное = собрать()
    план = []
    for орг, найденное in sorted(собранное.items()):
        строка = строки.get(орг)
        if строка is None:
            continue
        # Служебные строки описывают процесс, а не организацию: у препринта и
        # самиздата идентификатора нет по определению. Их не трогаем.
        if строка.get("id") in _ист.СЛУЖЕБНЫЕ:
            continue
        новое = {}
        if найденное["issn"] and not строка.get("issn"):
            новое["issn"] = ("|".join(sorted(найденное["issn"])), "ISSN материала")
        # Имя ПОЛЯ — `isbn` (см. `источники.КОЛОНКИ`), не заголовок листа.
        # До 17 сентября здесь стояло `isbn_префикс`, правая часть была всегда
        # истинна, и защита «дописываем только пустое» не работала.
        if найденное["isbn"] and not строка.get("isbn"):
            пр, почему = префикс_isbn(найденное["isbn"])
            if пр:
                новое["isbn"] = (пр, почему)
        if найденное["домен"] and not строка.get("домен"):
            свои = [д for д in sorted(найденное["домен"]) if домен_свой(д, строка)]
            чужие = [д for д in sorted(найденное["домен"]) if not домен_свой(д, строка)]
            if свои:
                новое["домен"] = ("|".join(свои), "домен назван в самой строке")
            for д in чужие:
                план.append((орг, строка["id"], "домен", д, "ОТКЛОНЁН: части домена "
                             "нет в строке — это площадка, а не издатель", False))
        for поле, (значение, почему) in новое.items():
            план.append((орг, строка["id"], поле, значение, почему, True))

    ширина = max((len(о) for о, *_ in план), default=10)
    беру = [п for п in план if п[5]]
    for орг, ид, поле, значение, почему, брать in план:
        знак = "+" if брать else "✗"
        print(f" {знак} {орг[:ширина]:{ширина}} {поле:13} {str(значение):26} {почему}")
    print(f"\nк записи: {len(беру)} значений в {len({п[1] for п in беру})} строках")

    if not записывать:
        print("это предпросмотр; чтобы записать — "
              "`python3 _скрипты/миграция_ключей.py записать`")
        return 0

    путь, кн, ws, ряд_шапки, _, место = _ист.открыть(кто="миграция_ключей")
    _ист.проверить_ключи_записи({п[2]: 1 for п in план if п[5]}, место, "миграция_ключей")
    записано = 0
    for ряд in range(ряд_шапки + 1, ws.max_row + 1):
        ид = ws.cell(ряд, место["id"]).value
        for орг, и, поле, значение, почему, брать in план:
            if брать and и == ид:
                ws.cell(ряд, место[поле], значение)
                записано += 1
    кн.save(путь)
    print(f"записано значений: {записано} → {путь}")
    return 0


if __name__ == "__main__":
    sys.exit(main(len(sys.argv) > 1 and sys.argv[1] == "записать"))
