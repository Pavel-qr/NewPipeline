# модели на неё тратить незачем. Модель получает найденное готовым.
РЕГУЛЯРКИ = {
    "doi":  re.compile(r"\b10\.\d{4,9}/[-._;()/:A-Za-z0-9]+"),
    "issn": re.compile(r"\b\d{4}-\d{3}[\dXx]\b"),
    # ISBN — только по слову ISBN рядом или по префиксу 978/979. Без этого
    # хвост DOI `10.1108/JBS-08-2024-0145` читается как ISBN «08-2024-0145».
    "isbn": re.compile(r"(?:ISBN[\s:—–-]*([\d—–\-\s]{9,20}[\dXx])"
                       r"|\b(97[89][—–\-\s]?[\d—–\-\s]{9,14}[\dXx])\b)"),
    "url":  re.compile(r"https?://[^\s)>\]\"']+"),
}

