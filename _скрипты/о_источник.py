"""
Связка шагов И1 (опознание) и И2 (строка справочника) с пайплайном.

  python3 _скрипты/о_источник.py вход     материалы/<папка> исходники/файл.pdf
  python3 _скрипты/о_источник.py свести   материалы/<папка>
  python3 _скрипты/о_источник.py записать материалы/<папка>

Три скриптовых шага вокруг двух модельных:

  [вход] → И1 модель → [свести] → (если нет строки) И2 модель → [записать]

Это шаг 0: он идёт до Б1 и ни от чего в стволе не зависит. И1 читает первые
страницы ОРИГИНАЛА, а не нормализованный текст, поэтому нормализация ему не
нужна вовсе.

Почему в начале, а не перед скорингом. Опознать материал — подготовительное
действие: пока неизвестно, что это за документ и кто за ним стоит, разбирать
его нечем. Если поставить опознание в конец, справочник дозаводится после того,
как за материал уже заплачено восемьюдесятью четырьмя вызовами Б4, а при работе
пачкой одна и та же организация всплывает у нескольких материалов и каждый ждёт
своей очереди. Здесь же наоборот: к моменту скоринга S известна, и ни одна
строка не уходит в «в работе» по причине «источник не сопоставлен».

Суждений скрипт не выносит: он собирает вход модели, раскладывает её ответ по
полям и дописывает строку в `_канон/источники.xlsx`.
"""
