def проверить_списки_авторов(плоско):
    """`author_name` и `author_credential` — два параллельных списка через
    `общее.РАЗДЕЛИТЕЛЬ_АВТОРОВ`.

    Сдвиг на одну позицию молча приписывает регалию одного человека другому, и по
    таблице этого не видно: имена и должности выглядят одинаково правдоподобно в
    любом сочетании. Поэтому длины сверяются здесь, а не «когда-нибудь заметим».

    У организации и редакции регалии нет — там прочерк целиком, и это не ошибка."""
    имена = _общее.список_авторов(плоско.get("author_name"))
    регалии = _общее.список_авторов(плоско.get("author_credential"))
    if not имена or not регалии:
        return None
    if плоско.get("author_type") in ("организация", "редакция"):
        return None
    if len(имена) != len(регалии):
        return (f"И1 вернула {len(имена)} имён и {len(регалии)} регалий: "
                f"{плоско['author_name']!r} против {плоско['author_credential']!r}. "
                f"Списки параллельны, разделитель — «{_общее.РАЗДЕЛИТЕЛЬ_АВТОРОВ}»; на месте "
                "неизвестной регалии должен стоять прочерк.")
    return None


def читать(папка, имя):
    п = os.path.join(папка, имя)
    return json.load(open(п, encoding="utf-8")) if os.path.exists(п) else None


def писать(папка, имя, данные):
    with open(os.path.join(папка, имя), "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False, indent=2)
    print(f"  → {os.path.join(папка, имя)}")


# ------------------------------------------------------- годность идентификатора
def _цифры(значение):
    return [з for з in str(значение or "").upper() if з.isdigit() or з == "X"]


def годен(вид, значение):
    """Проверяет, что строка вообще может быть идентификатором этого вида.

    У ложных идентификаторов две разные причины, и арифметика закрывает только
    первую:

    1. Строка не идентификатор вовсе. `2023-2025` — диапазон годов, а под маску
       ISSN подходит. Таких на 29 материалах было девять, и все девять
       отсеиваются контрольной цифрой.
    2. Строка — настоящий идентификатор ЧУЖОЙ работы, взятый из списка
       литературы. `9781529714340` — реальный ISBN книги из библиографии, он
       проходит любую проверку. Это лечится не арифметикой, а тем, что И1
       смотрит только первые три страницы, где библиографии нет.

    Проверка стоит здесь, а не в промте, по той же причине, по которой здесь
    стоят регулярки: это механическая работа, и вызов модели на неё тратить
    незачем. Заодно ложный идентификатор больше не доезжает до И2 — а
    идентификатор — ключ строки справочника, и записанный туда мусор
    остался бы там навсегда.
    """
    з = _цифры(значение)
    if вид == "issn":
        # Семь цифр с весами 8…2, сумма по модулю 11, восьмой знак — дополнение.
        if len(з) != 8 or "X" in з[:7]:
            return False
        сумма = sum(int(ц) * (8 - i) for i, ц in enumerate(з[:7]))
        остаток = сумма % 11
        контроль = "0" if остаток == 0 else ("X" if остаток == 1 else str(11 - остаток))
        return контроль == з[7]
    if вид == "isbn":
        if len(з) == 13:
            if "X" in з:
                return False
            сумма = sum(int(ц) * (1 if i % 2 == 0 else 3) for i, ц in enumerate(з[:12]))
            return (10 - сумма % 10) % 10 == int(з[12])
        if len(з) == 10:
            if "X" in з[:9]:
                return False
            сумма = sum(int(ц) * (10 - i) for i, ц in enumerate(з[:9]))
            остаток = (11 - сумма % 11) % 11
            return ("X" if остаток == 10 else str(остаток)) == з[9]
        return False
    if вид == "doi":
        # У DOI контрольной суммы нет — проверяется структура: префикс
        # регистранта `10.NNNN` и непустой суффикс после косой черты.
        return bool(re.fullmatch(r"10\.\d{4,9}/\S+", str(значение or "").strip()))
    return True


# --------------------------------------------------------------------- вход
СТРАНИЦ = 3       # сколько первых страниц оригинала получает И1


def _из_оригинала(исходник, сколько):
    """Сырой текст первых страниц ИСХОДНОГО файла, до нормализации.

    Выходные данные живут в вёрстке: титул, оборот титула, колонтитул. Б1 их
    как раз стирает — колонтитул «JOURNAL OF BUSINESS STRATEGY VOL. 47 NO. 1»
    уходит в `снятые_колонтитулы`, и в нормализованном тексте названия журнала
    больше нет. Поэтому опознание читает оригинал, а не `00_текст.txt`."""
    b1 = _модуль("b1", "b1_нормализация.py")
    расш = os.path.splitext(исходник)[1].lower()
    if расш not in b1.ЧИТАТЕЛИ:
        return None, None, None
    страницы, мета = b1.ЧИТАТЕЛИ[расш](исходник)
    return "\n".join(страницы[:сколько]), мета, len(страницы)


def вход(папка, исходник=None):
    """00_опознание_вход.json — то, что читает И1.

    Шаг 0: идёт до Б1 и от него не зависит. И1 получает путь к оригиналу и
    текст первых СТРАНИЦ страниц; чего там нет — ищет в интернете.

    Хвост документа не передаётся намеренно. У книги в конце колофон, но у
    научной статьи — список литературы, и именно оттуда пришли 5 из 14 ложных
    срабатываний регулярок: чужие DOI и ISBN из чужих работ."""
    # Только оригинал. Запасной путь через `00_мета.json`/`00_текст.txt` снят:
    # это выходы Б1, который стоит позже, и шаг молча уходил на них при опечатке
    # в пути. Путь разрешается от корпуса (`общее`).
    if not исходник:
        sys.exit("о_источник вход: нужен путь к оригиналу")
    исходник = _общее.путь_исходника(исходник, "о_источник вход")
    текст, мета_файла, страниц = _из_оригинала(исходник, СТРАНИЦ)
    имя = os.path.basename(исходник)
    if текст is None:
        sys.exit(f"нечего опознавать: нет читателя для {имя}")

    найдено, отсеяно = {}, {}
    for ключ, рег in РЕГУЛЯРКИ.items():
        хиты = рег.findall(текст)
        if ключ == "isbn":
            хиты = [re.sub(r"\D", "", (h[0] or h[1]) if isinstance(h, tuple) else h)
                    for h in хиты]
        if ключ == "url":
            найдено[ключ] = list(dict.fromkeys(хиты))[:5] or None
            continue
        # DOI часто кончается точкой предложения — она в идентификатор не входит.
        хиты = [str(х).rstrip(".,;)]") for х in хиты]
        прошли = list(dict.fromkeys(х for х in хиты if годен(ключ, х)))
        мимо = [х for х in хиты if not годен(ключ, х)]
        # Все годные, а не первый по тексту: у журнала два ISSN (печатный и
        # онлайн), и первый по порядку — ключ строки справочника, то есть выбор
        # определял S. Выбирает И1, видя страницу, а не порядок.
        найдено[ключ] = прошли or None
        if мимо:
            отсеяно[ключ] = sorted(set(мимо))[:4]

    данные = {
        "файл": имя,
        "путь_к_оригиналу": _общее.в_корпусе(исходник),
        "канал": _общее.канал(исходник),
        "страниц_всего": страниц,
        "страниц_передано": min(СТРАНИЦ, страниц or СТРАНИЦ),
        "текст_первых_страниц": текст,
        "метаданные_файла": мета_файла or {},
        "найдено_регулярками": найдено,
        "отсеяно_как_негодное": отсеяно or None,
    }
    писать(папка, "00_опознание_вход.json", данные)
    есть = [к for к, v in найдено.items() if v]
    print(f"  оригинал: {имя or '—'}, страниц {страниц}, передано "
          f"{данные['страниц_передано']}")
    print(f"  идентификаторы на этих страницах: {', '.join(есть) if есть else 'ни одного'}")
    for ключ, мимо in отсеяно.items():
        print(f"  отсеяно как негодный {ключ}: {', '.join(мимо)}")
    return 0

# Поля заявки на И2 — то, что промт И2 вправе называть во входе (сторож
# `контракты.обещания_входа`); сама заявка после исполнения снимается.
ПОЛЯ_ЗАЯВКИ = ("издатель", "идентификаторы", "issn", "isbn", "домен", "doi",
               "material_type", "автор")


# -------------------------------------------------------------------- свести
def _значение(поле):
    """И1 возвращает {значение, как_получено, чем}. Берём значение и запоминаем,
    откуда оно: «не найдено» после поиска и «не смотрели» — разные вещи."""
    if isinstance(поле, dict):
        return поле.get("значение"), поле.get("как_получено")
    return поле, None


def свести(папка):
    _общее.входы_шага(папка, "о_источник.py свести")
    ответ = читать(папка, "00_опознание.json")
    if _контракты.стоп("И1", ответ, os.path.basename(папка.rstrip("/")), папка):
        return 4

    плоско, откуда = {}, {}
    for поле in ПОЛЯ_И1:
        v, как = _значение(ответ.get(поле))
        плоско[поле] = v
        откуда[поле] = как
    плоско["год"] = None
    дата = плоско.get("publication_date")
    if дата:
        г = re.search(r"(1[89]|20)\d{2}", str(дата))
        плоско["год"] = int(г.group()) if г else None

    # Домен — только из `домен_издателя`: это официальный сайт организации, и
    # И1 возвращает его отдельно. Ссылка ведёт туда, где файл ЛЕЖИТ, а это не
    # всегда тот, кто его выпустил: презентацию Schneider Electric выложили на
    # сайте NVIDIA, и `nvidia.com` как ключ увёл бы материал в чужую строку. Запасной путь через `source_url` снят: при
    # пустом домене он брал ключ из места, где файл лежит, — ровно то, от чего
    # промт И1 предостерегает. Нет домена — нет ключа, и это
    # честнее чужой строки справочника.
    домен = None
    значение = плоско.get("домен_издателя")
    if значение:
        д = re.search(r"(?:https?://)?([^/\s]+)", str(значение))
        # Не lstrip("www."): он снимает ЛЮБЫЕ ведущие символы из набора {w, .},
        # и wsj.com превращается в sj.com. Ровно это и случилось на материале 24.
        домен = re.sub(r"^www\.", "", д.group(1).lower()) if д else None
    плоско["домен"] = домен

    рассинхрон = проверить_списки_авторов(плоско)
    if рассинхрон:
        # Форма ответа модели — тот же класс, что контракт: код 4, не «3»,
        # которого в контракте кодов (общее.py) не существует.
        print("  ! " + рассинхрон)
        print("  ! И1: ответ не по форме — исправить и повторить")
        return _общее.КОНТРАКТ

    источник = {
        "издание": плоско.get("publisher"),
        "автор": плоско.get("author_name"),
        "issn": плоско.get("issn"), "isbn": плоско.get("isbn"),
        "домен": домен, "doi": плоско.get("doi"),
    }
    # Оценка считается по плоским полям И1 целиком: кроме идентификаторов ей
    # нужны `publisher`, `author_name` и `material_type` — по ним выбирается
    # служебная строка, когда организации за текстом нет.
    оценка = _источники.оценить(плоско)
    писать(папка, "00_источник.json", {"поля": плоско, "как_получено": откуда,
                                       "что_искал": ответ.get("что_искал"),
                                       "оценка": оценка})

    print(f'  издатель: {источник["издание"] or "— не опознан"}')
    print(f'  автор:    {источник["автор"] or "— не опознан"}')
    if оценка["S_база"] is None:
        заявка = {
            "издатель": источник["издание"],
            "идентификаторы": {"issn": источник["issn"], "isbn": источник["isbn"],
                               "домен": домен, "doi": источник["doi"]},
            "material_type": плоско.get("material_type"),
            "автор": источник["автор"],
        }
        assert set(заявка) | set(заявка["идентификаторы"]) == set(ПОЛЯ_ЗАЯВКИ)
        писать(папка, "00_справочник_вход.json", заявка)
        # Это штатная ветка, а не отказ: шаг отработал, `00_источник.json`
        # записан, заявка на И2 лежит файлом — по нему прогон и решит, что И2
        # нужен. Раньше здесь стояла двойка, и прогон обрывался на исправном
        # пути у 9 папок из 29.
        print("  строки справочника нет → нужен И2 (заявка записана)")
        return 0
    # Организация нашлась — заявку на И2 надо снять, а не оставить лежать.
    # Прогон решает, нужен ли И2, по наличию этого файла: пока он на месте, шаг
    # требуется снова, даже когда справочник уже отвечает. Так встали 42 и 86
    # после того, как строка «нет организации» начала ловиться.
    заявка = os.path.join(папка, "00_справочник_вход.json")
    if os.path.exists(заявка):
        os.remove(заявка)
        print("  снята заявка на И2: организация нашлась")
    print(f'  справочник: {оценка["организация"]}, S = {оценка["S_база"]} '
          f'(по {оценка["сопоставлено_по"]})')
    return 0


# ------------------------------------------------------------------ записать
def не_найдено(значение):
    return значение is None


def записать(папка):
    """Запись в справочник — под замком на всё чтение-правку-сохранение (Д-5)."""
    with _общее.блокировка(_источники.найти_таблицу()):
        return _записать(папка)


def _записать(папка):
    _общее.входы_шага(папка, "о_источник.py записать")
    строка = читать(папка, "00_справочник_строка.json")
    if _контракты.стоп("И2", строка, os.path.basename(папка.rstrip("/"))):
        return 4
    плоско = (читать(папка, "00_источник.json") or {}).get("поля") or {}
    имя_папки = os.path.basename(папка.rstrip("/"))

    # Книга, лист и шапка — через `источники.открыть()`: те же имена полей,
    # что у читателя, и та же проверка «ключи ⊆ шапка».
    СПРАВОЧНИК, кн, ws, ряд_шапки, _, место = _источники.открыть(кто="о_источник записать")

    тип = строка.get("publisher_type")
    процесс = ПРОЦЕСС_ПО_ТИПУ.get(тип)
    if процесс is None:
        процесс = тип
        print(f'  ! publisher_type «{тип}» нет в таблице перевода — записан как есть')
    S = строка.get("S_база")

    # Ключ строки берётся у И2, а чего она не нашла — у материала. Вход И2 и так
    # содержит идентификаторы документа, и терять их незачем: строка без ключа
    # недостижима, её не найдёт ни один материал. Раньше такой ключ падал
    # на пол — так `j_design_society` осталась без ISSN 2732-527X, который всё
    # это время лежал в `16_weak_ties/00_источник.json`.
    # ISSN наследуется: он принадлежит изданию, а строка справочника у журнала
    # и есть издание.
    #
    # Домен наследуется ТОЛЬКО из `домен_издателя` — поля, которое И1 объявляет
    # официальным сайтом организации. Поле `домен` брать нельзя: оно выведено из
    # `source_url`, то есть из места, где файл ЛЕЖИТ. У `16_weak_ties` там
    # `doi.org`, и такой ключ перехватил бы все материалы с DOI разом; у
    # презентации Schneider там был `nvidia.com`. Это та же ошибка, от которой
    # мы отсекли домены на миграции, — здесь она зашла бы с другой стороны.
    ИЗ_МАТЕРИАЛА = {"issn": "issn", "домен": "домен_издателя"}
    ключи = {}
    for колонка, поле in ИЗ_МАТЕРИАЛА.items():
        ключи[колонка] = строка.get(колонка) or плоско.get(поле) or None
    # ISBN материала — номер книги, а не префикс издателя: подставлять его
    # нельзя, разложить на группы без реестра невозможно. Берём только то, что
    # нашла И2.
    ключи["isbn"] = строка.get("isbn_префикс")
    взято_у_материала = [к for к in ИЗ_МАТЕРИАЛА
                         if not строка.get(к) and ключи.get(к)]

    # Ключи словаря — имена ПОЛЕЙ из `источники.КОЛОНКИ`, не заголовки листа:
    # в какую колонку ложится поле, решает шапка через `место`.
    значения = {
        "id": строка.get("org_id"),
        "организация": строка.get("организация"),
        "варианты": строка.get("варианты написания"),
        "issn": ключи["issn"], "isbn": ключи["isbn"],
        "домен": ключи["домен"], "процесс": процесс,
        "маркер": строка.get("маркер"), "где_проверено": строка.get("где_проверено"),
        "тип": тип,
        "проверено_дата": строка.get("проверено_дата"),
        "S_база": S,
        # Правило из листа «как добавлять»: имя в тэг только при +2. Считается,
        # а не спрашивается у модели — иначе это ещё одно место, где можно разойтись.
        "имя_в_тэг": "да" if S == 2 else "нет",
        "статус": строка.get("статус"), "заметка": строка.get("заметка") or "",
        # Реестры и запросы, по которым организацию проверяли. Без них
        # «маркер не найден» нельзя отличить от «не искали».
        "что_искал": "; ".join(строка.get("что_искал") or []) or None,
        # Происхождение: из какого материала заведена строка. Без этого связь
        # «строка ↔ материал» живёт только в момент совпадения, и восстановить
        # её потом нечем.
        "материалы": имя_папки,
    }

    # Строка с таким org_id уже есть — это не повод молча выйти. Раньше здесь
    # печаталось «строка не дублируется», и на этом всё: недостающие ключи так и
    # оставались пустыми, а строка — недостижимой. Теперь ветка сливает: пустые
    # колонки существующей строки дозаполняются, заполненные не трогаются.
    # Дедуп идёт по ИДЕНТИФИКАТОРУ, а не только по `org_id`. `org_id` придумывает
    # модель — это тот же сочинённый ключ, который мы убрали из сопоставления
    #, и он там же ошибается: на `16_weak_ties` И2 вернула
    # `proceedings_design_society`, а строка на то же издание уже стояла под
    # `j_design_society`. По названию их не сличить, по ISSN — однозначно.
    _источники.проверить_ключи_записи(значения, место, "о_источник записать")
    ряды = {ws.cell(r, место["id"]).value: r for r in range(ряд_шапки + 1, ws.max_row + 1)}
    если_есть = ряды.get(строка.get("org_id"))
    if не_найдено(если_есть):
        для_сверки = list(_источники.читать())
        for поле, значение in (("issn", ключи["issn"]), ("isbn", ключи["isbn"]),
                               ("домен", ключи["домен"])):
            for часть in str(значение or "").split("|"):
                if not часть.strip():
                    continue
                чужая, чем = _источники._по_ключу(для_сверки, поле, часть.strip())
                if чужая is not None:
                    если_есть = ряды.get(чужая.get("id"))
                    print(f'  = та же организация уже стоит под id «{чужая.get("id")}» '
                          f'({чем}) — сливаю, а не завожу вторую строку')
                    break
            if если_есть:
                break
    if если_есть:
        дописано = []
        for колонка in ("issn", "isbn", "домен", "маркер", "где_проверено",
                        "проверено_дата", "что_искал"):
            ячейка = ws.cell(если_есть, место[колонка])
            if not ячейка.value and значения.get(колонка):
                ячейка.value = значения[колонка]
                дописано.append(колонка)
        ячейка = ws.cell(если_есть, место["материалы"])
        было = [ч.strip() for ч in str(ячейка.value or "").split("|") if ч.strip()]
        if имя_папки not in было:
            ячейка.value = "|".join(было + [имя_папки])
            дописано.append("материалы")
        # Файл пересохраняется только если в него что-то записано: openpyxl
        # сериализует книгу заново, и «сохранить без изменений» меняет байты —
        # для отпечатков (Д-4) это правка канона, и все её читатели устаревали бы
        # на каждом прогоне.
        if дописано:
            кн.save(СПРАВОЧНИК)
        print(f'  = {строка["org_id"]} уже в справочнике, строка {если_есть}: '
              + (f'дописано {", ".join(дописано)}' if дописано else "дописывать нечего"))
        писать(папка, "00_справочник_записана.json",
               {"org_id": строка.get("org_id"), "строка": если_есть,
                "дата": str(date.today()), "как": "дополнена",
                "дописано": дописано})
        return свести(папка)

    # Строка без идентификатора недостижима. У служебных типов идентификатора
    # нет по природе — там это нормально.
    БЕЗ_КЛЮЧА = {"препринт-сервер", "блог, канал, самиздат", "нет издателя"}
    if not any(ключи.values()) and тип not in БЕЗ_КЛЮЧА:
        print(f'  ! у строки «{значения["организация"]}» нет ни ISSN, ни префикса '
              f'ISBN, ни домена — её не найдёт ни один материал.')
        print(f'    Ни И2, ни материал ключа не дали. Повторите И2: у типа '
              f'«{тип}» идентификатор должен существовать.')

    ряд = ws.max_row + 1
    for поле, н in место.items():
        ws.cell(ряд, н, значения.get(поле))
    кн.save(СПРАВОЧНИК)
    print(f'  + {значения["id"]}: {значения["организация"]}, S = {S}, '
          f'{значения["статус"]} → строка {ряд}')
    if взято_у_материала:
        print(f'    ключ взят у материала: {", ".join(взято_у_материала)}')
    писать(папка, "00_справочник_записана.json",
           {"org_id": значения["id"], "строка": ряд,
            "дата": str(date.today()), "как": "заведена",
            "ключ_от_материала": взято_у_материала})
    return свести(папка)


КОМАНДЫ = {"вход": вход, "свести": свести, "записать": записать}

if __name__ == "__main__":
    if len(sys.argv) < 3 or sys.argv[1] not in КОМАНДЫ:
        sys.exit("python3 _скрипты/о_источник.py вход материалы/<папка> [исходник]\n"
                 "                            свести|записать материалы/<папка>")
    sys.exit(КОМАНДЫ[sys.argv[1]](*sys.argv[2:]) or 0)
