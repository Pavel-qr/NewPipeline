# -*- coding: utf-8 -*-
"""
Связка шага У1 (уровни заготовки) с пайплайном.

  python3 _скрипты/о_уровень.py вход    материалы/<папка>
  python3 _скрипты/о_уровень.py свести  материалы/<папка>

Два скриптовых шага вокруг одного модельного:

  О4 → [вход] → У1 модель (по заготовке за вызов) → [свести] → реестр

Заготовки шаг берёт функцией `реестр.заготовки()`, а не из `реестр.json`:
реестр собирается ПОСЛЕ У1 и вписывает уровни из `00_уровень_сведён.json`.
Второй писатель того же файла стирал бы уровни при перезапуске реестра.

Почему после отбора. Уровень в каноне определён для пары «тема × уровень», и
ставится он заготовке — принятой теме, — а не сюжету: отсеянные темы не
размечаются вовсе.
"""
import os, sys, json, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))


def _модуль(имя, файл):
    сп = importlib.util.spec_from_file_location(имя, os.path.join(ЗДЕСЬ, файл))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


_уровни = _модуль("уровни", "уровни.py")
_b4 = _модуль("b4", "b4_проверка_выжимок.py")
_общее = _модуль("общее", "общее.py")
_к = _модуль("контракты", "контракты.py")
_реестр = _модуль("реестр", "реестр.py")

ПОЛЯ_БЛОКА = ("id", "суть", "механизм", "полнота", "цитата",
              "инструменты", "опора_под_практику")
ПОЛЯ_СЮЖЕТА = ("название", "механизм", "автономен", "блоки")


def читать(папка, имя):
    п = os.path.join(папка, имя)
    return json.load(open(п, encoding="utf-8")) if os.path.exists(п) else None


def писать(папка, имя, данные):
    п = os.path.join(папка, имя)
    with open(п, "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False, indent=2)
    print(f"  → {п}")


# --------------------------------------------------------------------- вход
def вход(папка):
    """00_уровень_вход.jsonl — по строке на заготовку.

    Файл пишется всегда, в том числе пустым: пустой значит «принятых тем нет, и
    размечать нечего». Отсутствие файла значило бы «шаг не выполнялся» — это
    разные вещи (то же правило, что у И3 и И2)."""
    _общее.входы_шага(папка, "о_уровень.py вход")
    _, _, заготовки = _реестр.заготовки(папка, кто="о_уровень вход")
    # Содержание блоков лежит в агрегате: заготовка хранит только их id.
    агрегат = читать(папка, "04_агрегат.json")
    по_ид = {б["id"]: б for б in агрегат.get("блоки") or []}

    канон = _уровни.читать()
    выход = os.path.join(папка, "00_уровень_вход.jsonl")
    строки = []
    for з in заготовки:
        тема = з.get("тема")
        свои_блоки = [ {к: по_ид[б].get(к) for к in ПОЛЯ_БЛОКА}
                       for б in з.get("блоки") or [] if б in по_ид ]
        строки.append({
            "тема": тема,
            "материал": з.get("материал"),
            "папка": os.path.basename(папка.rstrip("/")),
            "заготовка": {
                "сюжеты": [{к: с.get(к) for к in ПОЛЯ_СЮЖЕТА}
                           for с in з.get("сюжеты") or []],
                "блоки": свои_блоки,
                "опора_под_практику": з.get("опора_под_практику") or [],
                "инструменты": з.get("опора_под_заберите_с_собой") or [],
            },
            "канон_уровней": {str(у): в for у, в in _уровни.столбец(тема, канон).items()},
        })
    with open(выход, "w", encoding="utf-8") as f:
        for с in строки:
            f.write(json.dumps(с, ensure_ascii=False) + "\n")
    print(f"  заготовок: {len(строки)}"
          + (f" → {выход}" if строки else " — принятых тем нет, шаг не нужен"))
    return 0


# ------------------------------------------------------------------- свести
def свести(папка):
    """Ответы У1 → уровни в реестре.

    Цитаты сверяются дословно по агрегату — тем же `норм`, что на Б4 и О4: одна
    нормализация на все проверки цитат в пайплайне.

    Полнота ответа — по вопросу: У1 получала `канон_уровней` каждой заготовки
    (`00_уровень_вход.jsonl`) и обязана ответить по каждому уровню. Уровень без
    ответа раньше просто не попадал в набор, и это было неотличимо от честного
    «не закрыт»."""
    _общее.входы_шага(папка, "о_уровень.py свести")
    ответы = os.path.join(папка, "00_уровень.jsonl")
    _, _, заготовки = _реестр.заготовки(папка, кто="о_уровень свести")
    агрегат = читать(папка, "04_агрегат.json")
    спрошено = {с["тема"]: set(int(у) for у in с["канон_уровней"])
                for с in (json.loads(л) for л in open(os.path.join(папка, "00_уровень_вход.jsonl"),
                                                       encoding="utf-8") if л.strip())}

    def строки_текста(о):
        if isinstance(о, str):
            yield о
        elif isinstance(о, dict):
            for v in о.values():
                yield from строки_текста(v)
        elif isinstance(о, list):
            for v in о:
                yield from строки_текста(v)

    текст = "\n".join(_b4.норм(т) for т in строки_текста(агрегат))

    # Контракт — там же, где ответ модели впервые читают, до сверки цитат и
    # до записи в реестр. Тот же порядок, что на Б4, Б5, О1 и О4: сначала форма
    # ответа, потом его содержание.
    разборы = [json.loads(л) for л in open(ответы, encoding="utf-8") if л.strip()]
    if _к.стоп("У1", разборы, os.path.basename(папка.rstrip("/"))):
        return 4

    по_теме = {}
    чужие, без_цитаты, не_отвечено = [], [], []
    for о in разборы:
        уровни = {}
        for у in о.get("уровни") or []:
            ц = у.get("цитата")
            # Закрытый уровень без цитаты — не «закрыт», а недоказан: ТЗ обещает
            # дословную сверку, а сверять нечего.
            if у.get("закрыт") and not (ц or "").strip():
                без_цитаты.append((о.get("тема"), у.get("уровень")))
            elif у.get("закрыт") and _b4.норм(ц) not in текст:
                чужие.append((о.get("тема"), у.get("уровень"), ц[:110]))
            уровни[int(у["уровень"])] = {
                "закрыт": bool(у.get("закрыт")),
                "сюжеты": у.get("сюжеты") or [],
                "что_покрыто": у.get("что_покрыто"),
                "чего_нет": у.get("чего_нет"),
                "цитата": ц,
                "почему": у.get("почему"),
                "граница_проверена": у.get("граница_проверена"),
            }
        по_теме[о.get("тема")] = {"уровни": уровни,
                                  "ограничения": о.get("ограничения") or []}
        пропущены = sorted(спрошено.get(о.get("тема"), set()) - set(уровни))
        if пропущены:
            не_отвечено.append((о.get("тема"), пропущены))

    if без_цитаты:
        print(f"закрытых уровней без цитаты: {len(без_цитаты)}")
        for т, у in без_цитаты:
            print(f"  ✗ {т}, уровень {у}")
        print("  ! закрытый уровень доказывается цитатой из заготовки — исправить и повторить")
        return _общее.КОНТРАКТ
    if не_отвечено:
        for т, у in не_отвечено:
            print(f"  ✗ {т}: нет ответа по уровням {', '.join(map(str, у))}")
        print("  ! У1 ответила не по всем уровням из канон_уровней — повторить")
        return _общее.КОНТРАКТ
    if чужие:
        print(f"цитат не из материала: {len(чужие)}")
        for т, у, ц in чужие:
            print(f"  ✗ {т}, уровень {у}: {ц}")
        print("  ! У1 цитирует не заготовку — исправить и повторить")
        return _общее.КОНТРАКТ

    нет = [з.get("тема") for з in заготовки if з.get("тема") not in по_теме]
    if нет:
        print(f"  ! У1 не ответила по заготовкам: {', '.join(нет)}")
        return _общее.КОНТРАКТ

    уровни = {}
    for з in заготовки:
        разбор = по_теме[з["тема"]]
        закрытые = sorted(у for у, в in разбор["уровни"].items() if в["закрыт"])
        # Набор, а не диапазон. Диапазон «мин–макс» обещает уровни, которых может
        # не быть: сюжеты на 1 и 3 дают «1–3», хотя двойки в заготовке нет.
        уровни[з["тема"]] = {
            "закрытые": закрытые,
            "разбор": {str(у): в for у, в in sorted(разбор["уровни"].items())},
            "ограничения": разбор["ограничения"],
        }

    # Единственный выход шага. Реестр собирается после и берёт уровни отсюда.
    писать(папка, "00_уровень_сведён.json",
           {"заготовок": len(заготовки), "уровни": уровни})
    for тема, у in уровни.items():
        print(f'  {тема:34} уровни {у["закрытые"] or "—"}')
    return 0


КОМАНДЫ = {"вход": вход, "свести": свести}

if __name__ == "__main__":
    if len(sys.argv) < 3 or sys.argv[1] not in КОМАНДЫ:
        sys.exit("python3 _скрипты/о_уровень.py вход|свести материалы/<папка>")
    sys.exit(КОМАНДЫ[sys.argv[1]](sys.argv[2]) or 0)
