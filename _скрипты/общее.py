# -*- coding: utf-8 -*-
"""
Общие правила для всех шагов-скриптов.

## Код возврата отражает РАБОТУ, а не отчёт

Шаг сначала делает дело и записывает файл, потом печатает, что получилось.
Печать — не работа. Если она упадёт, файл всё равно записан, и следующий шаг
может идти дальше.

Так было не всегда. 16 сентября `b5_карта.py` падал на `f'S_база {S:+d}'`, когда
организации в справочнике ещё нет и S равна None. Карта к этому моменту была
записана целиком, но наружу уходила единица, и прогон останавливался. Тот же
случай: печать `карта["источник"]["тип"]` на поле, которого больше
нет в контракте. Дважды одна и та же форма: отчёт роняет шаг, который отработал.

`отчёт()` эту форму закрывает: всё, что печатается после записи файла, идёт
через него, и упавшая печать становится строкой предупреждения, а не отказом.

## Оркестратор не выдумывает причину

Почему шаг не прошёл, знает шаг. `прогон.py` печатает то, что сказал скрипт, и
код возврата — и ничего не добавляет от себя. Раньше он держал три заготовленные
причины: код от `b4` читался как «есть недословные цитаты», от `b5_карта` — как
«П2 цитирует не агрегат», от `o4` — как «О2/О3 цитируют не карту». Скрипт мог
упасть по любой причине, а сообщение выдавалось одно и то же — и именно это
случилось: три материала без строки справочника получили диагноз про цитаты.

## Код возврата — один контракт на все скрипты

    0 — шаг прошёл, выход записан;
    1 — шаг упал: файл, шаг и причина напечатаны;
    2 — шаг остановился и ждёт вызова модели (только оркестратор);
    4 — нарушение контракта модельного выхода (см. `контракты.стоп`).

Каждый скрипт с `__main__` завершается `raise SystemExit(main(...))`: код,
который `main` вернул, и есть код процесса. До 17 сентября у пятнадцати
скриптов `main` вызывался без `SystemExit`, и возвращённая четвёрка уходила
наружу нулём — `o1_баллы` отказывался, а прогон шёл дальше и падал
трассировкой на следующем шаге. `main`, который ничего не
возвращает, даёт ноль — это законно только если шаг не умеет отказываться.

## Корень проекта — от расположения скрипта, не от текущей директории

Четыре сторожа держали `"материалы"` по умолчанию и разрешали его от cwd:
запущенные не из корня, они находили ноль папок и рапортовали «всё чисто». Теперь корень материалов выводится от `__file__`, а
относительный аргумент разрешается сначала от корня проекта и только потом
от cwd. Сторож, которому нечего проверять, — это отказ, а не зелёный свет.
"""
import os as _os

ОК, ОТКАЗ, ЖДЁТ_МОДЕЛЬ, КОНТРАКТ = 0, 1, 2, 4

ЗДЕСЬ = _os.path.dirname(_os.path.abspath(__file__))
КОРЕНЬ = _os.path.dirname(ЗДЕСЬ)                  # пайплайн_отбора/
ВЫШЕ = _os.path.dirname(КОРЕНЬ)                   # pipeline_src_v2/
МАТЕРИАЛЫ = "материалы"
# Разделитель в параллельных списках И1 (`author_name`, `author_credential`).
# Не запятая: регалия сама содержит запятые («Department of …, Dongguk
# University»), и первый же прогон на чужой модели разошёлся списками. Одно
# место для кода и промта И1.
РАЗДЕЛИТЕЛЬ_АВТОРОВ = ";"


def список_авторов(значение):
    """Параллельный список И1 → список строк без пустых."""
    return [ч.strip() for ч in str(значение or "").split(РАЗДЕЛИТЕЛЬ_АВТОРОВ) if ч.strip()]


def корень_материалов(аргумент=None, кто="скрипт"):
    """Абсолютный путь к корню папок материалов.

    Без аргумента — `<проект>/материалы`. Относительный аргумент разрешается
    от корня проекта, затем от cwd; абсолютный берётся как есть. Если папки
    нет ни там, ни там — `SystemExit(1)` с перечислением того, где искали:
    молчаливый «папок: 0» здесь запрещён."""
    if аргумент is None:
        кандидаты = [_os.path.join(КОРЕНЬ, МАТЕРИАЛЫ)]
    elif _os.path.isabs(аргумент):
        кандидаты = [аргумент]
    else:
        кандидаты = [_os.path.join(КОРЕНЬ, аргумент), _os.path.abspath(аргумент)]
    for п in кандидаты:
        if _os.path.isdir(п):
            return _os.path.normpath(п)
    raise SystemExit(f"{кто}: корень материалов не найден; искал:\n  "
                     + "\n  ".join(кандидаты))



# Корпус исходников — один, объявлен здесь. До 17 сентября скрипты держали четыре
# мнения о том, где он лежит, и ни один не смотрел в оба места.
# Исходники лежат внутри проекта; `<проект>/../ИСХОДНИКИ` остался запасным —
# так корпус находят копии со старой раскладкой.
КОРПУС = (_os.environ.get("КОРПУС_ИСХОДНИКОВ")
          or next((п for п in (_os.path.join(КОРЕНЬ, "ИСХОДНИКИ"),
                               _os.path.join(ВЫШЕ, "ИСХОДНИКИ"))
                   if _os.path.isdir(п)), _os.path.join(КОРЕНЬ, "ИСХОДНИКИ")))


def корень_корпуса(кто="скрипт"):
    if not _os.path.isdir(КОРПУС):
        raise SystemExit(f"{кто}: корпуса исходников нет: {КОРПУС} "
                         f"(задаётся переменной КОРПУС_ИСХОДНИКОВ, по умолчанию "
                         f"<проект>/ИСХОДНИКИ, затем <проект>/../ИСХОДНИКИ)")
    return КОРПУС


def путь_исходника(аргумент, кто="скрипт"):
    """Абсолютный путь к оригиналу. Относительный аргумент разрешается от корпуса,
    от корня pipeline_src_v2, от корня проекта и от cwd — в этом порядке; если
    файла нет нигде, SystemExit с перечнем. Раньше `прогон.py` создавал папку
    материала и шёл дальше, не проверив, что исходник существует."""
    if _os.path.isabs(аргумент):
        кандидаты = [аргумент]
    else:
        кандидаты = [_os.path.join(КОРПУС, аргумент), _os.path.join(ВЫШЕ, аргумент),
                     _os.path.join(КОРЕНЬ, аргумент), _os.path.abspath(аргумент)]
    for п in кандидаты:
        if _os.path.isfile(п):
            return _os.path.normpath(п)
    raise SystemExit(f"{кто}: исходник не найден; искал:\n  " + "\n  ".join(кандидаты))


def в_корпусе(путь):
    """Путь оригинала относительно корпуса — то, что хранится в данных: разрешимо
    от объявленного корня и не привязано к машине. Файл вне корпуса — путь
    как есть, с пометкой в первом сегменте."""
    п = _os.path.normpath(_os.path.abspath(путь))
    к = _os.path.normpath(КОРПУС)
    if п.startswith(к + _os.sep):
        return _os.path.relpath(п, к)
    return п


def канал(путь):
    """Канал материала — папка верхнего уровня корпуса, в которой лежит оригинал
    (`ЧД`, `ПОИСК`, …). Файл в корне корпуса канала не имеет; файл вне корпуса — тоже."""
    отн = в_корпусе(путь)
    if _os.path.isabs(отн):
        return None
    части = отн.split(_os.sep)
    return части[0] if len(части) > 1 else None


def папки_материалов(корень, кто="скрипт"):
    """Папки материалов внутри корня, отсортированные. Ноль папок — отказ:
    сторож, не нашедший работы, не имеет права отчитаться зелёным."""
    папки = sorted(_os.path.join(корень, d) for d in _os.listdir(корень)
                   if _os.path.isdir(_os.path.join(корень, d)) and not d.startswith("."))
    if not папки:
        raise SystemExit(f"{кто}: в {корень} нет ни одной папки материала — "
                         f"проверять нечего, это не «всё чисто»")
    return папки


def библиотека(модуль, кто="скрипт"):
    """Внешняя библиотека с внятным отказом вместо трассировки — см. `окружение.py`."""
    import importlib.util as _iu
    сп = _iu.spec_from_file_location("окружение", _os.path.join(ЗДЕСЬ, "окружение.py"))
    м = _iu.module_from_spec(сп); сп.loader.exec_module(м)
    return м.требовать(модуль, кто)


def _модуль(имя):
    import importlib.util as _iu
    сп = _iu.spec_from_file_location(имя, _os.path.join(ЗДЕСЬ, имя + ".py"))
    м = _iu.module_from_spec(сп); сп.loader.exec_module(м)
    return м


def входы_шага(папка, чем, кто=None):
    """Первая строка `main` любого скриптового шага: входы по объявлению
    `шаги.py` на месте и читаются, иначе отказ с именами (`входы.требовать_шага`)."""
    return _модуль("входы").требовать_шага(папка, чем, кто)


def отчёт(печать, *аргументы, **именованные):
    """Печать после того, как работа сделана. Упала — предупреждаем и живём."""
    try:
        печать(*аргументы, **именованные)
    except Exception as сбой:
        print(f"  (отчёт не напечатался: {type(сбой).__name__}: {сбой}. "
              f"На результат шага это не влияет — файл записан.)")


def знак(значение, пусто="—"):
    """Число со знаком для печати. None — не ноль и не минус: это «не ставится»."""
    return пусто if значение is None else f"{значение:+d}"


class блокировка:
    """Запись в общий файл (канон) под замком: два прогона, дописывающие
    справочник одновременно, перетирали бы строки друг друга.
    Замок — файл `<путь>.lock` рядом с таблицей; занят дольше минуты — отказ
    с именем файла, а не вечное ожидание."""

    def __init__(self, путь, ждать_секунд=60):
        self.замок = путь + ".lock"
        self.ждать = ждать_секунд

    def __enter__(self):
        import time
        начало = time.time()
        while True:
            try:
                self.fd = _os.open(self.замок, _os.O_CREAT | _os.O_EXCL | _os.O_WRONLY)
                _os.write(self.fd, str(_os.getpid()).encode())
                return self
            except FileExistsError:
                if time.time() - начало > self.ждать:
                    raise SystemExit(f"{self.замок}: справочник занят другим прогоном дольше "
                                     f"{self.ждать} с — если прогона нет, удалите файл замка")
                time.sleep(0.2)

    def __exit__(self, *_):
        _os.close(self.fd)
        try:
            _os.remove(self.замок)
        except FileNotFoundError:
            pass
        return False


def сохранить_книгу(кн, путь: str) -> None:
    """Сохранение книги openpyxl подменой файла целиком. Читатели справочника
    замок не берут, и `кн.save(путь)` поверх живого файла давал им недописанный
    zip («File is not a zip file»); после `os.replace` они видят старую книгу
    или новую, но не половину."""
    временный = f"{путь}.{_os.getpid()}.tmp"
    кн.save(временный)
    _os.replace(временный, путь)


# --- Объём по отрезкам --------------------------------------------
# Блок агрегата знает свои отрезки (`отрезки_ид`), агрегат — длину каждого
# отрезка (`отрезки`: id → содержательных знаков). Объём набора блоков — сумма
# длин УНИКАЛЬНЫХ отрезков: два блока на одном отрезке не считаются дважды.
# Одна функция на b5_карта, o1_баллы и реестр — чтобы «доля документа» у
# сюжета, темы и заготовки считалась одинаково.

def отрезки_блоков(агрегат, ид_блоков):
    """Множество id отрезков, занятых блоками из `ид_блоков`."""
    свои = set(ид_блоков)
    return {а for б in агрегат["блоки"] if б["id"] in свои for а in б.get("отрезки_ид", ())}


def объём_блоков(агрегат, ид_блоков):
    """Содержательных знаков в отрезках блоков, без двойного счёта."""
    длины = агрегат.get("отрезки") or {}
    return sum(длины.get(а, 0) for а in отрезки_блоков(агрегат, ид_блоков))
