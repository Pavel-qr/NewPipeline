# -*- coding: utf-8 -*-
"""Точечная правка адресов П1т: адрес блока берётся из позиции его цитаты.

  python3 _скрипты/п1т_правка_адресов.py материалы/<папка>

Б4т ловит два отказа, где виновата разметка ответа, а не текст блока:

  · «адрес [a, b] не внутри фрагментов темы» — модель противоречит своей же
    карте темы;
  · «цитата начинается вне отрезков a–b» — цитата дословна, но адрес указан
    не на неё.

Оба чинятся без модели. Твёрдое свидетельство здесь — цитата: её дословность
Б4т проверяет отдельно, и раз она найдена в эталоне, её позиция и есть
настоящий адрес блока. Переспрашивать модель бессмысленно — на прогоне
21.09.2026 шесть перевызовов П1т подряд дали одну и ту же ошибку адресации.

Фрагменты темы правятся только когда вычисленный адрес не попал ни в один из
них: тогда к фрагментам добавляется ровно диапазон блока. Это не новое
суждение — модель сама отнесла этот блок к этой теме и подтвердила цитатой.
"""
import json, os, sys, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))


def _модуль(имя, файл):
    сп = importlib.util.spec_from_file_location(имя, os.path.join(ЗДЕСЬ, файл))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


_b4 = _модуль("b4", "b4_проверка_выжимок.py")
_b4т = _модуль("b4т", "b4т_проверка_тем.py")

ПРИЗНАКИ = ("не внутри фрагментов темы", "начинается вне отрезков")


def конец_цитаты(цитата, текст_норм, карта):
    """Сырой индекс ПОСЛЕДНЕГО знака цитаты: идём по кускам, как `найдена`.

    Именно последнего, а не следующего за ним: цитата, кончающаяся ровно на
    границе отрезка, иначе засчиталась бы в следующий и раздула адрес."""
    куски = _b4.куски_цитаты(цитата)
    поз, конец = 0, None
    for к in куски:
        i = _b4.позиция(к, текст_норм, поз)
        if i < 0:
            return None
        конец = i + len(к)
        поз = i + 1
    if конец is None:
        return None
    return карта[min(конец, len(карта)) - 1]


def номер_отрезка(сырой_индекс, отрезки):
    """Номер отрезка чанка, в который попал сырой индекс (1…len)."""
    for о in отрезки:
        if о["начало"] <= сырой_индекс < о["конец"]:
            return о["n"]
    if сырой_индекс < отрезки[0]["начало"]:
        return отрезки[0]["n"]
    return отрезки[-1]["n"]


def main(папка):
    import bisect
    проверка_п = os.path.join(папка, "03_проверка_тем.json")
    темы_п = os.path.join(папка, "03_темы.jsonl")
    чанки_п = os.path.join(папка, "02_чанки.jsonl")
    if not all(os.path.isfile(п) for п in (темы_п, чанки_п)):
        print("п1т_правка_адресов: нет тем или чанков")
        return 1
    if not os.path.isfile(проверка_п):
        print("п1т_правка_адресов: отчёт Б4т снят после отказа — пересчитываю проверку")
        _b4т.main(папка)
        if not os.path.isfile(проверка_п):
            print("п1т_правка_адресов: проверка так и не записалась")
            return 1

    брак = json.load(open(проверка_п, encoding="utf-8")).get("брак") or []
    адресный = [б for б in брак
                if б.get("чанк") and any(п in (б.get("что") or "") for п in ПРИЗНАКИ)]
    if not адресный:
        print("п1т_правка_адресов: в проверке нет бракованных адресов")
        return 1

    сырой = open(os.path.join(папка, "00_текст.txt"), encoding="utf-8").read()
    текст_норм, карта = _b4.норм_с_картой(сырой)
    из_сырого = lambda i: bisect.bisect_left(карта, i)
    чанки = {c["id"]: c for c in
             (json.loads(л) for л in open(чанки_п, encoding="utf-8") if л.strip())}
    темы = [json.loads(л) for л in open(темы_п, encoding="utf-8") if л.strip()]

    # Какие (чанк, тема) чинить — из брака; номер блока в тексте отказа не
    # назван, поэтому пересчитываем все блоки такой темы: адрес, взятый из
    # своей же цитаты, верному блоку ничего не меняет.
    чинить = {(б["чанк"], б.get("тема")) for б in адресный}
    правок = фрагментов = 0
    for р in темы:
        c = чанки.get(р.get("чанк_id"))
        if c is None or not c.get("отрезки"):
            continue
        верх = len(c["отрезки"])
        for т in р.get("темы") or []:
            if (р["чанк_id"], т.get("id")) not in чинить:
                continue
            фрагменты = [ф for ф in (т.get("фрагменты") or [])
                         if isinstance(ф, list) and len(ф) == 2]
            for б in т.get("блоки") or []:
                ц = б.get("цитата")
                if not ц or not _b4.найдена(ц, текст_норм):
                    continue          # недословную цитату чинит п1т_правка_цитат
                н = _b4т.начало_цитаты(ц, текст_норм, карта, c, из_сырого)
                к = конец_цитаты(ц, текст_норм, карта)
                if н is None:
                    continue
                от = номер_отрезка(н, c["отрезки"])
                до = номер_отрезка(к if к is not None else н, c["отрезки"])
                адрес = [min(от, до), max(от, до)]
                адрес = [max(1, адрес[0]), min(верх, адрес[1])]
                if б.get("отрезки") != адрес:
                    б["отрезки"] = адрес
                    правок += 1
                if not any(ф[0] <= адрес[0] and адрес[1] <= ф[1] for ф in фрагменты):
                    фрагменты.append(адрес)
                    фрагментов += 1
            т["фрагменты"] = sorted(фрагменты)

    if not правок and not фрагментов:
        print("п1т_правка_адресов: адреса уже совпадают с цитатами — менять нечего")
        return 1
    with open(темы_п, "w", encoding="utf-8") as f:
        for т in темы:
            f.write(json.dumps(т, ensure_ascii=False) + "\n")
    print(f"п1т_правка_адресов: адресов поправлено {правок}, "
          f"фрагментов добавлено {фрагментов}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("python3 _скрипты/п1т_правка_адресов.py материалы/<папка>")
    raise SystemExit(main(sys.argv[1]))
