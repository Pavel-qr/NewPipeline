# -*- coding: utf-8 -*-
"""
Пересчёт скриптовой части по всем материалам — с честным «было — стало».

  python3 _скрипты/пересчёт.py            — прогнать и показать разницу
  python3 _скрипты/пересчёт.py --проверка — ничего не менять, только сказать,
                                            совпадёт ли результат с тем, что лежит
  python3 _скрипты/пересчёт.py --от b4_проверка_выжимок.py
                                          — начать цепочку с шага (Б2/Б3 не трогать:
                                            ответы Б4 привязаны к лежащим чанкам)

Зачем этот скрипт есть. 16 сентября я четыре раза отчитался «регрессия чистая,
ни одна строка не изменилась». Все четыре раза на одной папке `o4_скоринг.py`
возвращал 1 и файл не переписывал — сравнивался старый `13_итог.json` сам с собой.
Код возврата не проверялся, и молчаливый отказ выглядел ровно как совпадение.

Правилом в документе это не чинится: правило читает человек, а ошибается он там же,
где спешит. Поэтому проверка вынесена в скрипт, который не умеет соврать:

  1. Код возврата КАЖДОГО шага проверяется. Ненулевой — это провал проверки,
     а не «без изменений». Итоговая строка в таком случае говорит «ПРОВЕРКА НЕ
     ПРОШЛА», и код возврата самого пересчёта тоже ненулевой.
  2. «Было» снимается ДО запуска, «стало» — после, и сравниваются они по значениям,
     а не по времени файла.
  3. Папка, где шаг упал, показывается отдельно от папок, где ничего не изменилось.
     Их нельзя сложить в одно число.

Модель здесь не вызывается ни разу: пересчитывается только то, что считают скрипты.
Если изменился промт, а не код, этот скрипт разницы не покажет — он и не должен.

Цепочка — вся скриптовая часть от Б2 до сведения уровней, а снимок — все поля
`13_итог.json`, `реестр.json` и `отбор.md`. До 17 сентября цепочка начиналась с
карты, а снимок держал восемь полей: правка в `b1`–`b5_агрегат` или в
обосновании была регрессии не видна, и `реестр.py` в конце цепочки стирал
уровни У1, о чём снимок молчал. Б1 в цепочку не входит:
ему нужен оригинал, а не папка.
"""
import os, sys, json, subprocess, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))


def _модуль(имя, файл):
    сп = importlib.util.spec_from_file_location(имя, os.path.join(ЗДЕСЬ, файл))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м





def _цепочка():
    """Скриптовые шаги из объявления `шаги.py`, в его порядке, без тех, что
    читают оригинал (Б1, И1 вход) и без пишущих в канон (И2/И3 записать):
    регрессия считает папку, а не корпус и не справочники. Условие запуска —
    обязательные входы шага на месте; У1 могло не быть вовсе."""
    ш = _модуль("шаги", "шаги.py")
    цепочка = []
    for с in ш.скриптовые():
        if ш.ИСХОДНИК in с["входы"] or с["канон_пишет"]:
            continue
        обязательные = [в for в in ш.файлы_входа(с) if в not in с["необязательные"]]
        цепочка.append((с["чем"], обязательные))
    return цепочка


ЦЕПОЧКА = _цепочка()

СНИМОК = ("13_итог.json", "реестр.json", "отбор.md")

# Ответы Б4 (`03_выжимки.jsonl`) привязаны к чанкам по id и написаны по тексту
# конкретного чанка. Если Б2/Б3 после правки режут текст иначе, старые ответы
# относятся к другим кускам, и всё, что считается дальше, считается по чужим
# границам — молча. Поэтому чанкинг сравнивается ДО того, как цепочка пойдёт
# дальше: изменился — папке нужен перепрогон Б4, а не «регрессия».
ПОСЛЕ_ЧАНКИНГА = "b3_чанкинг.py"
ПИШУТ_ДО_ЧАНКИНГА = ("01_структура.json", "02_чанки.jsonl")   # что Б2/Б3 перезаписывают


def отпечаток_чанков(папка):
    п = os.path.join(папка, "02_чанки.jsonl")
    if not os.path.exists(п):
        return None
    return [(ч.get("id"), ч.get("начало"), ч.get("конец"), len(ч.get("текст") or ""))
            for ч in (json.loads(с) for с in open(п, encoding="utf-8") if с.strip())]


def снимок(папка):
    """Что мы считаем результатом папки: итог, реестр и отбор целиком, по
    значениям. None у файла — «файла не было»; строка — «не читается»."""
    с = {}
    for имя in СНИМОК:
        п = os.path.join(папка, имя)
        if not os.path.exists(п):
            с[имя] = None
        elif имя.endswith(".json"):
            try:
                с[имя] = json.load(open(п, encoding="utf-8"))
            except json.JSONDecodeError:
                с[имя] = "битый JSON"
        else:
            с[имя] = open(п, encoding="utf-8").read()
    return с


def _пути_различий(а, б, путь, из, предел=40):
    if len(из) >= предел:
        return
    if isinstance(а, dict) and isinstance(б, dict):
        for к in dict.fromkeys(list(а) + list(б)):
            if к not in а:
                из.append((f"{путь}.{к}", "∅", _коротко(б[к])))
            elif к not in б:
                из.append((f"{путь}.{к}", _коротко(а[к]), "∅"))
            else:
                _пути_различий(а[к], б[к], f"{путь}.{к}", из, предел)
    elif isinstance(а, list) and isinstance(б, list):
        if len(а) != len(б):
            из.append((f"{путь}: длина", len(а), len(б)))
        for i, (x, y) in enumerate(zip(а, б)):
            _пути_различий(x, y, f"{путь}[{i}]", из, предел)
    elif а != б:
        из.append((путь, _коротко(а), _коротко(б)))


def _коротко(v):
    s = json.dumps(v, ensure_ascii=False) if not isinstance(v, str) else v
    s = s.replace("\n", " ")
    return s if len(s) <= 60 else s[:57] + "…"


def разница(было, стало):
    """Список различий (путь, было, стало) по всем файлам снимка."""
    из = []
    for имя in СНИМОК:
        а, б = было.get(имя), стало.get(имя)
        if а is None or б is None or isinstance(а, str) or isinstance(б, str):
            if а != б:
                из.append((имя, "нет файла" if а is None else _коротко(а),
                           "нет файла" if б is None else _коротко(б)))
            continue
        _пути_различий(а, б, имя, из)
    return из


def main(корень=None, только_проверка=False, от=None):
    # Корень — от расположения скрипта (`общее.корень_материалов`), ноль папок —
    # отказ: раньше из чужой директории скрипт не запускал ни одного подпроцесса
    # и печатал «проверка прошла».
    о = _модуль("общее", "общее.py")
    корень = о.корень_материалов(корень, "пересчёт")
    папки = [d for d in о.папки_материалов(корень, "пересчёт")
             if os.path.exists(os.path.join(d, "13_итог.json"))]
    if not папки:
        print(f"пересчёт: в {корень} нет ни одной папки с 13_итог.json — "
              f"регрессию не на чем проверять")
        return 1
    if только_проверка:
        import shutil, tempfile
    упали, изменились, совпали, перечанкованы = [], [], 0, []

    for папка in папки:
        было = снимок(папка)
        рабочая = папка
        врем = None
        if только_проверка:
            # Считаем в копии: режим проверки ничего не трогает на месте.
            врем = tempfile.mkdtemp(prefix="пересчёт_")
            рабочая = os.path.join(врем, os.path.basename(папка))
            shutil.copytree(папка, рабочая)

        провал = None
        чанки_были = отпечаток_чанков(рабочая)
        # Б2/Б3 пишут на месте. Если чанкинг разойдётся, папку нельзя оставить
        # с новыми чанками и старыми выжимками — вернуть как было.
        было_на_диске = {}
        for имя in ПИШУТ_ДО_ЧАНКИНГА:
            п = os.path.join(рабочая, имя)
            if os.path.exists(п):
                было_на_диске[имя] = open(п, "rb").read()
        перечанкована = False
        начали = от is None
        for скрипт, обязательные in ЦЕПОЧКА:
            начали = начали or скрипт.split()[0] == от
            if not начали:
                continue
            if any(not os.path.exists(os.path.join(рабочая, в)) for в in обязательные):
                continue        # входа нет — шаг в этой папке не выполнялся
            имя, *подкоманда = скрипт.split()
            r = subprocess.run([sys.executable, os.path.join(ЗДЕСЬ, имя), *подкоманда, рабочая],
                               capture_output=True, text=True)
            if r.returncode != 0:
                хвост = (r.stdout or r.stderr or "").strip().splitlines()
                провал = (скрипт, r.returncode, хвост[-1][:140] if хвост else "")
                break
            if скрипт == ПОСЛЕ_ЧАНКИНГА and чанки_были is not None:
                стали = отпечаток_чанков(рабочая)
                if стали != чанки_были:
                    других = sum(1 for а, б in zip(чанки_были, стали) if а != б) \
                             + abs(len(стали) - len(чанки_были))
                    перечанкованы.append((os.path.basename(папка), len(чанки_были),
                                          len(стали), других))
                    перечанкована = True
                    for имя, байты in было_на_диске.items():
                        open(os.path.join(рабочая, имя), "wb").write(байты)
                    break

        if перечанкована:
            pass
        elif провал:
            упали.append((os.path.basename(папка),) + провал)
        else:
            из = разница(было, снимок(рабочая))
            if из:
                изменились.append((os.path.basename(папка), из))
            else:
                совпали += 1
        if врем:
            shutil.rmtree(врем, ignore_errors=True)

    print(f'{"ПРОВЕРКА" if только_проверка else "ПЕРЕСЧЁТ"}: папок с итогом {len(папки)}\n')
    if упали:
        print(f"ШАГ УПАЛ — {len(упали)} папок. Про них НЕЛЬЗЯ сказать «не изменилось»:")
        for имя, скрипт, код, текст in упали:
            print(f"  ✗ {имя}: {скрипт} вернул {код}")
            if текст:
                print(f"      {текст}")
        print()
    if перечанкованы:
        print(f"ЧАНКИНГ ИЗМЕНИЛСЯ — {len(перечанкованы)} папок. Ответы Б4 в них написаны "
              f"по прежним чанкам; считать дальше по новым — значит считать по чужим границам:")
        for имя, было, стало, других in перечанкованы:
            print(f"  ✗ {имя}: чанков {было} → {стало}, с другими границами {других}. "
                  f"Нужен перепрогон Б4 (модель), регрессия скриптов тут не применима")
        print()
    if изменились:
        print(f"ИЗМЕНИЛОСЬ — {len(изменились)} папок:")
        for имя, из in изменились:
            print(f"  ≠ {имя}")
            for что, а, б in из:
                print(f"      {что}: {а} → {б}")
        print()
    print(f"совпало без изменений: {совпали} из {len(папки)}")
    if перечанкованы:
        print("\nПРОВЕРКА НЕ ПРОШЛА: чанкинг разошёлся с тем, на котором получены ответы "
              "модели. Это не регрессия скриптов, а устаревшие модельные выходы.")
        return 1
    if упали:
        print("\nПРОВЕРКА НЕ ПРОШЛА: пока хоть один шаг падает, «регрессия чистая» "
              "сказать нельзя — упавший шаг не переписывает файл, и сравнение идёт "
              "старого результата с самим собой.")
        return 1
    print("проверка прошла: все шаги отработали с нулевым кодом")
    return 0


if __name__ == "__main__":
    арг = [a for a in sys.argv[1:] if not a.startswith("--")]
    от = None
    if "--от" in sys.argv:
        от = sys.argv[sys.argv.index("--от") + 1]
        арг = [a for a in арг if a != от]
        if от not in {с.split()[0] for с, _ in ЦЕПОЧКА}:
            raise SystemExit(f"--от: шага «{от}» нет в цепочке: "
                             + ", ".join(с.split()[0] for с, _ in ЦЕПОЧКА))
    raise SystemExit(main(арг[0] if арг else None,
                          только_проверка="--проверка" in sys.argv, от=от))
