# -*- coding: utf-8 -*-
"""
Оркестратор. Исполняет объявление шагов из `шаги.py` и ничего не решает сам:
порядок, входы, выходы, условия пропуска и контракты — всё оттуда.

  python3 _скрипты/прогон.py <исходник> материалы/<папка>
  python3 _скрипты/прогон.py --без-api <исходник> материалы/<папка>
  python3 _скрипты/прогон.py --принять <файл> материалы/<папка>

Исходник разрешается от корпуса (`общее.КОРПУС`), от корня pipeline_src_v2, от
корня проекта и от cwd — `ИСХОДНИКИ/ЧД/файл.pdf` и `ЧД/файл.pdf` равно годятся.

Останавливается там, где нужен вызов модели, если нет API-ключа: печатает,
какой промт взять, какой файл ему дать и куда положить ответ. Положили —
запустили снова. Если задан `API_KEY` (или `ANTHROPIC_API_KEY`),
на месте остановки вызывается Anthropic Messages API (модель
`claude-opus-5` по умолчанию); порядок шагов и контракт файлов не меняются.
Ручной режим: `прогон.py --без-api <исходник> <папка>`.

## Что оркестратор делает с каждым шагом

1. Нужен ли шаг: `шаги.почему_пропустить` — вход отсутствует или пуст, а его
   писатель объявил выход условным либо сам был пропущен → шаг пропускается,
   его выходы считаются пропущенными дальше по цепочке. Безусловный вход
   отсутствует → сбой производителя, прогон останавливается.
2. Сделан ли шаг: выходы есть И свежи. Свежесть — по отпечаткам входов
   (`_отпечатки.json`), не по времени файла. Скриптовый выход с изменившимся
   входом пересчитывается; модельный — останавливает прогон: ответ модели стоит
   вызова, и решать, повторять ли его, — человеку (`--принять`, если ответ
   верен и для нового входа).
3. Скрипт: запускается; ненулевой код — прогон останавливается с этим кодом,
   выходы шага удаляются: полуфабрикат от упавшего шага неотличим от готового
   файла. Ноль — записываются отпечатки входов для каждого выхода.
4. Модель: если есть ключ API — запрос, запись выхода, отпечаток, дальше
   по цепочке. Иначе записывается отпечаток входов, печатаются промт/вход/выход
   и прогон выходит кодом 2.

Код возврата (`общее.py`): 0 — пройдено до конца; 2 — ждёт вызова модели;
иначе — код упавшего шага (1 — скрипт упал, вход несогласован или выход
устарел; 4 — ответ модели не по требованию промта: схема, цитаты не из входа,
ссылки на несуществующие блоки/сюжеты, неполный ответ, нарушенное правило
разметки — чинить ответ, не скрипт).
"""
import sys, os, json, subprocess, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ЗДЕСЬ)


def _модуль(имя, файл):
    сп = importlib.util.spec_from_file_location(имя, os.path.join(ЗДЕСЬ, файл))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м


_общее = _модуль("общее", "общее.py")
_шаги = _модуль("шаги", "шаги.py")
_модель = _модуль("модель", "модель.py")


def _аргументы(ш, исходник, папка):
    имя, *подкоманда = ш["чем"].split()
    хвост = {"папка": [папка],
             "исходник папка": [исходник, папка],
             "папка исходник": [папка, исходник]}[ш["аргументы"]]
    return [sys.executable, os.path.join(ЗДЕСЬ, имя)] + подкоманда + хвост


def _есть_выходы(ш, папка):
    """Все безусловные выходы на месте."""
    return all(os.path.exists(os.path.join(папка, ф))
               for ф in ш["выходы"] if ф not in ш["условные"])


def _убрать_выходы(ш, папка):
    for ф in ш["выходы"]:
        п = os.path.join(папка, ф)
        if os.path.exists(п):
            os.remove(п)


def принять(файл, папка):
    """Перепривязать существующий выход к нынешним входам его шага. Для случая,
    когда человек проверил, что ответ модели верен и для изменённого входа."""
    ш = next((ш for ш in _шаги.ШАГИ if файл in ш["выходы"]), None)
    if ш is None:
        print(f"«{файл}» не объявлен выходом ни одного шага")
        return 1
    if not os.path.exists(os.path.join(папка, файл)):
        print(f"{папка}/{файл} нет — принимать нечего")
        return 1
    _шаги.записать_отпечаток(папка, файл, _шаги.отпечатки_входов(ш, папка))
    print(f"принято: {файл} привязан к нынешним входам {', '.join(ш['входы'])}")
    return 0


def _вызов(ш, папка):
    """Один файл на остановку: промт и его вход, в том порядке, в каком их даёт
    модели человек. Собирать вход из нескольких файлов и печати на экране —
    работа, которую при ручном вызове делали каждый раз заново; служебный файл,
    как `_отпечатки.json`, переписывается на каждой остановке."""
    промт = open(os.path.join(КОРЕНЬ, "_промты", ш["чем"]), encoding="utf-8").read()
    части = [промт.rstrip(), ""]
    if ш["по_строке"]:
        части.append(f'> Вход по строке за вызов: каждая строка файла `{ш["входы"][0]}` — '
                     f'отдельный вызов модели с этим промтом'
                     + (f'; ответы — по строке в `{ш["выходы"][0]}`, в том же порядке.'
                        if ш["выходы"][0].endswith(".jsonl") else
                        f'; объекты ответов складываются в список `темы` одного объекта '
                        f'`{{"темы": [...]}}` в `{ш["выходы"][0]}`.'))
    for в in ш["входы"]:
        if в.startswith(_шаги.КАНОН):
            # Модели канон даётся не таблицей, а текстом, и вид назван в
            # объявлении шага (`канон_вид`): П1т получает определения и
            # направления, П3 — определения и исключения. Канон другой таблицы
            # модельному шагу не объявлен — это отказ, не молчание.
            имя = в[len(_шаги.КАНОН):]
            if имя != "topics_индикаторы.xlsx":
                raise SystemExit(f"прогон: как давать модели {в}, не объявлено (только канон тем)")
            _канон = _модуль("канон", "канон.py")
            части += [f"\n## Файл входа: канон тем (вид «{ш['канон_вид']}», {имя})\n",
                      _канон.в_текст(_канон.вид(ш["канон_вид"]))]
            continue
        п = _шаги.путь_входа(в, папка)
        if not (п and os.path.exists(п)):
            части += [f"\n## Файл входа: {в}\n", "(файла нет — вход условный, шаг обошёлся без него)"]
            continue
        содержимое = open(п, encoding="utf-8").read()
        части += [f"\n## Файл входа: {в}\n", "```json" if в.endswith((".json", ".jsonl")) else "```",
                  содержимое.rstrip(), "```"]
    части += ["\n## Куда положить ответ\n", f"`{os.path.join(папка, ш['выходы'][0])}`"]
    путь = os.path.join(папка, _шаги.ВЫЗОВ)
    with open(путь, "w", encoding="utf-8") as f:
        f.write("\n".join(части) + "\n")
    return путь


def main(исходник, папка, без_api=False):
    исходник = _общее.путь_исходника(исходник, "прогон")
    os.makedirs(папка, exist_ok=True)
    пропущено = set()

    for ш in _шаги.ШАГИ:
        метка = f'{ш["код"]} {ш["чем"]}'

        причина = _шаги.почему_пропустить(ш, папка, пропущено)
        if причина and причина.startswith("!"):
            print(f"■ {метка}: {причина[1:].strip()}")
            return _общее.ОТКАЗ
        if причина:
            print(f"· {метка} — {причина}")
            пропущено |= set(ш["выходы"])
            continue

        if _есть_выходы(ш, папка):
            старое = _шаги.устарел(ш, папка, исходник)
            if not старое:
                print(f"· {метка} — уже сделано")
                continue
            if ш["вид"] == _шаги.МОДЕЛЬ:
                print(f"■ {метка}: выход {ш['выходы'][0]} получен на другой вход — "
                      f"изменились: {', '.join(старое)}.\n"
                      f"  Повторите вызов модели (удалите {ш['выходы'][0]}) либо, если ответ "
                      f"верен и для нового входа: прогон.py --принять {ш['выходы'][0]} {папка}")
                return _общее.ОТКАЗ
            print(f"↻ {метка} — входы изменились ({', '.join(старое)}), пересчитываю")
            _убрать_выходы(ш, папка)

        if ш["вид"] == _шаги.СКРИПТ:
            print(f"▶ {метка}")
            код = subprocess.call(_аргументы(ш, исходник, папка))
            if код:
                # Почему шаг не прошёл, знает шаг — он это уже напечатал выше.
                # Оркестратор причину не выдумывает.
                _убрать_выходы(ш, папка)
                # Код 4 — ответ модели не по требованию промта: чинить ответ,
                # не скрипт. Файл ответа — выход другого шага, он остаётся на
                # месте, чтобы было что исправлять.
                print(f"  ■ {метка} остановился, код возврата {код}. Причина — в выводе шага выше."
                      + ("\n  код 4: ответ модели не по требованию промта — исправьте или повторите "
                         "ответ, скрипты и промты не трогать" if код == _общее.КОНТРАКТ else ""))
                return код
            отпечаток = _шаги.отпечатки_входов(ш, папка, исходник)
            for ф in ш["выходы"]:
                if os.path.exists(os.path.join(папка, ф)):
                    _шаги.записать_отпечаток(папка, ф, отпечаток)
                else:
                    пропущено.add(ф)       # условный выход не понадобился
            continue

        # Модель: API, если есть ключ; иначе остановка для ручного ответа.
        if not без_api and _модель.включен():
            print(f"▶ {метка} — API ({_модель.модель()}, effort={ш.get('effort') or 'default'})")
            try:
                _модель.выполнить_шаг(ш, папка)
            except Exception as сбой:
                print(f"  ■ {метка}: вызов API не удался: {сбой}")
                return _общее.ОТКАЗ
            _шаги.записать_отпечаток(
                папка, ш["выходы"][0], _шаги.отпечатки_входов(ш, папка, исходник))
            continue

        _шаги.записать_отпечаток(папка, ш["выходы"][0], _шаги.отпечатки_входов(ш, папка, исходник))
        вызов = _вызов(ш, папка)
        print(f"\n■ {ш['код']}: нужен вызов модели")
        print(f"  промт:  _промты/{ш['чем']}")
        print(f"  вход:   {', '.join(ш['входы'])}" + (" (по строке за вызов)" if ш["по_строке"] else ""))
        print(f"  выход:  {os.path.join(папка, ш['выходы'][0])}")
        print(f"  всё вместе, для копирования: {вызов}")
        print("  положите файл и запустите прогон снова\n")
        return _общее.ЖДЁТ_МОДЕЛЬ

    print("\n✓ пройдено до конца:", os.path.join(папка, "отбор.md"),
          "и", os.path.join(папка, "реестр.json"))
    м = os.path.join(папка, "выгружено.json")
    if os.path.exists(м):
        в = json.load(open(м, encoding="utf-8"))
        print("  выгрузка для аналитика:", в["куда"] if в.get("выгружено") else в.get("почему"))
    return _общее.ОК


if __name__ == "__main__":
    арг = sys.argv[1:]
    без_api = False
    if арг and арг[0] == "--без-api":
        без_api = True
        арг = арг[1:]
    if len(арг) == 3 and арг[0] == "--принять":
        raise SystemExit(принять(арг[1], арг[2]))
    if len(арг) != 2:
        raise SystemExit(
            "python3 _скрипты/прогон.py <исходник> материалы/<папка>\n"
            "python3 _скрипты/прогон.py --без-api <исходник> материалы/<папка>\n"
            "python3 _скрипты/прогон.py --принять <файл> материалы/<папка>")
    raise SystemExit(main(арг[0], арг[1], без_api=без_api))
