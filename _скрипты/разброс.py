# -*- coding: utf-8 -*-
"""
Повторяемость модельного шага: насколько ответ совпадает сам с собой на одном входе.

  python3 _скрипты/разброс.py замер_разброса/19_okr      # П2, решение о документе
  python3 _скрипты/разброс.py П2т замер_сюжетов/19_okr   # П2т, сюжеты одной темы
  python3 _скрипты/разброс.py У1 замер_уровней           # У1, уровни заготовки

Шаг называется первым аргументом; без него — П2. Инструмент один на все шаги
намеренно: замер повторяемости — это не свойство одного шага, а обязанность перед
любым модельным шагом, и второй скрипт с тем же смыслом разошёлся бы с первым
через месяц.

П2: в папке несколько файлов `прогон_*.json` — ответы П2 (`04_решение.json`),
полученные независимыми вызовами на ОДНОМ и том же `04_агрегат_вход.json`.
П2т: файлы `прогон_*.json` — ответы П2т по ОДНОЙ строке `10_сюжеты_вход.jsonl`
(одна тема), и рядом `04_агрегат.json`, чтобы знать полный список блоков темы.

Что меряется и почему именно так.

**Простые поля** П2 — жанр, адресат, зависимость от продукта, выходные данные.
Тут ответ либо совпал во всех прогонах, либо нет; полутонов не бывает. Жанр стоит
первым не случайно: он закрывает все темы разом, и его нестабильность стоит дороже
любой другой.

**Сюжеты** П2т нельзя сравнивать по названиям: один и тот же смысловой кусок модель
назовёт по-разному, и побуквенное сравнение покажет ноль совпадений там, где разбор
на самом деле один и тот же. Поэтому сравнивается не состав названий, а **разбиение
блоков**: для каждой пары блоков спрашивается «в одном ли они сюжете» — и ответы
разных прогонов сверяются между собой. Это стандартная мера согласия для разбиений
(индекс Рэнда). Она не зависит от того, как сюжеты названы и в каком порядке идут.

Две цифры про сюжеты значат разное:
  · **согласие по парам** — одинаково ли модель группирует содержание;
  · **число сюжетов** — одинаково ли она режет группы на части.
Первое может быть высоким при разном втором: границы между соседними сюжетами
плывут, а сами группы держатся. Это ровно тот случай, когда чинить надо не модель,
а формулировку задачи.

Скрипт ничего не пишет, кроме stdout.
"""
import sys, os, json, glob, itertools, importlib.util

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
НЕТ = object()     # поля нет в ответе: это не None, и это не «совпало»


def _контракт_П2():
    сп = importlib.util.spec_from_file_location("контракты", os.path.join(ЗДЕСЬ, "контракты.py"))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м.КОНТРАКТЫ["П2"]


def _по_пути(р, путь):
    тек = р
    for к in путь.split("."):
        if not isinstance(тек, dict) or к not in тек:
            return НЕТ
        тек = тек[к]
    return тек


def поля_П2():
    """Простые поля замера — из контракта П2, не литералами. До 17 сентября
    четыре поля читались из блока `источник`, которого П2 давно не отдаёт, и
    четыре строки «= None | None | None» шли в «устойчивые».
    Закрытые списки контракта (`пути`) — первыми: они решающие."""
    к = _контракт_П2()
    поля = [(имя, путь) for путь, имя in к.get("пути", {}).items()]
    поля += [("зависимость от продукта", "зависимость_от_продукта.есть")]
    поля += [(имя, имя) for имя, (_, тип, список) in к.get("поля", {}).items()
             if тип in (bool, int) or список]
    return поля


def взять(р, как):
    return как(р) if callable(как) else _по_пути(р, как)


def пары_в_одном_сюжете(решение, блоки):
    """Множество пар блоков, оказавшихся в одном сюжете."""
    вместе = set()
    for с in решение.get("сюжеты") or []:
        свои = sorted(set(с.get("блоки") or []) & блоки)
        вместе |= set(itertools.combinations(свои, 2))
    return вместе


def согласие(а, б, все_пары):
    """Доля пар блоков, про которые оба прогона сказали одно и то же."""
    if not все_пары:
        return None
    расхождений = len(а ^ б)
    return 1 - расхождений / len(все_пары)


def _прогоны(папка):
    файлы = sorted(glob.glob(os.path.join(папка, "прогон_*.json")))
    if len(файлы) < 2:
        raise SystemExit(f"нужно хотя бы два файла прогон_*.json в {папка}, найдено {len(файлы)}")
    return [(os.path.basename(ф), json.load(open(ф, encoding="utf-8"))) for ф in файлы]


def main(папка):
    """Повторяемость П2: простые поля решения о документе."""
    прогоны = _прогоны(папка)
    print(f"{os.path.basename(папка)}: прогонов {len(прогоны)}\n")

    ПОЛЯ = поля_П2()
    шир = max(len(и) for и, _ in ПОЛЯ) + 1
    неустойчивые, мёртвые = [], []
    for имя, как in ПОЛЯ:
        значения = [взять(р, как) for _, р in прогоны]
        if all(з is НЕТ for з in значения):
            # Поля нет ни в одном прогоне — это не устойчивость, это мёртвая
            # строка замера; в «=» она не идёт.
            метка = "∅"
            мёртвые.append(имя)
        else:
            # «не ответил» и «ответил» — разные ответы
            одно = len({repr(з) if з is not НЕТ else "∅" for з in значения}) == 1
            метка = "=" if одно else "≠"
            if not одно:
                неустойчивые.append(имя)
        показ = " | ".join("∅" if з is НЕТ else str(з) for з in значения)
        print(f"{метка} {имя:<{шир}} {показ[:96]}")
    if мёртвые:
        print(f"  ∅ полей нет ни в одном прогоне: {', '.join(мёртвые)} — в счёт устойчивых не входят")

    print("\nвывод:")
    решающие = ("жанр", "адресат", "зависимость от продукта")
    if не_устойчиво := [и for и in неустойчивые if и in решающие]:
        print(f"  ! нестабильны решающие поля: {', '.join(не_устойчиво)} — "
              f"от них зависит, дойдёт ли материал до проверки вообще")
    elif мёртво := [и for и in мёртвые if и in решающие]:
        print(f"  ! решающих полей нет в ответах: {', '.join(мёртво)} — устойчивость не измерена")
    else:
        print("  решающие поля (жанр, адресат, зависимость от продукта) устойчивы")
    return 0


def сюжеты(папка):
    """Повторяемость П2т: разбиение блоков одной темы на сюжеты."""
    прогоны = _прогоны(папка)
    темы = {р.get("тема") for _, р in прогоны}
    if len(темы) != 1:
        raise SystemExit(f"ответы П2т должны быть по одной теме, а тут: {', '.join(map(str, темы))}")
    тема = темы.pop()

    агрегат = os.path.join(папка, "04_агрегат.json")
    блоки = set()
    if os.path.exists(агрегат):
        а = json.load(open(агрегат, encoding="utf-8"))
        блоки = {и for т in а["темы"] if т["id"] == тема for и in т["блоки"]}
    else:
        for _, р in прогоны:
            for с in р.get("сюжеты") or []:
                блоки |= set(с.get("блоки") or [])

    print(f"{os.path.basename(папка)}: тема {тема}, прогонов {len(прогоны)}, блоков темы {len(блоки)}\n")
    числа = [len(р.get("сюжеты") or []) for _, р in прогоны]
    print(f'{"=" if len(set(числа)) == 1 else "≠"} сюжетов  {" | ".join(map(str, числа))}')

    все_пары = set(itertools.combinations(sorted(блоки), 2))
    множества = [пары_в_одном_сюжете(р, блоки) for _, р in прогоны]
    покрытие = [len({i for с in (р.get("сюжеты") or []) for i in с.get("блоки") or []} & блоки)
                for _, р in прогоны]

    print(f"\nпокрытие блоков сюжетами: {' | '.join(f'{п}/{len(блоки)}' for п in покрытие)}")
    print("\nсогласие по парам блоков (в одном ли они сюжете):")
    доли = []
    for (i, (иа, _)), (j, (иб, _)) in itertools.combinations(list(enumerate(прогоны)), 2):
        д = согласие(множества[i], множества[j], все_пары)
        доли.append(д)
        print(f"  {иа} ↔ {иб}: {д:.1%}")
    if доли:
        print(f"  среднее: {sum(доли)/len(доли):.1%}, худшая пара: {min(доли):.1%}")

    print("\nвывод:")
    if len(set(числа)) > 1:
        print("  ! число сюжетов плавает — на сюжетах стоит реестр заготовок")
    if доли and min(доли) < 0.9:
        print("  ! группировка блоков расходится сильнее, чем на 10%")
    return 0


def уровни(папка):
    """Повторяемость У1: совпадают ли закрытые уровни заготовки от прогона к прогону.

    Ждёт в папке подпапки `прогон_1`, `прогон_2`, … с ответами У1 по файлу на
    заготовку и одинаковыми именами файлов во всех прогонах.

    Что меряется и почему именно так. Ответ У1 — не одно число, а четыре
    независимых да/нет: есть ли в заготовке текст под ячейку канона. Значит и
    единица замера — **ячейка «заготовка × уровень»**, а не заготовка целиком.
    Две цифры говорят разное:

      · **согласие по ячейкам** — одинаково ли шаг видит наличие материала;
      · **полное совпадение набора** — сходится ли ответ по заготовке целиком.

    Второе всегда хуже первого и падает быстрее: четыре независимых решения
    ошибаются независимо, и одной разошедшейся ячейки хватает, чтобы набор
    разъехался. Судить о шаге надо по первому, планировать работу — по второму.

    Отдельно считается, совпал ли **подтверждающий текст** у ячеек, которые все
    прогоны признали закрытыми: уровень можно закрыть, опираясь на разные куски
    материала, и это уже разница в разборе, а не в ответе.
    """
    прогоны = sorted(д for д in glob.glob(os.path.join(папка, "прогон_*"))
                     if os.path.isdir(д))
    if len(прогоны) < 2:
        raise SystemExit(f"нужно хотя бы две подпапки прогон_* в {папка}, найдено {len(прогоны)}")

    разборы = {}          # имя прогона → {заготовка: {уровень: (закрыт, цитата)}}
    for д in прогоны:
        свои = {}
        for ф in sorted(glob.glob(os.path.join(д, "*.json"))):
            о = json.load(open(ф, encoding="utf-8"))
            свои[os.path.basename(ф)[:-5]] = {
                int(у["уровень"]): (bool(у.get("закрыт")), у.get("цитата"))
                for у in о.get("уровни") or []}
        разборы[os.path.basename(д)] = свои

    общие = sorted(set.intersection(*(set(с) for с in разборы.values())))
    пропуски = {и: sorted(set(с) - set(общие)) for и, с in разборы.items() if set(с) - set(общие)}
    print(f"{os.path.basename(папка)}: прогонов {len(прогоны)}, заготовок {len(общие)}\n")
    for и, лишние in пропуски.items():
        print(f"  ! {и}: заготовки есть не во всех прогонах — {', '.join(лишние)}")

    УРОВНИ = (1, 2, 3, 4)
    шир = max(len(з) for з in общие) + 1
    полных = 0
    расхождения_по_уровням = {у: 0 for у in УРОВНИ}
    ячеек = совпавших = 0
    без_ответа = 0
    for з in общие:
        # Уровень, про который прогон не ответил, — не «не закрыт», а «нет
        # ответа»: в наборе он показан как «?» и с любым ответом
        # другого прогона расходится.
        def ответ(и, у):
            return разборы[и][з][у][0] if у in разборы[и][з] else НЕТ
        наборы = [sorted(у for у in УРОВНИ if ответ(и, у) is True) for и in разборы]
        пропущено = [sorted(у for у in УРОВНИ if ответ(и, у) is НЕТ) for и in разборы]
        одно = (len({tuple(н) for н in наборы}) == 1
                and len({tuple(п) for п in пропущено}) == 1 and not any(пропущено))
        полных += одно
        for у in УРОВНИ:
            ответы = {ответ(и, у) for и in разборы}
            ячеек += 1
            if НЕТ in ответы:
                без_ответа += 1
            if len(ответы) == 1 and НЕТ not in ответы:
                совпавших += 1
            else:
                расхождения_по_уровням[у] += 1
        показ = [f"{н or '—'}" + (f" ?{п}" if п else "") for н, п in zip(наборы, пропущено)]
        print(f'{"=" if одно else "≠"} {з:<{шир}} ' + " | ".join(показ))
    if без_ответа:
        print(f"  ! ячеек без ответа хотя бы в одном прогоне: {без_ответа} — считаются расхождением")

    print(f"\nсогласие по ячейкам «заготовка × уровень»: "
          f"{совпавших}/{ячеек} = {совпавших/ячеек:.1%}")
    print(f"полное совпадение набора уровней: {полных}/{len(общие)} = {полных/len(общие):.1%}")
    разошлись = {у: n for у, n in расхождения_по_уровням.items() if n}
    print("расхождения по уровням: " + (", ".join(
        f"уровень {у}: {n} из {len(общие)}" for у, n in разошлись.items()) or "нет"))

    # подтверждающий текст у единогласно закрытых ячеек
    единых = тех_же = 0
    for з in общие:
        for у in УРОВНИ:
            если = [разборы[и][з].get(у, (False, None)) for и in разборы]
            if all(з_[0] for з_ in если):
                единых += 1
                тех_же += len({(ц or "").strip() for _, ц in если}) == 1
    if единых:
        print(f"подтверждающая цитата совпала: {тех_же}/{единых} единогласно закрытых ячеек "
              f"= {тех_же/единых:.1%}")

    print("\nвывод:")
    if совпавших / ячеек < 0.9:
        print("  ! шаг расходится сам с собой чаще, чем в одной ячейке из десяти")
    else:
        print("  наличие материала под уровень шаг видит устойчиво")
    if полных < len(общие):
        print(f"  набор уровней целиком совпал не у всех заготовок "
              f"({len(общие)-полных} из {len(общие)} разъехались) — "
              f"планировать по одному прогону нельзя")
    return 0


РЕЖИМЫ = {"П2": main, "П2т": сюжеты, "У1": уровни}

if __name__ == "__main__":
    арг = sys.argv[1:]
    if арг and арг[0] in РЕЖИМЫ:
        шаг, арг = арг[0], арг[1:]
    else:
        шаг = "П2"
    if not арг:
        raise SystemExit("python3 _скрипты/разброс.py [П2|П2т|У1] <папка замера>")
    # Относительный путь — от корня проекта, потом от cwd.
    _сп = importlib.util.spec_from_file_location(
        "общее", os.path.join(os.path.dirname(os.path.abspath(__file__)), "общее.py"))
    _общее = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(_общее)
    raise SystemExit(РЕЖИМЫ[шаг](_общее.корень_материалов(арг[0], "разброс")))
