# -*- coding: utf-8 -*-
"""
Реестр заготовок (скрипт, без модели).
Вход:  04_карта.json, 04_агрегат.json, 10_сюжеты_сведены.json, 13_итог.json,
       00_уровень_сведён.json (если У1 был)
Выход: реестр.json

Реестр — последний шаг: он собирается со всем, что известно, включая уровни У1.
Заготовки считает функция `заготовки(папка)`, и той же функцией их берёт
`о_уровень.py вход` — иначе У1 читал бы `реестр.json`, а реестр потом читал бы
выход У1: два писателя одного файла. Одна функция — одно правило «что такое
заготовка», один писатель у файла.

**Строка реестра = принятая тема.** Всё, что материал даёт по одному индикатору,
собирается в одну заготовку: фрагменты темы (весь текст про неё, с координатами
в тексте), её блоки, сюжеты, цитаты, опоры под практику. Это разрез уже
собранного, а не второй скоринг: ни одного нового вызова модели и ни одного
нового балла.

Тема — граница заготовки, и тема к тексту привязана на разборе (Б4т), то есть
число заготовок детерминировано: сколько принятых тем, столько строк. Сколько
единиц контента выйдет из заготовки, пайплайн не решает — это работа аналитика.
Сюжеты остаются внутри заготовки готовой разметкой.

Тема берётся из финального вердикта, а не из кандидатов: кандидат мог быть
уронен строгой проверкой или не пройти гейт B.

Приоритет — готовое S из 13_итог.json, без пересчёта: два источника правды для
одного числа рано или поздно разойдутся.
"""
import sys, os, json, importlib.util

_сп = importlib.util.spec_from_file_location(
    "входы", os.path.join(os.path.dirname(os.path.abspath(__file__)), "входы.py"))
_входы = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(_входы)
_сп = importlib.util.spec_from_file_location(
    "общее", os.path.join(os.path.dirname(os.path.abspath(__file__)), "общее.py"))
_общее = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(_общее)

ПРИОРИТЕТ = {
    2: "1 — институциональная проверка",
    1: "2 — редакционная ответственность",
    0: "3 — именной автор",
    -1: "4 — без атрибуции",
}


def заготовки(папка, кто="реестр"):
    """(основа, приоритет, [заготовка, …]) по карте, агрегату, своду сюжетов и итогу.
    Без уровней: их ставит У1 по этим же заготовкам, и вписывает `main` ниже."""
    # Нехватка входов — остановка с именем файла, а не тихий пропуск. Входы — по
    # объявлению шага «реестр.py» (У1 зовёт заготовки с теми же файлами).
    _входы.требовать_шага(папка, "реестр.py", кто)

    def читать(имя):
        п = os.path.join(папка, имя)
        return json.load(open(п, encoding="utf-8")) if os.path.exists(п) else None

    карта = читать("04_карта.json")
    агрегат = читать("04_агрегат.json")
    свод = читать("10_сюжеты_сведены.json")
    итог = читать("13_итог.json")
    роли = {с["тема"]: с.get("роль_в_материале")
            for с in (итог or {}).get("строки", []) if с.get("роль_в_материале")}

    # какие темы материал реально закрывает
    принятые = {с["тема"]: с for с in итог["строки"] if с["вердикт"] == "✅"}

    основа = {
        "материал": карта["материал"].get("заголовок_из_файла") or карта["материал"]["файл"],
        "папка": os.path.basename(os.path.normpath(папка)),
        "источник": карта["источник"],
        "жанр": карта["жанр"]["тип"],
        "принятые_темы": sorted(принятые),
        "принятых_тем": len(принятые),
        "тем_в_тексте": len(карта["темы"]),
        "сюжетов_всего": sum(len(т["сюжеты"]) for т in свод["темы"]),
    }

    if not принятые:
        return основа, None, []

    # Принятая тема без свода сюжетов — рассогласование: вердикт ✅ выставлен
    # после П4, а П4 работала по этим самым сюжетам.
    по_теме = {т["id"]: т for т in свод["темы"]}
    без_свода = sorted(set(принятые) - set(по_теме))
    if без_свода:
        raise SystemExit(f'{кто}: принятые темы {", ".join(без_свода)} отсутствуют в '
                         f'10_сюжеты_сведены.json — заготовок по ним не будет')
    for т in принятые:
        if not по_теме[т]["сюжеты"]:
            raise SystemExit(f'{кто}: принятая тема {т} без единого сюжета в своде — '
                             f'заготовки не собрать, а вердикт ✅ был выставлен')

    s = next((с["S"] for с in принятые.values() if с["S"] is not None), None)
    приоритет = ПРИОРИТЕТ.get(s, "не определён")

    # Один отрезок текста может лежать во фрагментах двух тем. Это не ошибка
    # учёта: текст действительно работает на оба индикатора. Но аналитик, взяв
    # обе заготовки, должен видеть, что перед ним один и тот же кусок текста.
    отрезки_темы = {т: {а for ф in по_теме[т]["фрагменты"] for а in ф["отрезки_ид"]} for т in принятые}
    длины = агрегат.get("отрезки") or {}
    пересечения = {}
    for тема in принятые:
        for другая in принятые:
            if другая == тема:
                continue
            общие = отрезки_темы[тема] & отрезки_темы[другая]
            if общие:
                пересечения.setdefault(тема, []).append(
                    {"тема": другая, "отрезков": len(общие),
                     "знаков": sum(длины.get(а, 0) for а in общие)})

    заготовки = []
    for тема in принятые:
        т = по_теме[тема]
        свои = т["сюжеты"]
        блоки = sorted(т["блоки"])
        заготовки.append({
            # откуда
            "материал": карта["материал"].get("заголовок_из_файла") or карта["материал"]["файл"],
            "папка": os.path.basename(os.path.normpath(папка)),
            "тема": тема,
            # Пометка из o1: главная эта тема в материале, сопоставимая с главной
            # или обслуживающая её. В балл не входит.
            "роль_в_материале": роли.get(тема),
            "часть_документа": "/".join(т["распределение"]),
            # Весь текст про тему — участки с координатами в 00_текст.txt
            # (границы отрезков, ≈1 000 знаков; точность — до отрезка).
            "фрагменты": [{"чанк": ф["чанк"], "начало": ф["отрезки_док"][0],
                           "конец": ф["отрезки_док"][1], "знаков": ф["знаков"],
                           "раздел": ф.get("раздел")} for ф in т["фрагменты"]],
            "фрагментов": len(т["фрагменты"]),
            # Что внутри: сюжеты — готовая разметка, со своими свойствами.
            "сюжеты": [{"название": с["название"],
                        "знаков": с["знаков"],
                        "доля_документа": с["доля_документа"],
                        "блоки": с["блоки"],
                        "блоков": с["блоков"],
                        "автономен": с["автономность"],
                        "почему_автономность": с["почему_автономность"],
                        "механизм": с.get("механизм")} for с in свои],
            "сюжетов": len(свои),
            "блоков": len(блоки),
            "блоки": блоки,
            "цитаты": [ц for с in свои for ц in с["цитаты"]],
            # что это
            "актор": sorted({с["актор"] for с in свои if с.get("актор")}),
            "бенефициар": sorted({с["бенефициар"] for с in свои if с.get("бенефициар")}),
            "механизм": [с["механизм"] for с in свои if с.get("механизм")],
            # Объём заготовки — объём темы: знаки уникальных отрезков её
            # фрагментов (не блоков: блоки — содержание, фрагменты — объём).
            "знаков": т["знаков"],
            "доля_документа": т["доля_документа"],
            # что можно сделать
            "автономных_сюжетов": sum(1 for с in свои if с["автономность"]),
            "опора_под_практику": [о["что"] for с in свои for о in с["опоры_под_практику"]],
            "опора_под_заберите_с_собой": sorted({и for с in свои for и in с["инструменты"]}),
            # с чем пересекается
            "пересечение": пересечения.get(тема, []),
            # очередь
            "приоритет": приоритет,
            "S": s,
        })

    заготовки.sort(key=lambda з: -з["знаков"])
    return основа, приоритет, заготовки


def main(папка):
    основа, приоритет, список = заготовки(папка)

    # Уровни — из свода У1. Принятые темы есть → У1 обязан был отработать, и
    # реестр без уровней не собирается: контракт выгрузки требует их у каждой
    # заготовки, а молча выпустить заготовку без уровней — та же ошибка, что
    # второй писатель, стирающий уровни (Д-2).
    сведён = os.path.join(папка, "00_уровень_сведён.json")
    if список:
        if not os.path.exists(сведён):
            print("реестр: принятые темы есть, а 00_уровень_сведён.json нет — "
                  "сначала У1 (`о_уровень.py вход` → модель → `о_уровень.py свести`)")
            return 1
        уровни = json.load(open(сведён, encoding="utf-8")).get("уровни") or {}
        нет = [з["тема"] for з in список if з["тема"] not in уровни]
        if нет:
            print(f"реестр: в 00_уровень_сведён.json нет уровней для {', '.join(нет)} — "
                  f"свод У1 устарел, повторите `о_уровень.py свести`")
            return 1
        for з in список:
            з["уровни"] = уровни[з["тема"]]

    # Один набор ключей на оба случая. Раньше ветка «принятых тем нет» писала
    # файл из трёх полей, а обычная — из десяти, и `принятых_тем` существовало
    # ровно в той ветке, где оно всегда ноль.
    with open(os.path.join(папка, "реестр.json"), "w", encoding="utf-8") as f:
        json.dump({**основа, "приоритет": приоритет,
                   "заготовок": len(список), "заготовки": список},
                  f, ensure_ascii=False, indent=2)

    if not список:
        print("реестр: принятых тем нет — заготовок не будет")
        return 0
    print(f'реестр: {len(список)} заготовок по числу принятых тем '
          f'(сюжетов всего {основа["сюжетов_всего"]}), приоритет {приоритет}')
    for з in список:
        ур = ", ".join(str(x) for x in (з.get("уровни") or {}).get("закрытые") or []) or "—"
        метки = [f'сюжетов {з["сюжетов"]}, автономных {з["автономных_сюжетов"]}']
        if з["опора_под_практику"]:
            метки.append(f'практика×{len(з["опора_под_практику"])}')
        if з["опора_под_заберите_с_собой"]:
            метки.append("забрать: " + ", ".join(з["опора_под_заберите_с_собой"]))
        if з["пересечение"]:
            метки.append("общий текст с: " + ", ".join(п["тема"] for п in з["пересечение"]))
        print(f'  ур.{ур:<4} {з["тема"]:<34} {з["блоков"]:>3} бл  {з["знаков"]:>6} зн'
              f'  [{"; ".join(метки)}]')
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
