# Диагноз Б4/Б4т: чем именно плоха цитата, которая не нашлась.
# python3 _скрипты/самопроверка_цитат.py
import sys, os
ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ЗДЕСЬ)      # b4 лежит рядом; путей от cwd здесь нет
import b4_проверка_выжимок as b4

ТЕКСТ = ("Сначала Гуо и другие нашли, что навыки влияют на сети. "
         "Навыки влияния — это умение понимать других на работе. "
         "Позже обнаружилось, что наставничество тоже связано с сетями.")
НОРМ = b4.норм(ТЕКСТ)

СЛУЧАИ = [
    # (цитата, найдена, диагноз)
    ("Навыки влияния — это умение понимать других на работе", True, None),
    ("Сначала Гуо и другие нашли […] наставничество тоже связано с сетями",
     True, None),
    ("Сначала Гуо и другие нашли [….] наставничество тоже", True, None),
    ("Сначала Гуо и другие нашли [-] наставничество тоже", True, None),
    ("Сначала Гуо и другие нашли [—] наставничество тоже", True, None),
    # куски дословны, но в тексте идут в обратном порядке
    ("Навыки влияния — это умение понимать других […] Сначала Гуо и другие нашли",
     False, "куски цитаты переставлены — в тексте они идут в другом порядке"),
    # выдумка — ни один кусок не найден
    ("Этого в тексте нет и никогда не было", False, "недословна"),
    # первый кусок есть, второй выдуман — тоже недословна, не перестановка
    ("Сначала Гуо и другие нашли […] совершенно выдуманный хвост", False, "недословна"),
]

плохо = 0
for ц, ждём_найдена, ждём_диагноз in СЛУЧАИ:
    есть = b4.найдена(ц, НОРМ)
    if есть != ждём_найдена:
        плохо += 1
        print(f"  X найдена={есть}, ждали {ждём_найдена}: {ц[:60]!r}")
        continue
    if not есть:
        диагноз = b4.почему_не_найдена(ц, НОРМ)
        if диагноз != ждём_диагноз:
            плохо += 1
            print(f"  X диагноз {диагноз!r}, ждали {ждём_диагноз!r}: {ц[:60]!r}")

print(f"случаев: {len(СЛУЧАИ)}, расхождений: {плохо}")
sys.exit(1 if плохо else 0)
