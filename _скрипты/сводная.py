def сюжеты_внутри(з):
    """Что лежит в заготовке — по строке на сюжет, с уровнем и пометкой
    автономности. «6 сюжетов» аналитику ничего не говорит, а «конвейер сбора
    отзывов · глаголы вместо характеристик · границы метода» — говорит."""
    строки = []
    for с in з.get("сюжеты") or []:
        if isinstance(с, str):            # старый реестр: только имя
            строки.append(с); continue
        метка = "" if с.get("автономен") else " [не автономен]"
        строки.append(f'{с["название"]}{метка}')
    return "\n".join(строки)


def строка_заготовки(з):
    """Одна строка листа «Заготовки»: строка = тема."""
    закрытые = (з.get("уровни") or {}).get("закрытые")
    пересеч = ", ".join(п["тема"] for п in з.get("пересечение") or [])
    return [з["папка"], з["материал"], з["тема"], з.get("роль_в_материале") or "—",
            з.get("сюжетов"), з.get("блоков"),
            уровни_строкой(закрытые), з["знаков"], з.get("доля_документа"),
            f'{з.get("автономных_сюжетов")} из {з.get("сюжетов")}',
            сюжеты_внутри(з),
            "; ".join(з["опора_под_практику"]),
            ", ".join(з["опора_под_заберите_с_собой"]),
            пересеч, з["приоритет"]]


_УПРАВЛЯЮЩИЕ = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f]")


def чисто(v):
    """Excel не принимает управляющие символы, и openpyxl роняет всю сборку на
    одной ячейке. Метаданные PDF их приносят: у «Мэтт Шумер про ИИ.docx» в поле
    title лежит «Microsoft Word - ˘˛$˚ ˝&˘/…» с байтами 0x01. Вырезаем их из
    строк — данные остаются, сводная собирается."""
    return _УПРАВЛЯЮЩИЕ.sub("", v) if isinstance(v, str) else v


def xlsx(корень, строки, незавершённые, заготовки=(), атрибуты=(), вход=(),
         авторы=()):
    """Тот же набор данных, что в .md. Считаемые итоги — формулами, чтобы при
    ручной правке строк шапка пересчитывалась сама."""
    _модуль("общее", "общее.py").библиотека("openpyxl", "сводная")
    from openpyxl import Workbook
    from openpyxl.styles import Font, Alignment, PatternFill, Border, Side
    from openpyxl.utils import get_column_letter

    шрифт = "Arial"
    жирный = Font(name=шрифт, bold=True, size=11)
    обычный = Font(name=шрифт, size=10)
    белый_жирный = Font(name=шрифт, bold=True, size=10, color="FFFFFF")
    заливка_шапки = PatternFill("solid", fgColor="1F3864")
    принят = PatternFill("solid", fgColor="E2EFDA")
    отклонён = PatternFill("solid", fgColor="FCE4E4")
    ждёт = PatternFill("solid", fgColor="FFF2CC")   # решение модератора не принято
    в_работе = PatternFill("solid", fgColor="EDEDED")   # балл не считается (o4.В_РАБОТЕ)
    рамка = Border(*[Side(style="thin", color="D0D0D0")] * 4)

    wb = Workbook()
    ws = wb.active
    ws.title = "Сводная"

    ws["A1"] = "Сводная по материалам"; ws["A1"].font = Font(name=шрифт, bold=True, size=14)
    ws["A2"] = ("Зелёная строка прошла порог, жёлтая не добрала ровно балл, красная не прошла, серая — балл не считается (нет строки справочника, B или D). "
                "Колонка «Что решило» — одна фраза от того шага, который решил дело. "
                "Полные обоснования — в отбор.md внутри папки материала.")
    ws["A2"].font = Font(name=шрифт, size=10, italic=True, color="606060")

    первая = 6                      # первая строка данных
    последняя = первая + len(строки) - 1
    # Считаем МАТЕРИАЛЫ, а не строки. Строка — это тема, и «принято 7» при
    # четырёх принятых материалах вводит в заблуждение: у PMI три принятые темы,
    # и в счёте тем он весит втрое. Решение принимается по материалу.
    # Значениями, а не формулами: формула в файле, который никто не пересчитывал,
    # показывает пустую ячейку, и счётчика будто нет.
    все_папки = {с["папка"] for с in строки}
    принятые = {с["папка"] for с in строки if с["вердикт"] == "✅"}
    пограничные = {с["папка"] for с in строки
                   if с["вердикт"] == _скоринг.ПОГРАНИЧНЫЙ}
    ws["A3"] = "Материалов принято:"; ws["A3"].font = обычный
    ws["C3"] = len(принятые)
    ws["D3"] = "отклонено:"; ws["D3"].font = обычный
    ws["E3"] = len(все_папки - принятые)
    ws["F3"] = "пограничных:"; ws["F3"].font = обычный
    ws["G3"] = len(пограничные - принятые)
    ws["H3"] = "разобрано всего:"; ws["H3"].font = обычный
    ws["I3"] = len(все_папки)
    ws["J3"] = "в работе:"; ws["J3"].font = обычный
    ws["K3"] = len(незавершённые)
    for c in ("C3", "E3", "G3", "I3", "K3"):
        ws[c].font = жирный

    for i, (имя, ширина) in enumerate(КОЛОНКИ, 1):
        c = ws.cell(row=первая - 1, column=i, value=имя)
        c.font = белый_жирный; c.fill = заливка_шапки
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        ws.column_dimensions[get_column_letter(i)].width = ширина

    ключи = ["папка", "материал", "объём", "тема", "роль", "A", "B", "S", "D",
             "балл", "вердикт", "что_решило", "уровень", "жанр", "адресат",
             "источник", "флаги"]
    for r, с in enumerate(строки, первая):
        for i, к in enumerate(ключи, 1):
            v = с.get(к)
            c = ws.cell(row=r, column=i, value=("-" if v is None else чисто(v)))
            c.font = обычный; c.border = рамка
            c.alignment = Alignment(vertical="top",
                                    wrap_text=к in ("материал", "флаги", "тема",
                                                    "что_решило"),
                                    horizontal="center" if к in ("A","B","S","D","балл","вердикт","уровень","объём","роль") else "left")
            # Цвет — по вердикту, и только по нему. До 17 сентября жёлтый
            # выбирался по баллу, то есть правило «что такое пограничный» было
            # записано дважды: в цвете здесь и в голове у читающего. Теперь
            # состояние называет `o4_скоринг`, а сводная его лишь показывает —
            # один источник правды, как у порога и у шкалы.
            c.fill = (принят if с["вердикт"] == "✅"
                      else ждёт if с["вердикт"] == _скоринг.ПОГРАНИЧНЫЙ
                      else в_работе if с["вердикт"] == _скоринг.В_РАБОТЕ
                      else отклонён)

    ws.freeze_panes = f"A{первая}"
    if строки:
        ws.auto_filter.ref = f"A{первая-1}:{get_column_letter(len(КОЛОНКИ))}{последняя}"

    if заготовки:
        wz = wb.create_sheet("Заготовки")
        for i, (имя, ширина) in enumerate(КОЛОНКИ_ЗАГОТОВОК, 1):
            c = wz.cell(row=1, column=i, value=имя)
            c.font = белый_жирный; c.fill = заливка_шапки
            c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            wz.column_dimensions[get_column_letter(i)].width = ширина
        for r, з in enumerate(заготовки, 2):
            значения = строка_заготовки(з)
            for i, v in enumerate(значения, 1):
                c = wz.cell(row=r, column=i, value=(чисто(v) if v not in ("", None) else "—"))
                c.font = обычный; c.border = рамка
                c.alignment = Alignment(vertical="top",
                                        wrap_text=i in (2, 3, 10, 11, 12, 13),
                                        horizontal="center" if i in (4, 5, 6, 7, 8, 9) else "left")
        wz.freeze_panes = "A2"
        wz.auto_filter.ref = (f"A1:{get_column_letter(len(КОЛОНКИ_ЗАГОТОВОК))}"
                              f"{len(заготовки) + 1}")

    if незавершённые:
        ws2 = wb.create_sheet("В работе")
        for i, (имя, ширина) in enumerate([("Папка", 22), ("Материал", 46), ("Объём", 34),
                                           ("Пройдено", 20), ("Следующий шаг", 20)], 1):
            c = ws2.cell(row=1, column=i, value=имя)
            c.font = белый_жирный; c.fill = заливка_шапки
            ws2.column_dimensions[get_column_letter(i)].width = ширина
        for r, кортеж in enumerate(незавершённые, 2):
            for i, v in enumerate(кортеж, 1):
                c = ws2.cell(row=r, column=i, value=чисто(v) if v is not None else "—")
                c.font = обычный; c.border = рамка
        ws2.freeze_panes = "A2"

    if атрибуты:
        # Строка на материал, колонки — из атрибуты_спецификация.xlsx. Пустая
        # ячейка значит, что поле ещё не собирается: шага опознания нет, файла
        # загрузки нет. Прятать такие колонки нельзя — по ним видно, сколько
        # работы осталось до полной карточки материала.
        wa = wb.create_sheet("Атрибуты")
        wa["A1"] = "Атрибуты материалов"
        wa["A1"].font = Font(name=шрифт, bold=True, size=14)
        собрано = sum(1 for имя, _ in _атрибуты.КОЛОНКИ
                      if any(с.get(имя) not in (None, "", []) for с in атрибуты))
        wa["A2"] = (f"Строка = материал. Колонок {len(_атрибуты.КОЛОНКИ)}, "
                    f"из них заполняется {собрано}. Пустой столбец — поле, которое "
                    f"пайплайн пока не собирает.")
        wa["A2"].font = Font(name=шрифт, size=10, italic=True, color="606060")

        for i, (имя, ширина) in enumerate(_атрибуты.КОЛОНКИ, 1):
            c = wa.cell(row=4, column=i, value=имя)
            c.font = белый_жирный; c.fill = заливка_шапки
            c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            wa.column_dimensions[get_column_letter(i)].width = ширина
            # начало нового слоя помечается: иначе сорок колонок читаются сплошняком
            if имя in _атрибуты.ГРАНИЦЫ:
                c.value = f"{_атрибуты.ГРАНИЦЫ[имя]}: {имя}"
        for r, с in enumerate(атрибуты, 5):
            for i, (имя, _) in enumerate(_атрибуты.КОЛОНКИ, 1):
                v = с.get(имя)
                c = wa.cell(row=r, column=i, value=("" if v in (None, []) else чисто(v)))
                c.font = обычный; c.border = рамка
                c.alignment = Alignment(vertical="top",
                                        wrap_text=имя in ("file_name", "title", "publisher",
                                                          "author_name", "industry",
                                                          "key_concepts", "строка_атрибуции"))
                if v in (None, "", []):
                    c.fill = ждёт
        wa.freeze_panes = "C5"
        wa.auto_filter.ref = (f"A4:{get_column_letter(len(_атрибуты.КОЛОНКИ))}"
                              f"{len(атрибуты) + 4}")

    # Лист создаётся всегда, в том числе пустым: пустой значит «ни один автор
    # пока не опознан», и это состояние, о котором надо знать. Спрятанный лист
    # значил бы «такого среза не бывает» — то же правило, по которому на листе
    # «Атрибуты» видны несобираемые колонки.
    if True:
        # Строка = автор справочника. Не «автор материала»: в справочник попадают
        # только опознанные — те, у кого найден адрес. Автор без адреса строки не
        # имеет и виден на листе «Атрибуты», в колонке `автор_опознан`.
        wt = wb.create_sheet("Авторы")
        wt["A1"] = "Авторы"
        wt["A1"].font = Font(name=шрифт, bold=True, size=14)
        подтверждено = sum(1 for а in авторы if _авторы.норм(а.get("статус")) == _авторы.норм("подтверждён"))
        wt["A2"] = ((f"Строка = опознанный автор. Всего {len(авторы)}, "
                     f"из них подтверждённых {подтверждено}. ")
                    if авторы else
                    ("Ни один автор пока не опознан: шаг И3 по материалам не "
                     "запускался либо адресов не нашлось. "))
        wt["A2"].value += ("Опознание идёт по адресу — ORCID, страница у издателя, "
                           "канал, личный домен; по имени авторы не сличаются "
                           "никогда. Автор без адреса строки не имеет и виден на "
                           "листе «Атрибуты», в колонке «автор_опознан».")
        wt["A2"].font = Font(name=шрифт, size=10, italic=True, color="606060")
        for i, (имя, ширина) in enumerate(КОЛОНКИ_АВТОРОВ, 1):
            c = wt.cell(row=4, column=i, value=имя)
            c.font = белый_жирный; c.fill = заливка_шапки
            c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            wt.column_dimensions[get_column_letter(i)].width = ширина
        for r, а in enumerate(авторы, 5):
            for i, (имя, _) in enumerate(КОЛОНКИ_АВТОРОВ, 1):
                v = а.get(имя)
                c = wt.cell(row=r, column=i, value=("" if v in (None, []) else чисто(v)))
                c.font = обычный; c.border = рамка
                c.alignment = Alignment(vertical="top",
                                        wrap_text=имя in ("описание", "почему_признанность",
                                                          "адрес", "автор", "где проверено"))
                if v in (None, "", []):
                    c.fill = ждёт
        wt.freeze_panes = "C5"
        wt.auto_filter.ref = (f"A4:{get_column_letter(len(КОЛОНКИ_АВТОРОВ))}"
                              f"{len(авторы) + 4}")

    if вход:
        # Очередь: файлы в исходниках, у которых ещё нет папки материала.
        # Канал — папка верхнего уровня, она же acquisition. Темы здесь нет
        # намеренно: тему определяет разбор, а не раскладка по папкам.
        wv = wb.create_sheet("Входящие")
        ждут = sum(1 for х in вход if х[4] == "ожидает разбора")
        wv["A1"] = "Входящие"
        wv["A1"].font = Font(name=шрифт, bold=True, size=14)
        wv["A2"] = (f"Файлов без папки материала: {len(вход)}, из них готовы к разбору "
                    f"{ждут}. Канал = папка в исходниках.")
        wv["A2"].font = Font(name=шрифт, size=10, italic=True, color="606060")
        for i, (имя, ширина) in enumerate([("Файл", 74), ("Канал", 14), ("МБ", 8),
                                           ("Формат", 10), ("Статус", 30)], 1):
            c = wv.cell(row=4, column=i, value=имя)
            c.font = белый_жирный; c.fill = заливка_шапки
            c.alignment = Alignment(horizontal="center", vertical="center")
            wv.column_dimensions[get_column_letter(i)].width = ширина
        for r, кортеж in enumerate(вход, 5):
            for i, v in enumerate(кортеж, 1):
                c = wv.cell(row=r, column=i, value=чисто(v))
                c.font = обычный; c.border = рамка
                c.alignment = Alignment(vertical="top", wrap_text=(i == 1),
                                        horizontal="center" if i in (2, 3, 4) else "left")
            if кортеж[4] != "ожидает разбора":
                wv.cell(row=r, column=5).fill = ждёт
        wv.freeze_panes = "A5"
        wv.auto_filter.ref = f"A4:E{len(вход) + 4}"

    wb.save(os.path.join(корень, "0_сводная.xlsx"))


