def стадия(папка):
    достигнуто = "—"
    # Без живых кандидатов О2 и О3 не зовутся: их файлы — не «следующая
    # стадия», а законный пропуск (тот же список, что у `входы.УСЛОВНЫЕ_О4`).
    пропуск = set() if _входы.живые_кандидаты(папка) else set(_входы.УСЛОВНЫЕ_О4)
    for файл, имя in СТАДИИ:
        if файл in пропуск:
            continue
        if os.path.exists(os.path.join(папка, файл)):
            достигнуто = имя
        else:
            return достигнуто, имя
    return достигнуто, None


# Файл `решение_модератора.json` удалён 17 сентября вместе с полем «в саммари».
# Он был единственным местом, где значение ставил человек, и заводился под ветку
# суммаризации — а ветку не строят. Заготовки создавались у всех 93 материалов и
# ни одна не заполнялась: поле без потребителя, только на диске, а не в промте
# (объявление без потребителя). Решение оценщика, из которого будет копиться золотой
# набор, писать сюда не станем: связь «материал → вывод оценщика» должна жить
# там, где её читают, а не в файле, который никто не открывает.


def уровни_строкой(закрытые):
    """Уровни заготовки — НАБОР закрытых, а не диапазон.

    Диапазон «мин–макс» обещал уровни, которых может не быть: сюжеты на 1 и 3
    давали «1–3» при отсутствующей двойке. Набор говорит ровно то, что есть:
    «1, 3» — значит выйдут две единицы, первого и третьего уровня.

    Прочерк у неотобранных тем — не пропуск данных: уровни ставит шаг У1 только
    принятым темам, и платить за отсеянные незачем."""
    if not закрытые:
        return "—"
    return ", ".join(str(у) for у in закрытые)


def читать(папка, имя):
    """Нет файла — None («ещё не дошёл»); есть, но не читается — отказ с именем,
    а не строка «в работе»."""
    п = os.path.join(папка, имя)
    if not os.path.exists(п):
        return None
    try:
        return json.load(open(п, encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError) as сбой:
        raise SystemExit(f"сводная: {п} не читается: {сбой} — разбор сломан, сводная по нему не собирается")


