# -*- coding: utf-8 -*-
"""
Сравнение двух версий разбора одного материала — или двух корней целиком.
Вход:  две папки материала — текущая («стало») и та, с чем сравниваем («было»),
       либо два корня с папками материалов: сравниваются одноимённые папки
Выход: таблица «было — стало» в stdout (markdown, можно вставлять в отчёт)

  python3 _скрипты/сравнить_разбор.py материалы/02_техреспублика
  python3 _скрипты/сравнить_разбор.py материалы/02_техреспублика _до_правок/02_техреспублика
  python3 _скрипты/сравнить_разбор.py материалы материалы_old        # два корня

С одним аргументом «было» ищется в `_до_правок/<имя папки>`.

Зачем это нужно. Разницу между версиями разбора нельзя писать по памяти: одна
строка из соседнего материала — и отчёт врёт, а проверить его дорого. Здесь
разницу считает код, и взять чужой материал ему неоткуда.

Три состояния строки, а не два. «=» — совпало; «←» — разошлось; «∅» — поля
нет ни в одной из версий. До 17 сентября отсутствующее поле читалось как
`None` с обеих сторон и попадало в «совпало»: два поля из девяти (`источник.тип`
и `уровень`) не существовали ни в одной из 93 карт и всегда печатались как
совпавшие. Поле, которого нет нигде, — не свидетельство
устойчивости, а мёртвая строка сравнения, и она считается отдельно.

Скрипт ничего не меняет и никуда не пишет, кроме stdout.
"""
import sys, os, json

НЕТ = object()          # поля нет в файле — это не None и не пустая строка


def _по_пути(данные, путь):
    """Значение по пути `а.б.в`; `НЕТ`, если какого-то ключа нет."""
    тек = данные
    for ключ in путь.split("."):
        if not isinstance(тек, dict) or ключ not in тек:
            return НЕТ
        тек = тек[ключ]
    return тек


def _уровни_заготовки(з):
    у = з.get("уровни", НЕТ)
    if у is НЕТ:
        return НЕТ
    if not у:
        return None
    закрытые = у.get("закрытые") if isinstance(у, dict) else у
    return ",".join(str(x) for x in sorted(закрытые or [])) or None


# Поля карты. Список — то, что П2 и И1 сегодня отдают в карту; поле, ушедшее из
# контракта, здесь не держится «на всякий случай» — оно попадёт в «∅».
ПОЛЯ_МАТЕРИАЛА = [
    ("жанр",                    "жанр.тип"),
    ("зависимость от продукта", "зависимость_от_продукта.есть"),
    ("адресат",                 "адресат.тег"),
    ("название",                "источник.название"),
    ("издание",                 "источник.издание"),
    ("тип материала",           "источник.material_type"),
    ("отрасль материала",       "отрасль_материала"),
    ("ключевых понятий",        lambda к: len(к["key_concepts"]) if "key_concepts" in к else НЕТ),
    ("тем в тексте",            lambda к: len(к["темы"]) if "темы" in к else НЕТ),
    ("блоков по темам",         lambda к: sum(т.get("блоков", 0) for т in к["темы"]) if "темы" in к else НЕТ),
    ("чанков",                  "материал.чанков"),
    ("знаков содержательных",   "материал.знаков_содержательных"),
]

# Поля строки итога. Длинные тексты сравниваются длиной — см. `ДЛИНОЙ`.
ПОЛЯ_СТРОКИ = ["A", "B", "S", "D", "балл", "вердикт", "остановка", "что_решило",
               "роль_в_материале", "почему_B", "почему_D", "флаги"]
ДЛИНОЙ = ["обоснование", "комментарий"]

ПОЛЯ_ЗАГОТОВКИ = [
    ("сюжетов",   "сюжетов"),
    ("блоков",    "блоков"),
    ("приоритет", "приоритет"),
    ("уровни",    _уровни_заготовки),
]


def взять(данные, как):
    if данные is None:
        return НЕТ
    if callable(как):
        return как(данные)
    return _по_пути(данные, как)


def читать(папка, имя):
    п = os.path.join(папка, имя)
    if not os.path.exists(п):
        return None
    try:
        return json.load(open(п, encoding="utf-8"))
    except Exception as e:
        return {"_ошибка_чтения": str(e)}


def ячейка(v):
    if v is НЕТ:
        return "∅"
    if v is None:
        return "—"
    if isinstance(v, bool):
        return "да" if v else "нет"
    if isinstance(v, (list, tuple)):
        v = "; ".join(str(x) for x in v) or "—"
    s = str(v).replace("|", "\\|").replace("\n", " ").strip()
    return s if len(s) <= 90 else s[:87] + "…"


class Счёт:
    def __init__(self):
        self.расхождений = 0
        self.мёртвых = 0

    def строка(self, что, было, стало):
        if было is НЕТ and стало is НЕТ:
            self.мёртвых += 1
            знак = " ∅ поля нет ни в одной версии"
        elif было == стало:
            знак = ""
        else:
            self.расхождений += 1
            знак = " ←"
        return f"| {что} | {ячейка(было)} | {ячейка(стало)} |{знак}"


def сравнить_материал(к_было, к_стало, счёт):
    строки = ["| | было | стало |", "|---|---|---|"]
    for имя, как in ПОЛЯ_МАТЕРИАЛА:
        строки.append(счёт.строка(имя, взять(к_было, как), взять(к_стало, как)))
    return строки


def темы(итог):
    """Строки итога по темам, ключ — topic_id (или «НЕ ОПРЕДЕЛЕНО»)."""
    if not итог:
        return {}
    return {с.get("тема") or "—": с for с in итог.get("строки", [])}


def сравнить_темы(и_было, и_стало, счёт):
    a, b = темы(и_было), темы(и_стало)
    все = list(dict.fromkeys(list(a) + list(b)))
    блоки = []
    for t in все:
        сa, сb = a.get(t), b.get(t)
        шапка = f"\n**{t}**"
        if сa is None:
            шапка += "  — строки не было"
            счёт.расхождений += 1
        elif сb is None:
            шапка += "  — строка исчезла"
            счёт.расхождений += 1
        блоки += [шапка, "", "| | было | стало |", "|---|---|---|"]
        for поле in ПОЛЯ_СТРОКИ:
            блоки.append(счёт.строка(поле, взять(сa, поле), взять(сb, поле)))
        for поле in ДЛИНОЙ:
            la, lb = взять(сa, поле), взять(сb, поле)
            la = la if la is НЕТ else len(la or "")
            lb = lb if lb is НЕТ else len(lb or "")
            блоки.append(счёт.строка(f"{поле}, знаков", la, lb))
    return блоки


def сравнить_заготовки(р_было, р_стало, счёт):
    блоки = ["| | было | стало |", "|---|---|---|",
             счёт.строка("заготовок", взять(р_было, "заготовок"), взять(р_стало, "заготовок")),
             счёт.строка("принятых тем", взять(р_было, "принятых_тем"), взять(р_стало, "принятых_тем"))]
    a = {з.get("тема"): з for з in (р_было or {}).get("заготовки") or []}
    b = {з.get("тема"): з for з in (р_стало or {}).get("заготовки") or []}
    for t in dict.fromkeys(list(a) + list(b)):
        зa, зb = a.get(t), b.get(t)
        шапка = f"\n**заготовка {t}**"
        if зa is None:
            шапка += "  — не было"
            счёт.расхождений += 1
        elif зb is None:
            шапка += "  — исчезла"
            счёт.расхождений += 1
        блоки += [шапка, "", "| | было | стало |", "|---|---|---|"]
        for имя, как in ПОЛЯ_ЗАГОТОВКИ:
            блоки.append(счёт.строка(имя, взять(зa, как), взять(зb, как)))
    return блоки


def сравнить_папки(путь_стало, путь_было):
    """Одна папка против другой. Возвращает (расхождений, мёртвых полей)."""
    print("# Сравнение разбора\n")
    print(f"- стало: `{путь_стало}`")
    print(f"- было:  `{путь_было}`\n")

    к_было, к_стало = читать(путь_было, "04_карта.json"), читать(путь_стало, "04_карта.json")
    и_было, и_стало = читать(путь_было, "13_итог.json"), читать(путь_стало, "13_итог.json")
    р_было, р_стало = читать(путь_было, "реестр.json"), читать(путь_стало, "реестр.json")

    for имя, а, б in (("04_карта.json", к_было, к_стало), ("13_итог.json", и_было, и_стало),
                      ("реестр.json", р_было, р_стало)):
        for где, v in (("было", а), ("стало", б)):
            if v is None:
                print(f"! нет `{имя}` в версии «{где}» — его строки показаны как ∅\n")

    счёт = Счёт()
    print("## Материал\n")
    print("\n".join(сравнить_материал(к_было, к_стало, счёт)))
    print("\n## Темы")
    print("\n".join(сравнить_темы(и_было, и_стало, счёт)))
    print("\n## Заготовки\n")
    print("\n".join(сравнить_заготовки(р_было, р_стало, счёт)))

    print(f"\n---\n\nРасхождений по сравниваемым полям: **{счёт.расхождений}**; "
          f"полей, которых нет ни в одной версии: **{счёт.мёртвых}** "
          f"(в «совпало» не входят).")
    if set(темы(и_было)) != set(темы(и_стало)):
        print("\nВнимание: набор тем в таблице различается — сравнивайте построчно, "
              "а не по числу строк.")
    return счёт.расхождений, счёт.мёртвых


def _это_корень(путь):
    """Корень — папка без файлов разбора, но с подпапками."""
    return (os.path.isdir(путь)
            and not any(os.path.exists(os.path.join(путь, ф))
                        for ф in ("04_карта.json", "13_итог.json", "00_мета.json"))
            and any(os.path.isdir(os.path.join(путь, d)) for d in os.listdir(путь)))


def _папка(аргумент, кто="сравнить_разбор"):
    """Относительный путь — от корня проекта, потом от cwd."""
    import importlib.util
    сп = importlib.util.spec_from_file_location(
        "общее", os.path.join(os.path.dirname(os.path.abspath(__file__)), "общее.py"))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м)
    return м.корень_материалов(аргумент, кто)


def main(путь_стало, путь_было=None):
    путь_стало = _папка(путь_стало)
    если_нет = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                            "_до_правок", os.path.basename(os.path.normpath(путь_стало)))
    путь_было = путь_было or если_нет
    if not os.path.isdir(путь_было) and os.path.isabs(путь_было):
        raise SystemExit(f"нечего сравнивать: нет папки {путь_было}\n"
                         f"  «было» ищется в _до_правок/<имя папки> или задаётся вторым аргументом")
    путь_было = _папка(путь_было)

    if _это_корень(путь_стало) and _это_корень(путь_было):
        общие = sorted(set(os.listdir(путь_стало)) & set(os.listdir(путь_было)))
        общие = [d for d in общие if not d.startswith(".")
                 and os.path.isdir(os.path.join(путь_стало, d))]
        if not общие:
            raise SystemExit(f"в корнях нет одноимённых папок: {путь_стало} и {путь_было}")
        только_стало = sorted(set(os.listdir(путь_стало)) - set(общие) - {"0_сводная.xlsx"})
        только_было = sorted(set(os.listdir(путь_было)) - set(общие) - {"0_сводная.xlsx"})
        итого = []
        for d in общие:
            р, м = сравнить_папки(os.path.join(путь_стало, d), os.path.join(путь_было, d))
            итого.append((d, р, м))
            print("\n\n")
        print("# Сводка по корням\n")
        print("| папка | расхождений | мёртвых полей |")
        print("|---|---|---|")
        for d, р, м in итого:
            print(f"| {d} | {р} | {м} |")
        if только_стало:
            print(f"\nтолько в «стало»: {', '.join(x for x in только_стало if not x.startswith('.'))}")
        if только_было:
            print(f"только в «было»: {', '.join(x for x in только_было if not x.startswith('.'))}")
        return 0

    сравнить_папки(путь_стало, путь_было)
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    sys.exit(main(*sys.argv[1:3]))
