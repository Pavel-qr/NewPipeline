# -*- coding: utf-8 -*-
"""
Канон уровней: матрица «тема × уровень».

  python3 _скрипты/уровни.py                      — что в каноне
  python3 _скрипты/уровни.py relationship_networks — столбец темы целиком

Файл `_канон/уровни_темы.xlsx` — четыре листа, по одному на уровень: темы в
столбцах, параметры в строках. Чтение по столбцу даёт полное описание уровня для
одной темы: ролевой ракурс, ведущие W этого уровня, раскрытые под тему, что
входит в уровень, результат в поведении и **чего не должно быть** — границы с
соседними уровнями в обе стороны.

Зачем отдельный файл, а не `уровни.json`. Там платформенная строка про уровень
вообще: диапазоны навыка, когнитивный фокус, типичная роль. Здесь — уровень под
конкретную тему. Разные размерности, и класть их вместе значит потерять обе.

Почему уровень нельзя поставить раньше темы. Ячейка открывается парой «тема ×
уровень», и без темы её просто нет. Поэтому уровень ушёл из П2 (она тем не
видит) на отдельный шаг после отбора, где тема уже принята. Пока он стоял в П2,
модель отвечала на вопрос без ответа — и воспроизводимость была 54–72% против
94–100% у наблюдаемых полей.

Лист `topics (индикаторы)` из исходной книги в канон НЕ перенесён намеренно: это
устаревшая копия канона тем, в ней у `technology_business_synergy` живы ссылки на
несуществующую тему `disrupt`. Канон тем один — 
`_канон/topics_индикаторы.xlsx`.
"""
import os, sys, json

def _библиотека(модуль, кто):
    import importlib.util as _iu
    сп = _iu.spec_from_file_location("общее", os.path.join(os.path.dirname(os.path.abspath(__file__)), "общее.py"))
    м = _iu.module_from_spec(сп); сп.loader.exec_module(м)
    return м.библиотека(модуль, кто)


ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ЗДЕСЬ)
ИМЯ = "уровни_темы.xlsx"
УРОВНИ = (1, 2, 3, 4)
ГРАНИЦА = "Чего не должно быть"


def найти_таблицу():
    из_среды = os.environ.get("КАНОН_УРОВНИ")
    кандидаты = ([из_среды] if из_среды else []) + [
        os.path.join(КОРЕНЬ, "_канон", ИМЯ),
        os.path.join(КОРЕНЬ, ИМЯ),
    ]
    for п in кандидаты:
        if п and os.path.exists(п):
            return п
    raise SystemExit("не найден канон уровней " + ИМЯ + "; искал:\n  "
                     + "\n  ".join(str(x) for x in кандидаты))


def читать(путь=None):
    """{уровень: {topic_id: {параметр: значение}}}."""
    openpyxl = _библиотека("openpyxl", "уровни")
    кн = openpyxl.load_workbook(путь or найти_таблицу())
    канон = {}
    for уровень in УРОВНИ:
        лист = f"Уровень {уровень}"
        if лист not in кн.sheetnames:
            raise SystemExit(f"в каноне уровней нет листа «{лист}»")
        ws = кн[лист]
        ид = {c: ws.cell(2, c).value for c in range(2, ws.max_column + 1)
              if ws.cell(2, c).value}
        параметры = {r: str(ws.cell(r, 1).value).strip()
                     for r in range(3, ws.max_row + 1) if ws.cell(r, 1).value}
        канон[уровень] = {
            тема: {имя: (ws.cell(r, c).value or None) for r, имя in параметры.items()}
            for c, тема in ид.items()}
    return канон


def столбец(тема, канон=None):
    """Все четыре уровня одной темы — это и есть вход модельного шага У1."""
    канон = канон or читать()
    отсутствуют = [у for у in УРОВНИ if тема not in канон[у]]
    if отсутствуют:
        raise SystemExit(f"темы «{тема}» нет на листах уровней {отсутствуют}")
    return {у: канон[у][тема] for у in УРОВНИ}


def темы(канон=None):
    канон = канон or читать()
    return sorted(set.intersection(*[set(канон[у]) for у in УРОВНИ]))


if __name__ == "__main__":
    канон = читать()
    if len(sys.argv) > 1:
        print(json.dumps(столбец(sys.argv[1], канон), ensure_ascii=False, indent=2))
    else:
        общие = темы(канон)
        print(f"канон уровней: {найти_таблицу()}")
        print(f"уровней {len(УРОВНИ)}, тем {len(общие)}")
        for у in УРОВНИ:
            свои = канон[у]
            пример = next(iter(свои.values()))
            границы = sum(1 for т in свои.values() if т.get(ГРАНИЦА))
            print(f"  уровень {у}: тем {len(свои)}, параметров {len(пример)}, "
                  f"с границей «чего не должно быть» — {границы}")
        print("темы:", ", ".join(общие))
